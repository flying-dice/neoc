/**
 * Types for the backend's ambient API (the global `app`: `app.sendRequest`, `app.onRequest`, `app.sendNotification`,
 * `app.onNotification`): one module of types per app it knows, its own (`types/<id>.luau`) and each it depends on
 * (`types/<id>.luau`, its public methods). Nothing here runs, and the backend works the same without it: the host's
 * bus holds every request and notification to the app's contract. The types are for annotations:
 *
 *     local notes = require("../types/notes")
 *     app.onRequest("add", function(params: notes.AddParams, ctx: notes.Context): notes.AddResult ... end)
 */
import { paramsObject, pascal, type Contract, type Method, type Schema } from './contract.ts'
import type { Dependency } from './emit-ts.ts'

export const LUAU_KEYWORDS = new Set([
  'and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'if', 'in', 'local', 'nil', 'not', 'or',
  'repeat', 'return', 'then', 'true', 'until', 'while'
])

export function luauString(s: string): string {
  let out = '"'
  for (const ch of s) {
    const code = ch.codePointAt(0) as number
    if (ch === '\\') out += '\\\\'
    else if (ch === '"') out += '\\"'
    else if (ch === '\n') out += '\\n'
    else if (ch === '\r') out += '\\r'
    else if (ch === '\t') out += '\\t'
    else if (code < 0x20 || code === 0x7f) out += `\\${code}`
    else out += ch
  }
  return `${out}"`
}

const luauDoc = (text: string | undefined, indent: string): string =>
  text === undefined ? '' : `${text.split(/\r?\n/).map((line) => (line === '' ? `${indent}---` : `${indent}--- ${line}`)).join('\n')}\n`

const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/
/** A field name as a Luau table writes it: bare, or `["end"]`. */
const key = (name: string): string => (IDENTIFIER.test(name) && !LUAU_KEYWORDS.has(name) ? name : `[${luauString(name)}]`)

const optional = (type: string): string => (type.endsWith('?') ? type : /^[\w.]+$/.test(type) ? `${type}?` : `(${type})?`)

/** The Luau type of a schema; `prefix` names another app's types (`App1_Item`): Luau has no namespaces. */
export function luauType(schema: Schema, prefix = ''): string {
  switch (schema.kind) {
    case 'string':
      return schema.enum ? schema.enum.map(luauString).join(' | ') : 'string'
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'nil'
    case 'array':
      return `{ ${luauType(schema.items, prefix)} }`
    case 'object': {
      const fields = Object.entries(schema.properties).map(([name, property]) => {
        const type = luauType(property, prefix)
        return `${key(name)}: ${schema.required.includes(name) ? type : optional(type)}`
      })
      return fields.length === 0 ? '{ [string]: never }' : `{ ${fields.join(', ')} }`
    }
    case 'ref':
      return `${prefix}${schema.name}`
    case 'nullable':
      return optional(luauType(schema.inner, prefix))
  }
}

const docOf = (m: Method): string | undefined => [m.summary, m.description].filter((t) => t !== undefined).join('\n\n') || undefined

/** A module of an app's types: its components, and `<Method>Params` / `<Request>Result` for the methods given. */
function typesModule(header: string, contract: Contract, methods: Method[]): string {
  const out: string[] = []
  out.push('--!strict')
  out.push(header)
  out.push('')
  out.push('--- Who is calling (the page, another app, an agent) and when.')
  out.push('export type Context = vos_app_Context')
  out.push('')
  for (const [name, schema] of Object.entries(contract.components)) out.push(`${luauDoc(schema.description, '')}export type ${name} = ${luauType(schema)}`)
  for (const m of methods) {
    const doc = luauDoc(docOf(m), '')
    if (m.params.length > 0) out.push(`${doc}export type ${pascal(m.name)}Params = ${luauType(paramsObject(m))}`)
    if (m.kind === 'request') out.push(`${m.params.length > 0 ? '' : doc}export type ${pascal(m.name)}Result = ${luauType(m.result)}`)
  }
  out.push('')
  out.push('return {}')
  out.push('')
  return out.join('\n')
}

/** `types/<id>.luau`: this app's types, every method of its contract. */
export function emitLuau(contract: Contract, source: string, appId = 'app'): string {
  return typesModule(
    `-- GENERATED by @vos/vite-plugin-v2 from ${source}: do not edit. The types of ${appId}'s contract: nothing runs here.`,
    contract,
    [...contract.requests, ...contract.notifications]
  )
}

/** `types/<id>.luau` of an app this one depends on: the types of its public methods. */
export function emitDependencyLuau(dependency: Dependency): string {
  const { id, contract } = dependency
  return typesModule(
    `-- GENERATED by @vos/vite-plugin-v2: do not edit. The types of ${id}, as this app's backend depends on it: nothing runs here.`,
    contract,
    [...contract.requests, ...contract.notifications].filter((m) => !m.private)
  )
}
