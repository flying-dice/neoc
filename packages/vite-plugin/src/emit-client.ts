/**
 * The typed client, from the definition: the `@<app id>/rpc` module of the app's project ([`rpcModule`]). The app's page is a normal Vite
 * page; the host's bridge script (`/apps/bridge.js`, injected into its `index.html` by the build) defines the global
 * `vos`, and this module turns it into one typed function per method of the definition (`api.add({ title })`), so a
 * call the definition does not allow is a type error before it is a request.
 */
import type { Definition, Schema } from './definition.ts'
import { jsDoc, jsString, lineComment } from './escape.ts'
import { pascal, tsKey } from './names.ts'

type Components = Record<string, Schema>

/**
 * Whether a value of this schema may be absent on the wire. **The rule, once, for null and absent:** in this contract a null
 * and an absent key are the same value (a Luau nil is an absent key), so a property or a param whose schema allows null is
 * never required to be present, and TypeScript types it optional too (`tag?: string | null`), Luau types it `string?`, and
 * the router lets it be absent.
 */
export function allowsNull(schema: Schema, components: Components, seen = new Set<string>()): boolean {
  if (schema.kind === 'nullable' || schema.kind === 'null') return true
  if (schema.kind !== 'ref' || seen.has(schema.name)) return false
  seen.add(schema.name)
  const target = components[schema.name]
  return target !== undefined && allowsNull(target, components, seen)
}

/** The TypeScript type of a schema. */
export function tsType(schema: Schema, components: Components): string {
  switch (schema.kind) {
    case 'string':
      return schema.enum ? schema.enum.map((o) => jsString(o)).join(' | ') : 'string'
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array': {
      // `T[]`, not `Array<T>`: a schema named `Array` must not be able to shadow what the generated code means
      const item = tsType(schema.items, components)
      return /[ |&{]/.test(item) ? `(${item})[]` : `${item}[]`
    }
    case 'object': {
      const fields = Object.entries(schema.properties).map(
        ([name, property]) => `${tsKey(name)}${schema.required.includes(name) && !allowsNull(property, components) ? '' : '?'}: ${tsType(property, components)}`
      )
      return fields.length === 0 ? '{ [key: string]: never }' : `{ ${fields.join('; ')} }`
    }
    case 'ref':
      return schema.name
    case 'nullable':
      return `${tsType(schema.inner, components)} | null`
  }
}

/** The params of a method as one object type (`AddParams`). */
export function paramsSchema(definition: Definition, method: string): Schema {
  const m = definition.methods.find((x) => x.name === method)
  if (!m) throw new Error(`no method ${method}`)
  return {
    kind: 'object',
    properties: Object.assign(Object.create(null) as Record<string, Schema>, Object.fromEntries(m.params.map((p) => [p.name, p.schema]))),
    required: m.params.filter((p) => p.required).map((p) => p.name)
  }
}

/**
 * The types of the definition, as both sides of it are written in TypeScript (the page, and a backend in TypeScript): one
 * per schema, and `<Method>Params` (when the method has params) and `<Method>Result` per method.
 */
export function contractTypes(definition: Definition): string[] {
  const body: string[] = []
  for (const [name, schema] of Object.entries(definition.components)) {
    body.push(`${jsDoc(schema.description, '')}export type ${name} = ${tsType(schema, definition.components)}`)
  }
  if (Object.keys(definition.components).length > 0) body.push('')
  for (const method of definition.methods) {
    const type = pascal(method.name)
    if (method.params.length > 0) {
      const fields = method.params.map(
        (p) => `${jsDoc(p.description, '  ')}  ${tsKey(p.name)}${p.required && !allowsNull(p.schema, definition.components) ? '' : '?'}: ${tsType(p.schema, definition.components)}`
      )
      body.push(`export interface ${type}Params {\n${fields.join('\n')}\n}`)
    }
    body.push(`export type ${type}Result = ${tsType(method.result, definition.components)}`)
  }
  return body
}

/**
 * The name a page imports an app's typed client by: `@<app id>/rpc`. Everything a page gets from an app is under the app's
 * own scope (`@todos/rpc`), so a page can name the clients of several apps; what the framework gives every page is
 * `@vos/*`, which is why `vos` is not an app id.
 */
export const rpcModule = (appId: string): string => `@${appId}/rpc`

/** `.app/rpc.d.ts`: the types of the app's `@<app id>/rpc` module, from the definition. */
export function emitDeclarations(definition: Definition, source: string): string {
  const name = rpcModule(definition.app.id)
  const out: string[] = []
  out.push(`// GENERATED by @vos/vite-plugin from ${lineComment(source)}: do not edit (\`bun run generate\` writes it).`)
  out.push(`// The typed client of the app's RPC: ${lineComment(definition.title)} ${lineComment(definition.version)}. Import it as \`import { api } from '${name}'\`; the host page is \`@vos/host\`.`)
  out.push('')
  // `Promise` is the one builtin the generated types name; it comes from `@vos/host` under a name of its own, so a schema called
  // `Promise` (or `Reply`) cannot shadow it
  out.push(`declare module '${name}' {`)
  out.push("  import type { Reply as __vos_Reply } from '@vos/host'\n")
  const body: string[] = contractTypes(definition)
  body.push('')
  body.push('/** One typed function per method of the definition. */')
  body.push('export interface Api {')
  for (const method of definition.methods) {
    const type = pascal(method.name)
    const text = [method.summary, method.description].filter((t) => t !== undefined).join('\n\n') || undefined
    const allOptional = method.params.every((p) => !p.required || allowsNull(p.schema, definition.components))
    const params = method.params.length === 0 ? '' : `params${allOptional ? '?' : ''}: ${type}Params`
    body.push(`${jsDoc(text, '  ')}  ${tsKey(method.name)}(${params}): __vos_Reply<${type}Result>`)
  }
  body.push('}')
  body.push(`
/** The app's backend, as typed functions. A failed call rejects with \`RpcError\` (from \`@vos/host\`). */
export const api: Api`)
  out.push(body.map((line) => line.split('\n').map((l) => (l === '' ? l : `  ${l}`)).join('\n')).join('\n'))
  out.push('}')
  out.push('')
  return out.join('\n')
}

/** `.app/rpc.js`: the module behind `@<app id>/rpc`. It reads the global `vos` that the host's bridge script defines. */
export function emitModule(definition: Definition, source: string): string {
  const out: string[] = []
  out.push(`// GENERATED by @vos/vite-plugin from ${lineComment(source)}: do not edit (\`bun run generate\` writes it).`)
  out.push(`// The module behind \`${rpcModule(definition.app.id)}\`: ${lineComment(definition.title)} ${lineComment(definition.version)}.`)
  out.push('')
  out.push(`import { RpcError } from '@vos/host'

/** The host's bridge: its script is the first thing in the page, so it is there when this module runs. */
function bridge() {
  const vos = globalThis.vos
  if (!vos) throw new Error('This page has no host: open the app through vos (/apps/<id>), which serves it with the bridge')
  return vos
}

const failure = (e) =>
  new RpcError(typeof e?.code === 'number' ? e.code : -32603, typeof e?.message === 'string' ? e.message : String(e), e?.data)

async function request(method, params) {
  try {
    return await bridge().call(method, params ?? {})
  } catch (e) {
    throw failure(e)
  }
}

export const api = {`)
  for (const method of definition.methods) {
    const withParams = method.params.length > 0
    // the key and the method name are string literals: any word is a name here, and `api.new` is the method called `new`
    out.push(`  ${jsString(method.name)}: (${withParams ? 'params' : ''}) => request(${jsString(method.name)}, ${withParams ? 'params' : 'undefined'}),`)
  }
  out.push('}')
  out.push('')
  return out.join('\n')
}
