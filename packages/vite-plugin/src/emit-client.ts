/**
 * The typed client, from the definition: `generated/rpc.ts` in the app's project. The client's `mount(el, { rpc, host })`
 * gets the host's raw `rpc(method, args)`; `createRpc(raw)` turns it into an object with one typed function per method of
 * the definition (`rpc.add({ title })`), so a call the definition does not allow is a type error before it is a request.
 */
import type { Definition, Schema } from './definition.ts'
import { jsDoc, jsString, lineComment } from './escape.ts'
import { pascal } from './names.ts'

type Components = Record<string, Schema>

/**
 * Whether a value of this schema may be absent on the wire. **The rule, once, for null and absent:** in this contract a null
 * and an absent key are the same value (a Luau nil is an absent key), so a property or a param whose schema allows null is
 * never required to be present, and TypeScript types it optional too (`tag?: string | null`), Luau types it `string?`, and
 * the router lets it be absent.
 */
export function allowsNull(schema: Schema, components: Components, seen = new Set<string>()): boolean {
  if (schema.kind === 'nullable' || schema.kind === 'null') return true
  if (schema.kind !== 'ref' || seen.has(schema.name)) return false
  seen.add(schema.name)
  const target = components[schema.name]
  return target !== undefined && allowsNull(target, components, seen)
}

/** The TypeScript type of a schema. */
export function tsType(schema: Schema, components: Components): string {
  switch (schema.kind) {
    case 'string':
      return schema.enum ? schema.enum.map((o) => jsString(o)).join(' | ') : 'string'
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array': {
      const item = tsType(schema.items, components)
      return /[ |&]/.test(item) ? `Array<${item}>` : `${item}[]`
    }
    case 'object': {
      const fields = Object.entries(schema.properties).map(
        ([name, property]) => `${name}${schema.required.includes(name) && !allowsNull(property, components) ? '' : '?'}: ${tsType(property, components)}`
      )
      return fields.length === 0 ? 'Record<string, never>' : `{ ${fields.join('; ')} }`
    }
    case 'ref':
      return schema.name
    case 'nullable':
      return `${tsType(schema.inner, components)} | null`
  }
}

/** The params of a method as one object type (`AddParams`). */
export function paramsSchema(definition: Definition, method: string): Schema {
  const m = definition.methods.find((x) => x.name === method)
  if (!m) throw new Error(`no method ${method}`)
  return {
    kind: 'object',
    properties: Object.assign(Object.create(null) as Record<string, Schema>, Object.fromEntries(m.params.map((p) => [p.name, p.schema]))),
    required: m.params.filter((p) => p.required).map((p) => p.name)
  }
}

/** `.app/rpc.d.ts`: the types of the `app:rpc` module, from the definition. */
export function emitDeclarations(definition: Definition, source: string): string {
  const out: string[] = []
  out.push(`// GENERATED by @vos/vite-plugin from ${lineComment(source)}: do not edit (\`bun run generate\` writes it).`)
  out.push(`// The typed client of the app's RPC: ${lineComment(definition.title)} ${lineComment(definition.version)}. Import it as \`import { api, host } from 'app:rpc'\`.`)
  out.push('')
  out.push("declare module 'app:rpc' {")
  const body: string[] = []
  for (const [name, schema] of Object.entries(definition.components)) {
    body.push(`${jsDoc(schema.description, '')}export type ${name} = ${tsType(schema, definition.components)}`)
  }
  if (Object.keys(definition.components).length > 0) body.push('')
  for (const method of definition.methods) {
    const type = pascal(method.name)
    if (method.params.length > 0) {
      const fields = method.params.map(
        (p) => `${jsDoc(p.description, '  ')}  ${p.name}${p.required && !allowsNull(p.schema, definition.components) ? '' : '?'}: ${tsType(p.schema, definition.components)}`
      )
      body.push(`export interface ${type}Params {\n${fields.join('\n')}\n}`)
    }
    body.push(`export type ${type}Result = ${tsType(method.result, definition.components)}`)
  }
  body.push('')
  body.push('/** One typed function per method of the definition. */')
  body.push('export interface Api {')
  for (const method of definition.methods) {
    const type = pascal(method.name)
    const text = [method.summary, method.description].filter((t) => t !== undefined).join('\n\n') || undefined
    const allOptional = method.params.every((p) => !p.required || allowsNull(p.schema, definition.components))
    const params = method.params.length === 0 ? '' : `params${allOptional ? '?' : ''}: ${type}Params`
    body.push(`${jsDoc(text, '  ')}  ${method.name}(${params}): Promise<${type}Result>`)
  }
  body.push('}')
  body.push(`
/** What the host offers the app: events (the backend's \`app.emit\`, and \`host:theme\`) and the shell's appearance. */
export interface Host {
  /** Hear an event; returns a function that stops listening. */
  on(name: string, fn: (data: unknown) => void): () => void
  readonly theme: 'light' | 'dark'
}

/** A JSON-RPC 2.0 error: the router refused the call (-32602 invalid params, -32601 method not found) or the handler failed it. */
export class RpcError extends Error {
  readonly code: number
  readonly data: unknown
  constructor(code: number, message: string, data?: unknown)
}

/** The app's backend, as typed functions. A failed call rejects with an {@link RpcError}. */
export const api: Api
export const host: Host`)
  out.push(body.map((line) => line.split('\n').map((l) => (l === '' ? l : `  ${l}`)).join('\n')).join('\n'))
  out.push('}')
  out.push('')
  return out.join('\n')
}

/** `.app/rpc.js`: the module behind `app:rpc`. The generated entry binds it to the host before the app's `mount` runs. */
export function emitModule(definition: Definition, source: string): string {
  const out: string[] = []
  out.push(`// GENERATED by @vos/vite-plugin from ${lineComment(source)}: do not edit (\`bun run generate\` writes it).`)
  out.push(`// The module behind \`app:rpc\`: ${lineComment(definition.title)} ${lineComment(definition.version)}.`)
  out.push('')
  out.push(`let bound

/** Called by the generated entry with what the host gives \`mount\`, before the app's own \`mount\` runs. */
export function bind(props) {
  bound = props
}

export class RpcError extends Error {
  constructor(code, message, data) {
    super(message)
    this.name = 'RpcError'
    this.code = code
    this.data = data
  }
}

async function call(method, params) {
  if (!bound) throw new Error('app:rpc was used before the app was mounted')
  try {
    return await bound.rpc(method, params ?? {})
  } catch (e) {
    throw new RpcError(typeof e?.code === 'number' ? e.code : -32603, typeof e?.message === 'string' ? e.message : String(e), e?.data)
  }
}

export const host = {
  on: (name, fn) => bound.host.on(name, fn),
  get theme() {
    return bound.host.theme
  }
}

export const api = {`)
  for (const method of definition.methods) {
    const withParams = method.params.length > 0
    out.push(`  ${method.name}: (${withParams ? 'params' : ''}) => call('${method.name}', ${withParams ? 'params' : 'undefined'}),`)
  }
  out.push('}')
  out.push('')
  return out.join('\n')
}

/** `.app/entry.js`: what the build bundles. It binds `app:rpc` to the host and then calls the app's `mount(el)`. */
export function emitEntry(clientFromGenerated: string): string {
  return `// GENERATED by @vos/vite-plugin: do not edit. The client's entry: binds \`app:rpc\` to the host, then mounts the app.
import { mount as mountApp } from '${clientFromGenerated}'
import { bind } from './rpc.js'

export function mount(el, props) {
  bind(props)
  return mountApp(el)
}
`
}
