  // `Promise` (or `Reply`) cannot shadow it
  out.push("declare module 'app:rpc/builtins' {\n  export type Reply<T> = Promise<T>\n}\n")
  out.push("declare module 'app:rpc' {")
  out.push("  import type { Reply as __vos_Reply } from 'app:rpc/builtins'\n")
