// `@vos/host`: what the app framework gives every page, whatever its app: the host page that holds it (its appearance,
// context and capabilities, the backend's events, links, display modes) and the error a backend call rejects with. The
// same for every app, so it is not read from the contract; the app's own API is `@<app id>/rpc`. A page's framework modules are
// `@vos/*` (this, `@vos/tracing`); a backend's are `vos:*`.

/** `.app/host.d.ts`: the types of `@vos/host`. */
export function emitHostDeclarations(): string {
  return `// GENERATED by @vos/vite-plugin: do not edit (\`bun run generate\` writes it).
declare module '@vos/host' {
  /** What a call to the host or the backend gives: a promise of its result. */
  export type Reply<T> = Promise<T>

  /** What the host offers the app. */
  export interface Host {
    /** Hear an event the backend sent with \`app.emit(name, data)\`; returns a function that stops listening. */
    on(name: string, fn: (data: unknown) => void): () => void
    /** The appearance the host shows now: the page follows it (the bridge sets \`data-theme\` and \`color-scheme\`). */
    readonly theme: 'light' | 'dark'
    /** The host context (MCP Apps' \`hostContext\`): theme, displayMode, availableDisplayModes, locale, timeZone, ... */
    readonly context: { readonly [key: string]: unknown }
    /** What the host offers (MCP Apps' \`hostCapabilities\`), known once {@link Host.ready} has resolved. */
    readonly capabilities: { readonly [key: string]: unknown }
    /** True when the host page draws UI of its own (the shell: sheets, alerts, window layouts); false on the standalone page. */
    readonly hosted: boolean
    /** Resolves when the handshake with the host is done; rejects when the host did not accept the page. */
    readonly ready: Reply<void>
    /** Hear a change of the host context (the appearance, the display mode); returns a function that stops listening. */
    onContext(fn: (context: { readonly [key: string]: unknown }) => void): () => void
    /** Run \`fn\` before the host removes the page (\`ui/resource-teardown\`); it may return a promise. */
    onTeardown(fn: () => void | Reply<void>): () => void
    /** Open a link outside the app (\`ui/open-link\`): http and https only. */
    openLink(url: string): Reply<void>
    /** Ask for a display mode (\`ui/request-display-mode\`); resolves with the mode the host ended in. */
    requestDisplayMode(mode: 'inline' | 'fullscreen' | 'pip'): Reply<'inline' | 'fullscreen' | 'pip'>
  }

  /** A JSON-RPC 2.0 error: the router refused the call (-32602 invalid params, -32601 method not found) or the handler failed it. */
  export class RpcError extends Error {
    readonly code: number
    readonly data: unknown
    constructor(code: number, message: string, data?: unknown)
  }

  /** The host page that holds the app. */
  export const host: Host
}
`
}

/** `.app/host.js`: the module behind \`@vos/host\`. It reads the global \`vos\` that the host's bridge script defines. */
export function emitHostModule(): string {
  return `// GENERATED by @vos/vite-plugin: do not edit (\`bun run generate\` writes it).
// The module behind \`@vos/host\`: the host page that holds the app, through the bridge's global \`vos\`.

export class RpcError extends Error {
  constructor(code, message, data) {
    super(message)
    this.name = 'RpcError'
    this.code = code
    this.data = data
  }
}

/** The host's bridge: its script is the first thing in the page, so it is there when this module runs. */
function bridge() {
  const vos = globalThis.vos
  if (!vos) throw new Error('This page has no host: open the app through vos (/apps/<id>), which serves it with the bridge')
  return vos
}

const failure = (e) =>
  new RpcError(typeof e?.code === 'number' ? e.code : -32603, typeof e?.message === 'string' ? e.message : String(e), e?.data)

async function request(method, params) {
  try {
    return await bridge().call(method, params ?? {})
  } catch (e) {
    throw failure(e)
  }
}

export const host = {
  on: (name, fn) => bridge().on(name, fn),
  get theme() {
    // before the handshake the context is empty: the page's own data-theme (the bridge set it before first paint) is the answer
    return (bridge().context.theme ?? document.documentElement.dataset.theme) === 'dark' ? 'dark' : 'light'
  },
  get context() {
    return bridge().context
  },
  get capabilities() {
    return bridge().capabilities
  },
  get hosted() {
    return Boolean(bridge().capabilities.experimental?.vos?.ui)
  },
  get ready() {
    return bridge().ready.then(() => undefined)
  },
  onContext: (fn) => bridge().onContext(fn),
  onTeardown: (fn) => bridge().onTeardown(fn),
  async openLink(url) {
    await request('ui/open-link', { url })
  },
  async requestDisplayMode(mode) {
    return (await request('ui/request-display-mode', { mode })).mode
  }
}
`
}
