// `@vos/tracing`: spans and events from an app's page, after Rust's `tracing` (NEOC-521 POC). What the app framework
// gives a page (TypeScript) is `@vos/*`; what it gives a backend (Luau, or TypeScript compiled to it) is `vos:*`, so the
// two are never mistaken for one another, nor for what an app gives a page (`@<app id>/*`). The same for every app, so
// it is not read from the contract; it is a thin module over the bridge's `vos.tracing`, which holds the span the page
// is in (the bridge has to: it reads it when a call to the backend starts, so the call is a child of that span).

/** `.app/tracing.d.ts`: the types of `@vos/tracing`. */
export function emitTracingDeclarations(): string {
  return `// GENERATED by @vos/vite-plugin: do not edit (\`bun run generate\` writes it).
declare module '@vos/tracing' {
  /** How detailed an event or a span is, finest first. */
  export type Level = 'trace' | 'debug' | 'info' | 'warn' | 'error'
  /** The fields of an event or a span: written as JSON, so what JSON cannot hold is left out. */
  export type Fields = { readonly [key: string]: unknown }

  export interface SpanOptions {
    /** How detailed it is. When not given: \`info\`. */
    level?: Level
  }

  /**
   * A span: a named stretch of the page's work, with fields, a child of the span the page was in when it was opened. A
   * call to the backend made in it is a child of it, and so is what the host and the backend do for that call.
   */
  export interface Span {
    /** Record \`value\` under \`key\` on the span, as \`tracing\`'s \`Span::record\` does. Nothing happens once it has ended. */
    record(key: string, value: unknown): void
    /**
     * Run \`body\` in the span and end it: when \`body\` returns, or when the promise it returns settles. Gives what \`body\`
     * gave; what it throws (or the promise rejects with) is the span's failure, and thrown again.
     *
     * The page has no async context, so the span is current for what \`body\` does before it first waits, and after that
     * for calls and events outside any other scope while it is the only scope still pending.
     */
    inScope<T>(body: () => T): T
    /** End the span now, if \`inScope\` did not. */
    end(): void
  }

  /**
   * Open a span named \`name\` with \`fields\`, in the span the page is in now (else as the root of a trace of its own).
   *
   * \`\`\`ts
   * const units = await span('load units', { scope: 'system' }).inScope(() => api.overview())
   * \`\`\`
   */
  export function span(name: string, fields?: Fields, options?: SpanOptions): Span

  /**
   * \`body\` with a span of its own around every call, as \`#[instrument]\` does. Its arguments are never recorded unless
   * \`fields\` picks them (an argument may be something the person typed).
   *
   * \`\`\`ts
   * const load = instrument('load unit', (name: string) => api.unit({ name }), { fields: (name) => ({ name }) })
   * \`\`\`
   */
  export function instrument<A extends unknown[], R>(
    name: string,
    body: (...args: A) => R,
    options?: SpanOptions & { fields?: (...args: A) => Fields }
  ): (...args: A) => R

  /** Write a \`trace\` event in the span the page is in now. */
  export function trace(message: string, fields?: Fields): void
  /** Write a \`debug\` event in the span the page is in now. */
  export function debug(message: string, fields?: Fields): void
  /**
   * Write an \`info\` event in the span the page is in now.
   *
   * \`\`\`ts
   * info('drew the units', { count: units.length })
   * \`\`\`
   */
  export function info(message: string, fields?: Fields): void
  /** Write a \`warn\` event in the span the page is in now. */
  export function warn(message: string, fields?: Fields): void
  /** Write an \`error\` event in the span the page is in now; an \`Error\` is written with its type and stack. */
  export function error(message: string | Error, fields?: Fields): void
}
`
}

/** `.app/tracing.js`: the module behind \`@vos/tracing\`. */
export function emitTracingModule(): string {
  return `// GENERATED by @vos/vite-plugin: do not edit (\`bun run generate\` writes it).
// The module behind \`@vos/tracing\`: the bridge's \`vos.tracing\`, which holds the span the page is in.

function tracing() {
  const vos = globalThis.vos
  if (!vos || !vos.tracing) throw new Error('This page has no host: open the app through vos (/apps/<id>), which serves it with the bridge')
  return vos.tracing
}

export const span = (name, fields, options) => tracing().span(name, fields, options)
export const instrument = (name, body, options) => tracing().instrument(name, body, options)
export const trace = (message, fields) => tracing().event('trace', message, fields)
export const debug = (message, fields) => tracing().event('debug', message, fields)
export const info = (message, fields) => tracing().event('info', message, fields)
export const warn = (message, fields) => tracing().event('warn', message, fields)
export const error = (message, fields) => tracing().event('error', message, fields)
`
}
