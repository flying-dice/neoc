/**
 * The typed client, from the definition: `generated/rpc.ts` in the app's project. The client's `mount(el, { rpc, host })`
 * gets the host's raw `rpc(method, args)`; `createRpc(raw)` turns it into an object with one typed function per method of
 * the definition (`rpc.add({ title })`), so a call the definition does not allow is a type error before it is a request.
 */
import type { Definition, Schema } from './definition.ts'
import { pascal } from './names.ts'

const doc = (description: string | undefined, indent: string): string =>
  description === undefined ? '' : `${indent}/** ${description.replace(/\*\//g, '* /').replace(/\n/g, `\n${indent} * `)} */\n`

/** The TypeScript type of a schema. */
export function tsType(schema: Schema): string {
  switch (schema.kind) {
    case 'string':
      return schema.enum ? schema.enum.map((o) => JSON.stringify(o)).join(' | ') : 'string'
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array': {
      const item = tsType(schema.items)
      return /[ |&]/.test(item) ? `Array<${item}>` : `${item}[]`
    }
    case 'object': {
      const fields = Object.entries(schema.properties).map(
        ([name, property]) => `${name}${schema.required.includes(name) ? '' : '?'}: ${tsType(property)}`
      )
      return fields.length === 0 ? 'Record<string, never>' : `{ ${fields.join('; ')} }`
    }
    case 'ref':
      return schema.name
    case 'nullable':
      return `${tsType(schema.inner)} | null`
  }
}

/** The params of a method as one object type (`AddParams`). */
export function paramsSchema(definition: Definition, method: string): Schema {
  const m = definition.methods.find((x) => x.name === method)
  if (!m) throw new Error(`no method ${method}`)
  return {
    kind: 'object',
    properties: Object.fromEntries(m.params.map((p) => [p.name, p.schema])),
    required: m.params.filter((p) => p.required).map((p) => p.name)
  }
}

export function emitTs(definition: Definition, source: string): string {
  const out: string[] = []
  out.push(`// GENERATED by @vos/vite-plugin from ${source}: do not edit (\`bun run generate\` writes it).`)
  out.push(`// The typed client of the app's RPC: ${definition.title} ${definition.version}.`)
  out.push('')
  for (const [name, schema] of Object.entries(definition.components)) {
    out.push(`${doc(schema.description, '')}export type ${name} = ${tsType(schema)}`)
  }
  if (Object.keys(definition.components).length > 0) out.push('')

  for (const method of definition.methods) {
    const type = pascal(method.name)
    if (method.params.length > 0) {
      const fields = method.params.map(
        (p) => `${doc(p.description, '  ')}  ${p.name}${p.required ? '' : '?'}: ${tsType(p.schema)}`
      )
      out.push(`export interface ${type}Params {\n${fields.join('\n')}\n}`)
    }
    out.push(`export type ${type}Result = ${tsType(method.result)}`)
  }
  out.push('')

  out.push('/** One typed function per method of the definition. */')
  out.push('export interface Rpc {')
  for (const method of definition.methods) {
    const type = pascal(method.name)
    const text = [method.summary, method.description].filter((t) => t !== undefined).join('\n\n') || undefined
    const allOptional = method.params.every((p) => !p.required)
    const params = method.params.length === 0 ? '' : `params${allOptional ? '?' : ''}: ${type}Params`
    out.push(`${doc(text, '  ')}  ${method.name}(${params}): Promise<${type}Result>`)
  }
  out.push('}')
  out.push('')

  out.push(`/** What the host gives \`mount\`: the raw call to the app's backend. */
export type RawRpc = (method: string, args?: unknown) => Promise<unknown>

/** What the host gives \`mount\`: events (the backend's \`app.emit\`, and \`host:theme\`) and the appearance. */
export interface Host {
  /** Hear an event; returns a function that stops listening. */
  on(name: string, fn: (data: unknown) => void): () => void
  readonly theme: 'light' | 'dark'
}

/** The props of \`mount(el, props)\`. */
export interface MountProps {
  rpc: RawRpc
  host: Host
}

/** A JSON-RPC 2.0 error: the router refused the call (-32602 invalid params, -32601 method not found), or the handler failed. */
export class RpcError extends Error {
  readonly code: number
  readonly data: unknown
  constructor(code: number, message: string, data?: unknown) {
    super(message)
    this.name = 'RpcError'
    this.code = code
    this.data = data
  }
}

/** The typed client over the host's raw \`rpc\`. A failed call rejects with an [\`RpcError\`]. */
export function createRpc(raw: RawRpc): Rpc {
  const call = async (method: string, params: object | undefined): Promise<never> => {
    try {
      return (await raw(method, params ?? {})) as never
    } catch (e) {
      const { code, message, data } = e as { code?: unknown; message?: unknown; data?: unknown }
      throw new RpcError(typeof code === 'number' ? code : -32603, typeof message === 'string' ? message : String(e), data)
    }
  }
  return {`)
  for (const method of definition.methods) {
    const withParams = method.params.length > 0
    out.push(`    ${method.name}: (${withParams ? 'params' : ''}) => call('${method.name}', ${withParams ? 'params' : 'undefined'}),`)
  }
  out.push('  }')
  out.push('}')
  out.push('')
  return out.join('\n')
}
