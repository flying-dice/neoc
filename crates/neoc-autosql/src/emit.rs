//! Emits the `autosql/` data-access layer: the shared `ports.neoc` (the
//! `SqlValue` / `SqlExecutor` contract plus the bind/decode helpers), the
//! `migrate.neoc` runner, and one self-contained file per query.
//!
//! Everything emitted is pure neoc that touches no `std:`/`lib:`/`vnd:` module.
//! A query file imports only `autosql::ports`; the contract and helpers live
//! there, the row struct, decoder, and query function live in the query's own
//! file. The generated code relies only on language features confirmed in
//! `lang/`: generic functions with a trait bound, method calls through that
//! bound, `for x in xs` iteration, `let` bindings reassigned and
//! index-assigned, `match` with or-patterns producing values, and `?` at
//! statement level.
//!
//! Two lowering constraints shape the output (see `ASSUMPTIONS.md`): `match`
//! lowers to an IIFE, so a match arm may not contain `return` or `?`. Decoding
//! therefore goes through shared `Result`-returning helpers, consumed with `?`
//! in the function body — never inside a `match` arm.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::Migration;
use crate::naming;
use crate::query::{AnalyzedQuery, Kind, Param, ResultCol};
use crate::{Prim, Variant};

/// The header stamped on every generated file.
const HEADER: &str = "// @generated by neoc autosql — do not edit.\n";

/// The full bind/decode helper surface `ports.neoc` exports. Every helper is
/// emitted once in `ports`, and each query file imports only the ones it uses.
const ALL_VARIANTS: [Variant; 4] = [Variant::Int, Variant::Real, Variant::Text, Variant::Bool];
const ALL_PRIMS: [Prim; 3] = [Prim::Number, Prim::String, Prim::Bool];

/// The shared `ports.neoc`: the executor contract and every bind/decode helper
/// a query file may import.
pub(crate) fn ports() -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    out.push_str(
        "\
// The executor contract. Implement `SqlExecutor` for your runtime through
// `ext` declarations — that impl is the only code that touches a database.

pub enum SqlValue {
    Int(number),
    Real(number),
    Text(string),
    Bool(bool),
    Null,
}

pub trait SqlExecutor {
    fn execute(self, sql: string, params: [SqlValue]) -> Result<number, string>;
    fn query(self, sql: string, params: [SqlValue]) -> Result<[[SqlValue]], string>;
}
",
    );
    out.push('\n');

    // `bind_opt_*` first, then `decode_*` / `decode_opt_*`, in a stable order.
    for variant in ALL_VARIANTS {
        emit_bind_helper(&mut out, variant);
    }
    for prim in ALL_PRIMS {
        emit_decode_helper(&mut out, prim, false);
        emit_decode_helper(&mut out, prim, true);
    }
    out.trim_end().to_string() + "\n"
}

/// The `migrate.neoc` runner: applies every migration's DDL statements in
/// order, one `db.execute` call each, returning the count of statements run.
pub(crate) fn migrate(migrations: &[&Migration]) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str("use autosql::ports::SqlExecutor;\n\n");
    out.push_str(
        "\
// Runs every DDL statement, in migration order, through the executor. Returns
// the number of statements applied.
pub fn migrate<E: SqlExecutor>(db: E) -> Result<number, string> {
",
    );
    out.push_str("    let applied = 0;\n");
    for migration in migrations {
        let _ = writeln!(out, "    // {:04}-{}", migration.order, migration.name);
        for statement in split_statements(&migration.sql) {
            let literal = neoc_string(&statement);
            let _ = writeln!(out, "    db.execute({literal}, [])?;");
            out.push_str("    applied = applied + 1;\n");
        }
    }
    out.push_str("    Ok(applied)\n");
    out.push_str("}\n");
    out
}

/// One query's file: its row struct (for a row-returning query), its decoder,
/// and the typed query function. Imports only the `autosql::ports` items it
/// uses.
pub(crate) fn query_file(query: &AnalyzedQuery) -> String {
    let fn_name = query.fn_name();

    // Collect the ports items this file references, so the `use` lists exactly
    // what it needs.
    let mut imports: BTreeSet<String> = BTreeSet::new();
    imports.insert("SqlValue".to_string());
    imports.insert("SqlExecutor".to_string());
    for p in &query.params {
        if p.nullable {
            imports.insert(format!("bind_opt_{}", p.ty.variant.ctor().to_lowercase()));
        }
    }
    for c in &query.result {
        imports.insert(decode_helper_name(c.ty.prim, c.nullable));
    }

    let mut out = String::new();
    out.push_str(HEADER);
    // neoc has no grouped `use a::{b, c}` form — one item per `use` line.
    for item in &imports {
        let _ = writeln!(out, "use autosql::ports::{item};");
    }
    out.push('\n');

    if query.kind.returns_rows() {
        emit_struct(&mut out, &query.row_name(), &result_fields(&query.result));
    }

    emit_query(&mut out, query, &fn_name);

    if query.kind.returns_rows() {
        emit_decoder(&mut out, query, &fn_name);
    }

    out.trim_end().to_string() + "\n"
}

/// A field rendered as `name: Type`.
struct Field {
    name: String,
    ty: String,
}

/// The fields for a result struct. Field names are sanitised to valid neoc
/// identifiers.
fn result_fields(cols: &[ResultCol]) -> Vec<Field> {
    cols.iter()
        .map(|c| Field {
            name: naming::sanitize_ident(&c.field),
            ty: neoc_type(c.ty.prim, c.nullable),
        })
        .collect()
}

/// Writes a `pub struct Name { … }`.
fn emit_struct(out: &mut String, name: &str, fields: &[Field]) {
    let _ = writeln!(out, "pub struct {name} {{");
    for field in fields {
        let _ = writeln!(out, "    {}: {},", field.name, field.ty);
    }
    out.push_str("}\n\n");
}

/// Writes a query's function. A row-returning query collects decoded rows; a
/// non-returning statement returns the rows-affected count directly.
fn emit_query(out: &mut String, query: &AnalyzedQuery, fn_name: &str) {
    let sql = neoc_string(&query.sql);
    let signature = fn_signature(query, fn_name);

    let _ = writeln!(out, "{signature} {{");
    let _ = writeln!(
        out,
        "    let params: [SqlValue] = [{}];",
        binds(&query.params)
    );

    match query.kind {
        Kind::Exec => {
            let _ = writeln!(out, "    db.execute({sql}, params)");
        }
        Kind::Many => {
            let row = query.row_name();
            let _ = writeln!(out, "    let rows = db.query({sql}, params)?;");
            let _ = writeln!(out, "    let out: [{row}] = [];");
            out.push_str("    let next = 0;\n");
            out.push_str("    for row in rows {\n");
            let _ = writeln!(out, "        let decoded = decode_{fn_name}(row)?;");
            out.push_str("        out[next] = decoded;\n");
            out.push_str("        next = next + 1;\n");
            out.push_str("    }\n");
            out.push_str("    Ok(out)\n");
        }
    }
    out.push_str("}\n\n");
}

/// Builds the function signature line, e.g.
/// `pub fn user_by_id<E: SqlExecutor>(db: E, id: number) -> Result<[UserByIdRow], string>`.
fn fn_signature(query: &AnalyzedQuery, fn_name: &str) -> String {
    let mut params = String::from("db: E");
    for p in &query.params {
        let _ = write!(
            params,
            ", {}: {}",
            naming::sanitize_ident(&p.name),
            neoc_type(p.ty.prim, p.nullable)
        );
    }
    let ret = match query.kind {
        Kind::Exec => "number".to_string(),
        Kind::Many => format!("[{}]", query.row_name()),
    };
    format!("pub fn {fn_name}<E: SqlExecutor>({params}) -> Result<{ret}, string>")
}

/// Renders the `[SqlValue]` bind list for a parameter set, using the shared
/// `bind_opt_*` helpers for nullable parameters.
fn binds(params: &[Param]) -> String {
    params
        .iter()
        .map(|p| {
            let arg = naming::sanitize_ident(&p.name);
            if p.nullable {
                format!("bind_opt_{}({arg})", p.ty.variant.ctor().to_lowercase())
            } else {
                format!("SqlValue::{}({arg})", p.ty.variant.ctor())
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// Writes a decoder `fn decode_<name>(cols: [SqlValue]) -> Result<Row, string>`
/// that pulls each column through a shared `ports` decode helper with `?`.
fn emit_decoder(out: &mut String, query: &AnalyzedQuery, fn_name: &str) {
    let row = query.row_name();
    let _ = writeln!(
        out,
        "fn decode_{fn_name}(cols: [SqlValue]) -> Result<{row}, string> {{"
    );
    for (index, col) in query.result.iter().enumerate() {
        let helper = decode_helper_name(col.ty.prim, col.nullable);
        let field = naming::sanitize_ident(&col.field);
        let label = neoc_string(&format!("{fn_name}: column {index} ({field})"));
        let _ = writeln!(out, "    let {field} = {helper}(cols[{index}], {label})?;");
    }
    let names = query
        .result
        .iter()
        .map(|c| naming::sanitize_ident(&c.field))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(out, "    Ok({row} {{ {names} }})");
    out.push_str("}\n\n");
}

/// Writes a `pub bind_opt_<variant>` helper turning an `Option<T>` parameter
/// into a `SqlValue` (or `SqlValue::Null`). The `match` is the function's value
/// — no `return`/`?` inside it.
fn emit_bind_helper(out: &mut String, variant: Variant) {
    let lower = variant.ctor().to_lowercase();
    let ty = match variant {
        Variant::Int | Variant::Real => "number",
        Variant::Text => "string",
        Variant::Bool => "bool",
    };
    let _ = writeln!(
        out,
        "pub fn bind_opt_{lower}(value: Option<{ty}>) -> SqlValue {{"
    );
    out.push_str("    match value {\n");
    let _ = writeln!(
        out,
        "        Some(inner) => SqlValue::{}(inner),",
        variant.ctor()
    );
    out.push_str("        None => SqlValue::Null,\n");
    out.push_str("    }\n}\n\n");
}

/// Writes a `pub decode_*` helper: `fn decode_number(value, label) -> Result<…>`.
/// The `match` produces `Ok`/`Err` values directly — the failure path is an
/// `Err`, not a `return`, so the whole match is a legal value expression.
fn emit_decode_helper(out: &mut String, prim: Prim, nullable: bool) {
    let name = decode_helper_name(prim, nullable);
    let ret = neoc_type(prim, nullable);
    let value_arm = match prim {
        Prim::Number => "SqlValue::Int(inner) | SqlValue::Real(inner)",
        Prim::String => "SqlValue::Text(inner)",
        Prim::Bool => "SqlValue::Bool(inner)",
    };
    let _ = writeln!(
        out,
        "pub fn {name}(value: SqlValue, label: string) -> Result<{ret}, string> {{"
    );
    out.push_str("    match value {\n");
    if nullable {
        out.push_str("        SqlValue::Null => Ok(None),\n");
        let _ = writeln!(out, "        {value_arm} => Ok(Some(inner)),");
    } else {
        let _ = writeln!(out, "        {value_arm} => Ok(inner),");
    }
    out.push_str("        _ => Err(label),\n");
    out.push_str("    }\n}\n\n");
}

/// The shared decode helper name for a column type.
fn decode_helper_name(prim: Prim, nullable: bool) -> String {
    let base = match prim {
        Prim::Number => "number",
        Prim::String => "string",
        Prim::Bool => "bool",
    };
    if nullable {
        format!("decode_opt_{base}")
    } else {
        format!("decode_{base}")
    }
}

/// The neoc type for a primitive, wrapped in `Option<…>` when nullable.
fn neoc_type(prim: Prim, nullable: bool) -> String {
    if nullable {
        format!("Option<{}>", prim.neoc())
    } else {
        prim.neoc().to_string()
    }
}

/// Splits a DDL blob into individual statements on `;`, dropping blank and
/// comment-only fragments, and normalising each to a single-line string.
fn split_statements(sql: &str) -> Vec<String> {
    sql.split(';')
        .map(strip_comments_and_normalize)
        .filter(|s| !s.is_empty())
        .collect()
}

/// Strips `--` line comments, collapses whitespace, and trims — leaving one
/// clean SQL statement (or the empty string for a blank/comment-only fragment).
fn strip_comments_and_normalize(fragment: &str) -> String {
    let without_comments: String = fragment
        .lines()
        .map(|line| match line.find("--") {
            Some(idx) => &line[..idx],
            None => line,
        })
        .collect::<Vec<_>>()
        .join(" ");
    without_comments
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

/// Renders a neoc double-quoted string literal, escaping `\` and `"`.
fn neoc_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            _ => out.push(ch),
        }
    }
    out.push('"');
    out
}
