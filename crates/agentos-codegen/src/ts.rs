fn tokens() -> String {
    let mut out = String::new();
    for (name, def) in named_enums() {
        let _ = writeln!(out, "export type {name} = {}", union(def.values));
    }
    out.push('\n');
    for (name, def) in named_objects() {
        let _ = writeln!(out, "export type {name} = {}", object(def, 0));
    }
    out.push('\n');
    out
}

fn union(values: &[&str]) -> String {
    values.iter().map(|v| format!("'{v}'")).collect::<Vec<_>>().join(" | ")
}

fn enum_type(def: &EnumDef) -> String {
    if def.name.is_empty() {
        union(def.values)
    } else {
        def.name.to_owned()
    }
}

/// The TypeScript type of a value of `ty` (without the `Expr` wrapper).
fn ty(value: &PropType) -> String {
    match value {
        PropType::Str | PropType::Source => "string".to_owned(),
        PropType::Number | PropType::Int => "number".to_owned(),
        PropType::Bool => "boolean".to_owned(),
        PropType::Json => "JsonValue".to_owned(),
        PropType::Enum(def) => enum_type(def),
        PropType::Spacing => "Spacing".to_owned(),
        PropType::Insets => "Spacing | Insets".to_owned(),
        PropType::Frame => "'fill' | Frame".to_owned(),
        PropType::List(inner) => format!("Array<{}>", ty(inner)),
        PropType::Object(def) => {
            if def.name.is_empty() {
                object(def, 0)
            } else {
                def.name.to_owned()
            }
        }
        PropType::Union(options) => options.iter().map(ty).collect::<Vec<_>>().join(" | "),
    }
}

/// One field's type: a binding is a ref; a source is an id; everything else may be an expression.
fn field_type(p: &PropSpec) -> String {
    if p.binding.is_some() {
        "Binding".to_owned()
    } else if matches!(p.ty, PropType::Source) {
        "string".to_owned()
    } else {
        format!("Expr<{}>", ty(&p.ty))
    }
}

fn object(def: &ObjectDef, _depth: usize) -> String {
    let mut fields: Vec<String> = def
        .fields
        .iter()
        .map(|f| format!("{}{}: {}", ident(f.name), if f.required { "" } else { "?" }, field_type(f)))
        .collect();
    if def.open {
        fields.push("[param: string]: Expr".to_owned());
    }
    format!("{{ {} }}", fields.join("; "))
}

fn ident(name: &str) -> String {
    if name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
        name.to_owned()
    } else {
        format!("'{name}'")
    }
}

fn components() -> String {
    let mut out = String::new();
    out.push_str("/** Props every node accepts. A component's own prop of the same name overrides it. */\n");
    let _ = writeln!(out, "export type CommonProps = {{\n{}}}\n", props_body(COMMON_PROPS.iter(), "  "));
    let common_events: Vec<String> =
        COMMON_EVENTS.iter().map(|e| format!("  {}?: Handler\n", ident(e.name))).collect();
    let _ = writeln!(out, "export type CommonEvents = {{\n{}}}\n", common_events.concat());
    let names: Vec<&str> = CATALOGUE.iter().map(|c| c.name).collect();
    let _ = writeln!(out, "export type ComponentName = {}\n", union(&names));
    out.push_str(&meta_table());
    for c in CATALOGUE {
        out.push_str(&component(c));
    }
    let typed: Vec<String> = CATALOGUE.iter().map(|c| format!("{}Node", c.name)).collect();
    let _ = writeln!(
        out,
        "/** A node of a known component, with its props, slots and events typed. */\nexport type TypedNode =\n  | {}\n",
        typed.join("\n  | ")
    );
    out.push_str(&event_payloads());
    out
}

fn props_body<'a>(props: impl Iterator<Item = &'a PropSpec>, indent: &str) -> String {
    let mut out = String::new();
    for p in props {
        if !p.doc.is_empty() {
            let _ = writeln!(out, "{indent}/** {} */", p.doc);
        }
        let _ = writeln!(
            out,
            "{indent}{}{}: {}",
            ident(p.name),
            if p.required { "" } else { "?" },
            field_type(p)
        );
    }
    out
}

fn component(c: &ComponentSpec) -> String {
    let mut out = String::new();
    let overridden: Vec<String> = COMMON_PROPS
        .iter()
        .filter(|p| c.props.iter().any(|own| own.name == p.name))
        .map(|p| format!("'{}'", p.name))
        .collect();
    let base = if overridden.is_empty() {
        "CommonProps".to_owned()
    } else {
        format!("Omit<CommonProps, {}>", overridden.join(" | "))
    };
    let _ = writeln!(out, "/** {} (Tier {}, since {}) */", c.doc, c.tier as u8, c.since);
    if c.open_props {
        let _ = writeln!(out, "export type {}Props = {base} & {{ [prop: string]: Expr }}", c.name);
    } else if c.props.is_empty() {
        let _ = writeln!(out, "export type {}Props = {base}", c.name);
    } else {
        let _ = writeln!(
            out,
            "export type {}Props = {base} & {{\n{}}}",
            c.name,
            props_body(c.props.iter(), "  ")
        );
    }

    let any_required = c.effective_props().any(|p| p.required);
    let events: String =
        c.events.iter().map(|e| format!("{}?: Handler", ident(e.name))).collect::<Vec<_>>().join("; ");
    let on =
        if events.is_empty() { "CommonEvents".to_owned() } else { format!("CommonEvents & {{ {events} }}") };

    let mut slot_fields: Vec<String> = Vec::new();
    for s in c.slots.iter().chain(COMMON_SLOTS) {
        let name = if s.prefix { format!("[slot: `{}${{string}}`]", s.name) } else { ident(s.name) };
        let optional = if s.prefix || s.required { "" } else { "?" };
        slot_fields.push(format!("{name}{optional}: Array<TypedNode>"));
    }
    if c.open_props {
        slot_fields.push("[slot: string]: Array<TypedNode> | undefined".to_owned());
    }

    let _ = writeln!(out, "export type {}Node = {{", c.name);
    let _ = writeln!(out, "  type: '{}'", c.name);
    let _ = writeln!(out, "  key: string");
    let _ = writeln!(out, "  props{}: {}Props", if any_required { "" } else { "?" }, c.name);
    if !matches!(c.children, Children::None) {
        let _ = writeln!(out, "  children?: Array<TypedNode>");
    }
    let _ = writeln!(out, "  slots?: {{ {} }}", slot_fields.join("; "));
    let _ = writeln!(out, "  on?: {on}");
    out.push_str("}\n\n");
    out
}

fn name_rule(rule: NameRule) -> String {
    match rule {
        NameRule::None => "null".to_owned(),
        NameRule::OneOf { props, children } => {
            format!(
                "{{ oneOf: [{}], children: {children} }}",
                props.iter().map(|p| format!("'{p}'")).collect::<Vec<_>>().join(", ")
            )
        }
        NameRule::AltOrDecorative => "{ altOrDecorative: true }".to_owned(),
    }
}

fn binding(kind: BindingKind) -> &'static str {
    kind.as_str()
}

fn event_names(events: &[&EventSpec]) -> String {
    events.iter().map(|e| format!("'{}'", e.name)).collect::<Vec<_>>().join(", ")
}

/// The runtime table the renderer reads: interactivity, bindings, events, slots, tier.
fn meta_table() -> String {
    let mut out = String::new();
    out.push_str(
        "export type ComponentMeta = {\n  tier: 1 | 2 | 3\n  since: string\n  group: string\n  interactive: boolean\n  \
         /** The prop a positional Luau argument sets. */\n  positional: string | null\n  role: string\n  \
         name: { oneOf: string[]; children: boolean } | { altOrDecorative: true } | null\n  \
         /** Two-way props and how the host merges a write. */\n  bindings: { [prop: string]: 'text' | 'scalar' | 'collection' }\n  \
         events: string[]\n  slots: string[]\n  children: 'none' | 'any' | number\n  \
         /** Placeholder components accept any prop. */\n  openProps: boolean\n}\n\n",
    );
    out.push_str("export const COMPONENTS = {\n");
    for c in CATALOGUE {
        let bindings: Vec<String> = c
            .props
            .iter()
            .filter_map(|p| p.binding.map(|b| format!("{}: '{}'", ident(p.name), binding(b))))
            .collect();
        let events: Vec<&EventSpec> = c.effective_events().collect();
        let slots: Vec<String> = c
            .slots
            .iter()
            .chain(COMMON_SLOTS)
            .map(|s| format!("'{}{}'", s.name, if s.prefix { "*" } else { "" }))
            .collect();
        let children = match c.children {
            Children::None => "'none'".to_owned(),
            Children::Any => "'any'".to_owned(),
            Children::Max(n) => n.to_string(),
        };
        let _ = writeln!(
            out,
            "  {}: {{ tier: {}, since: '{}', group: '{}', interactive: {}, positional: {}, role: '{}', name: {}, bindings: {{ {} }}, events: [{}], slots: [{}], children: {}, openProps: {} }},",
            c.name,
            c.tier as u8,
            c.since,
            c.group.title(),
            c.interactive,
            c.positional.map_or_else(|| "null".to_owned(), |p| format!("'{p}'")),
            c.a11y.role,
            name_rule(c.a11y.name),
            bindings.join(", "),
            event_names(&events),
            slots.join(", "),
            children,
            c.open_props,
        );
    }
    out.push_str("} as const satisfies Record<ComponentName, ComponentMeta>\n\n");
    out
}

/// `EventPayloads['TextField.submit']`.
fn event_payloads() -> String {
    let mut out = String::from(
        "/** The payload of each event, by `Component.event`. */\nexport interface EventPayloads {\n",
    );
    let mut line = |key: String, payload: &[PropSpec]| {
        let fields = payload
            .iter()
            .map(|f| format!("{}{}: {}", ident(f.name), if f.required { "" } else { "?" }, ty(&f.ty)))
            .collect::<Vec<_>>()
            .join("; ");
        let _ = writeln!(out, "  '{key}': {{ {fields} }}");
    };
    for e in COMMON_EVENTS {
        line(format!("*.{}", e.name), e.payload);
    }
    for c in CATALOGUE {
        for e in c.events {
            line(format!("{}.{}", c.name, e.name), e.payload);
        }
    }
    out.push_str("}\n\n");
    out
}

fn expressions() -> String {
    let names: Vec<&str> = Func::ALL.iter().map(|f| f.name()).collect();
    let mut out = format!(
        "/** The closed, pure, presentation-only function set. */\nexport type FunctionName = {}\n\n",
        union(&names)
    );
    out.push_str("export const FUNCTIONS = {\n");
    for f in Func::ALL {
        let a = f.arity();
        let max = a.max.map_or_else(|| "null".to_owned(), |m| m.to_string());
        let _ = writeln!(out, "  '{}': {{ min: {}, max: {max} }},", f.name(), a.min);
    }
    out.push_str("} as const satisfies Record<FunctionName, { min: number; max: number | null }>\n\n");
    out
}

fn methods() -> String {
    let mut out = String::from("/** The JSON-RPC method table: who sends it, and the params and result types. */\nexport interface Methods {\n");
    for m in METHODS {
        let kind = match m.kind {
            agentos_domain::ui::protocol::MethodKind::Request => "request",
            agentos_domain::ui::protocol::MethodKind::Notification => "notification",
        };
        let direction = match m.direction {
            agentos_domain::ui::protocol::Direction::ClientToHost => "clientToHost",
            agentos_domain::ui::protocol::Direction::HostToClient => "hostToClient",
        };
        let result = match m.result {
            Some("null") => "null".to_owned(),
            Some(r) => r.to_owned(),
            None => "never".to_owned(),
        };
        let _ = writeln!(
            out,
            "  '{}': {{ kind: '{kind}'; direction: '{direction}'; params: {}; result: {result} }}",
            m.name, m.params
        );
    }
    out.push_str("}\n\nexport type MethodName = keyof Methods\n\n");
    out.push_str("/** Method names by direction, for dispatch tables. */\n");
    let list = |direction| {
        METHODS
            .iter()
            .filter(|m| m.direction == direction)
            .map(|m| format!("'{}'", m.name))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let _ = writeln!(
        out,
        "export const CLIENT_METHODS = [{}] as const\nexport const HOST_METHODS = [{}] as const",
        list(agentos_domain::ui::protocol::Direction::ClientToHost),
        list(agentos_domain::ui::protocol::Direction::HostToClient)
    );
    out
}
