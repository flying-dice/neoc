fn export(decl: &str) -> String {
    format!("export {decl}\n")
}

/// The whole file.
pub fn generate() -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    let _ = writeln!(out, "export const PROTO_VERSION = {PROTO_VERSION}");
    let _ = writeln!(out, "export const KIT_VERSION = '{KIT_VERSION}'\n");
    out.push_str(&prelude());
    out.push_str("\n// ---------------------------------------------------------------------------------------------\n");
    out.push_str("// Protocol (ts-rs)\n");
    out.push_str("// ---------------------------------------------------------------------------------------------\n\n");
    out.push_str(&protocol());
    out.push_str("\n// ---------------------------------------------------------------------------------------------\n");
    out.push_str("// Component schema (the catalogue)\n");
    out.push_str("// ---------------------------------------------------------------------------------------------\n\n");
    out.push_str(&tokens());
    out.push_str(&components());
    out.push_str(&expressions());
    out.push_str(&methods());
    out
}

