//! Dev-time adapter: code generation from the domain types. Not linked into the host.
//!
//! One source of truth (the Rust domain types) -> every consumer:
//!   * TypeScript for the Svelte client: `ts-rs` (reads the serde attributes)
//!   * JSON Schema: `schemars` (also what MCP tool schemas / validation can reuse)
//!   * Luau type definitions for app authors: our small emitter below, driven by the JSON Schema
//!
//! Add a type to the three lists in `typescript()` / `schemas()` and everything regenerates.

mod luau;

pub use luau::schema_to_luau;

use agentos_domain::{
    protocol::{DispatchUiEvent, UiPatches, UiTree},
    ui::{Direction, ListItem, UiEvent, UiNode, UiPatch},
    AppId,
};
use schemars::schema_for;
use serde_json::Value;
use ts_rs::TS;

fn export(decl: &str) -> String {
    format!("export {decl}\n")
}

/// `types.ts` for the client.
pub fn typescript() -> String {
    let mut out =
        String::from("// GENERATED by agentos-codegen from the Rust domain types. Do not edit.\n\n");
    let cfg = ts_rs::Config::default();
    for decl in [
        AppId::decl(&cfg),
        Direction::decl(&cfg),
        ListItem::decl(&cfg),
        UiNode::decl(&cfg),
        UiPatch::decl(&cfg),
        UiEvent::decl(&cfg),
        DispatchUiEvent::decl(&cfg),
        UiTree::decl(&cfg),
        UiPatches::decl(&cfg),
    ] {
        out.push_str(&export(&decl));
    }
    out
}

/// JSON Schemas, by type name.
pub fn schemas() -> Vec<(&'static str, Value)> {
    let to = |s: schemars::Schema| serde_json::to_value(s).unwrap_or(Value::Null);
    vec![
        ("UiNode", to(schema_for!(UiNode))),
        ("UiPatch", to(schema_for!(UiPatch))),
        ("UiEvent", to(schema_for!(UiEvent))),
        ("DispatchUiEvent", to(schema_for!(DispatchUiEvent))),
        ("UiTree", to(schema_for!(UiTree))),
        ("UiPatches", to(schema_for!(UiPatches))),
    ]
}

/// `ui.d.luau`-style definitions: `export type` aliases an app author can `require`/import in `--!strict`.
pub fn luau() -> String {
    let mut out = String::from(
        "--!strict\n-- GENERATED by agentos-codegen from the Rust domain types. Do not edit.\n\n",
    );
    let mut seen = std::collections::BTreeSet::new();
    for (name, schema) in schemas() {
        out.push_str(&schema_to_luau(name, &schema, &mut seen));
    }
    out
}
