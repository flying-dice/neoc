//! `types/generated/agentos.d.luau` (the definitions file) and `types/generated/app.luau` (the type shim).

use agentos_domain::ui::{components::PALETTE, source::ClientDecl};
use schemars::schema_for;
use std::fmt::Write as _;

use super::{core, literals};
use crate::schema_luau::schema_to_luau;

const APP_API: &str = include_str!("app_api.luau.tpl");

const HEADER: &str = "-- GENERATED by agentos-codegen from the Rust domain (crates/agentos-domain, `ui` module). Do not edit.\n\
-- Regenerate with `bun run codegen`; `bun run codegen:check` fails when this file is stale.\n\
--\n\
-- AgentOS app API: type definitions for app authors, consumed by `luau-lsp analyze --definitions` (`bun run\n\
-- lint:luau`) and by editors through luau-lsp's `definitionFiles` setting. Declares the global `app`; `ui.luau`\n\
-- (the constructors, `require(\"@agentos/ui\")`) carries the component types and an identical copy of the core\n\
-- types below, because a definitions file cannot export types to scripts.\n\n";

/// The definitions file.
pub fn definitions() -> String {
    let mut out = String::from(HEADER);
    out.push_str(&core(false));
    out.push('\n');
    let _ = write!(out, "type PaletteToken = {}\n\n", literals(PALETTE.values));
    out.push_str(&client_decl());
    out.push('\n');
    out.push_str(APP_API);
    out
}

/// `ClientDecl` and its enums, from the JSON Schema of the Rust types (the schemars to Luau path).
fn client_decl() -> String {
    let mut seen = std::collections::BTreeSet::new();
    let schema = serde_json::to_value(schema_for!(ClientDecl)).unwrap_or(serde_json::Value::Null);
    schema_to_luau("ClientDecl", &schema, &mut seen).replace("export type", "type")
}

/// Lets `require("@agentos/app")` resolve for the type checker. The host provides the real module.
pub fn app_shim() -> String {
    "--!strict\n\
-- GENERATED by agentos-codegen. Do not edit.\n\
-- A type shim: `require(\"@agentos/app\")` resolves to the global `app` declared in agentos.d.luau, so\n\
-- luau-lsp can type-check app code. The host provides the real module natively; this file is never loaded.\n\
return app\n"
        .to_owned()
}
