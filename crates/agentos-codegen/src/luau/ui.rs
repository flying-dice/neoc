const RUNTIME: &str = include_str!("runtime.luau.tpl");

/// The whole module.
pub fn module() -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str(&core(true));
    out.push('\n');
    out.push_str(&tokens());
    for c in CATALOGUE {
        out.push_str(&props_type(c));
    }
    out.push('\n');
    out.push_str(RUNTIME);
    out.push('\n');
    out.push_str(&definitions());
    out.push_str(&constructors());
    out.push_str(&helpers());
    out.push_str("\nreturn ui\n");
    out
}

const HEADER: &str = "--!strict\n\
-- GENERATED by agentos-codegen from the Rust domain (crates/agentos-domain, `ui` module). Do not edit.\n\
-- Regenerate with `bun run codegen`; `bun run codegen:check` fails when this file is stale.\n\
--\n\
-- The `ui.*` constructors: `local ui = require(\"@agentos/ui\")`. Table-call syntax, positional entries are\n\
-- children (or the text/title), named keys are props, slots and handlers:\n\
--\n\
--   ui.VStack { spacing = 2, ui.Text { \"Hello\", style = \"title1\" }, ui.Button { key = \"go\", title = \"Go\", onTap = fn } }\n\
--\n\
-- Constructors return plain node tables. There are no style modifiers: apps pick semantic tokens only.\n\n";

fn tokens() -> String {
    let mut out = String::new();
    for (name, def) in named_enums() {
        let _ = writeln!(out, "export type {name} = {}", literals(def.values));
    }
    for (name, def) in named_objects() {
        let _ = writeln!(out, "export type {name} = {}", object_type(def));
    }
    out.push('\n');
    out
}

/// The slot kinds of a component, as authors write them.
struct Slots<'a> {
    plain: Vec<&'a SlotSpec>,
    groups: BTreeMap<&'a str, Vec<&'a SlotSpec>>,
    prefixes: Vec<&'a SlotSpec>,
}

fn classify<'a>(slots: impl Iterator<Item = &'a SlotSpec>) -> Slots<'a> {
    let mut out = Slots { plain: Vec::new(), groups: BTreeMap::new(), prefixes: Vec::new() };
    for slot in slots {
        if slot.prefix {
            out.prefixes.push(slot);
        } else if let Some((group, _)) = split_group(slot.name) {
            out.groups.entry(group).or_default().push(slot);
        } else {
            out.plain.push(slot);
        }
    }
    out
}

fn group_name(prefix: &str) -> &str {
    prefix.trim_end_matches(':')
}

fn props_type(c: &ComponentSpec) -> String {
    let mut fields: Vec<String> = Vec::new();
    let mut by_name: BTreeMap<String, String> = BTreeMap::new();
    let mut order: Vec<String> = Vec::new();
    let put = |name: String,
               ty: String,
               required: bool,
               order: &mut Vec<String>,
               by_name: &mut BTreeMap<String, String>| {
        let ty = if required { ty } else { optional(&ty) };
        if by_name.insert(name.clone(), ty).is_none() {
            order.push(name);
        }
    };

    put("key".to_owned(), "string".to_owned(), c.interactive, &mut order, &mut by_name);
    for p in effective_props(c) {
        // a positional prop is given as the first entry, so it is never required by name
        let required = p.required && c.positional != Some(p.name);
        put(key(p.name), field_type(p), required, &mut order, &mut by_name);
    }
    // events
    for e in effective_events(c) {
        put(e.prop_name(), format!("Handler<{}>", payload_type(e.payload)), false, &mut order, &mut by_name);
    }
    // slots: a slot that shares a name with a prop widens that prop's type (a string, or a node)
    let slots = classify(c.effective_slots());
    for slot in &slots.plain {
        let row = slot.scope == Some(agentos_domain::ui::spec::SlotScope::Row);
        let slot_ty = if row { "Child | ((r: RowRefs) -> Node)" } else { "Child" };
        let name = key(slot.name);
        match by_name.get(&name).cloned() {
            Some(existing) => {
                let base =
                    existing.strip_suffix('?').unwrap_or(&existing).trim_matches(|c| c == '(' || c == ')');
                by_name.insert(name, format!("({base} | {slot_ty})?"));
            }
            None => put(name, slot_ty.to_owned(), slot.required, &mut order, &mut by_name),
        }
    }
    for (group, members) in &slots.groups {
        let inner: Vec<String> = members
            .iter()
            .map(|m| {
                let (_, sub) = split_group(m.name).unwrap_or(("", m.name));
                format!("{}: Child?", key(sub))
            })
            .collect();
        put(key(group), format!("{{ {} }}", inner.join(", ")), false, &mut order, &mut by_name);
    }
    for prefix in &slots.prefixes {
        put(key(group_name(prefix.name)), "{ [string]: Child }".to_owned(), false, &mut order, &mut by_name);
    }
    for name in &order {
        fields.push(format!("\t{name}: {},", by_name[name]));
    }
    // positional entries
    let positional = c.positional.and_then(|p| c.prop(p));
    let entry = match (positional, c.children) {
        (Some(p), Children::None) => Some(format!("Expr<{}>", paren_value(p))),
        (Some(p), _) => Some(format!("Expr<{}> | Child", paren_value(p))),
        (None, Children::None) => None,
        (None, _) => Some("Child".to_owned()),
    };
    if let Some(entry) = entry {
        fields.push(format!("\t[number]: {entry},"));
    }
    let mut out = String::new();
    let _ = writeln!(out, "-- {}", c.doc);
    let _ = writeln!(out, "export type {}Props = {{\n{}\n}}\n", c.name, fields.join("\n"));
    out
}

fn paren_value(p: &PropSpec) -> String {
    let ty = value_type(&p.ty);
    if ty.contains('|') && !ty.starts_with('(') {
        format!("({ty})")
    } else {
        ty
    }
}

/// The data the runtime builder reads: what each component accepts.
fn definitions() -> String {
    let mut out = String::from("local COMPONENTS: { [string]: any } = {\n");
    for c in CATALOGUE {
        out.push_str(&definition(c, c.name));
    }
    out.push_str("}\n");
    for (sugar, axis) in STACK_SUGAR {
        let _ = writeln!(out, "COMPONENTS.{sugar} = sugar(COMPONENTS.Stack, \"{sugar}\", \"{axis}\")");
    }
    out.push('\n');
    out
}

fn set(names: impl Iterator<Item = String>) -> String {
    let body: Vec<String> = names.map(|n| format!("{} = true", key(&n))).collect();
    if body.is_empty() {
        "{}".to_owned()
    } else {
        format!("{{ {} }}", body.join(", "))
    }
}

fn definition(c: &ComponentSpec, name: &str) -> String {
    let props = effective_props(c);
    let events: Vec<String> =
        effective_events(c).iter().map(|e| format!("{} = \"{}\"", e.prop_name(), e.name)).collect();
    let slots = classify(c.effective_slots());
    let plain_names = slots.plain.iter().map(|s| s.name.to_owned());
    let rows = slots
        .plain
        .iter()
        .filter(|s| s.scope == Some(agentos_domain::ui::spec::SlotScope::Row))
        .map(|s| s.name.to_owned());
    let groups: Vec<String> = slots
        .groups
        .iter()
        .map(|(group, members)| {
            let inner: Vec<String> = members
                .iter()
                .map(|m| {
                    let (_, sub) = split_group(m.name).unwrap_or(("", m.name));
                    format!("{} = \"{}\"", key(sub), m.name)
                })
                .collect();
            format!("{} = {{ {} }}", key(group), inner.join(", "))
        })
        .collect();
    let prefixes: Vec<String> =
        slots.prefixes.iter().map(|p| format!("{} = \"{}\"", key(group_name(p.name)), p.name)).collect();
    let bindings = props.iter().filter(|p| p.binding.is_some()).map(|p| p.name.to_owned());
    let sources = props.iter().filter(|p| contains_source(&p.ty)).map(|p| p.name.to_owned());
    let braces = |items: &[String]| {
        if items.is_empty() {
            "{}".to_owned()
        } else {
            format!("{{ {} }}", items.join(", "))
        }
    };
    format!(
        "\t{name} = {{\n\t\tname = \"{name}\",\n\t\tlabel = \"{name}\",\n\t\tpositional = {},\n\t\tprops = {},\n\t\tbindings = {},\n\t\tsources = {},\n\t\tevents = {},\n\t\tslots = {},\n\t\trows = {},\n\t\tgroups = {},\n\t\tprefixes = {},\n\t}},\n",
        c.positional.map_or_else(|| "nil".to_owned(), |p| format!("\"{p}\"")),
        set(props.iter().map(|p| p.name.to_owned())),
        set(bindings),
        set(sources),
        braces(&events),
        set(plain_names),
        set(rows),
        braces(&groups),
        braces(&prefixes),
    )
}

fn constructors() -> String {
    let mut out = String::from("local ui = {}\n\n");
    for c in CATALOGUE {
        let _ = writeln!(out, "-- {} (Tier {}, since {})", c.doc, c.tier as u8, c.since);
        let _ = writeln!(
            out,
            "function ui.{0}(props: {0}Props): Node\n\treturn build(COMPONENTS.{0}, props)\nend\n",
            c.name
        );
    }
    for (sugar, axis) in STACK_SUGAR {
        let which = if *axis == "v" { "vertical" } else { "horizontal" };
        let _ = writeln!(
            out,
            "-- A {which} `Stack`.\nfunction ui.{sugar}(props: StackProps): Node\n\treturn build(COMPONENTS.{sugar}, props)\nend\n"
        );
    }
    out
}

/// Parameters for a function of `arity`: `a: any, b: any` / `a: any, opts: any?` / `first: any, ...: any`.
fn params(arity: Arity) -> (String, String) {
    let names = ["a", "b", "c"];
    match arity.max {
        None => {
            let mut declared = vec!["first: any".to_owned()];
            declared.push("...: any".to_owned());
            (declared.join(", "), "first, ...".to_owned())
        }
        Some(max) => {
            let declared: Vec<String> = (0..max)
                .map(|i| format!("{}: {}", names[i], if i < arity.min { "any" } else { "any?" }))
                .collect();
            let passed: Vec<&str> = names.iter().take(max).copied().collect();
            (declared.join(", "), passed.join(", "))
        }
    }
}

/// The Luau name of an expression function: `and`/`or`/`not`/`if` are keywords.
fn helper_name(f: Func) -> String {
    match f {
        Func::And => "all".to_owned(),
        Func::Or => "any".to_owned(),
        Func::Not => "negate".to_owned(),
        Func::If => "when".to_owned(),
        other => other.name().strip_prefix("fmt.").unwrap_or(other.name()).to_owned(),
    }
}

fn helpers() -> String {
    let mut out = String::new();
    out.push_str(
        "-- Maps a Luau list to children. `nil` results are skipped.\n\
function ui.each<T>(list: { T }, body: (T, number) -> Node?): { Node }\n\
\tlocal out: { Node } = {}\n\
\tfor index, item in ipairs(list) do\n\
\t\tlocal node = body(item, index)\n\
\t\tif node ~= nil then\n\
\t\t\ttable.insert(out, node)\n\
\t\tend\n\
\tend\n\
\treturn out\n\
end\n\n",
    );
    out.push_str("-- Expressions: the closed function set, evaluated on the client. `and`, `or` and `not` are Luau keywords.\n");
    for f in Func::ALL.iter().filter(|f| !f.name().starts_with("fmt.")) {
        let (declared, passed) = params(f.arity());
        let _ = writeln!(
            out,
            "-- {}\nfunction ui.{}({declared}): Fn\n\treturn call(\"{}\", {passed})\nend\n",
            f.doc(),
            helper_name(*f),
            f.name()
        );
    }
    out.push_str("-- Formatting in the viewer's locale and time zone.\nlocal fmt = {}\nui.fmt = fmt\n\n");
    for f in Func::ALL.iter().filter(|f| f.name().starts_with("fmt.")) {
        let (declared, passed) = params(f.arity());
        let _ = writeln!(
            out,
            "-- {}\nfunction fmt.{}({declared}): Fn\n\treturn call(\"{}\", {passed})\nend\n",
            f.doc(),
            helper_name(*f),
            f.name()
        );
    }
    out.push_str(ACTIONS);
    out
}

/// `ui.act`: the client actions (one per `Action` variant; a contract test keeps them in step).
pub const ACTION_BUILDERS: &[(&str, &str)] = &[
    ("set", "set"),
    ("toggle", "toggle"),
    ("push", "nav.push"),
    ("pop", "nav.pop"),
    ("popToRoot", "nav.popToRoot"),
    ("focus", "focus"),
    ("scrollTo", "scrollTo"),
    ("copy", "copy"),
    ("emit", "emit"),
    ("seq", "seq"),
];

const ACTIONS: &str = r#"-- Client actions: run on the client with no round trip. Handlers take one, or a list mixing actions and functions.
local act = {}
ui.act = act

-- Write a client-managed or app-state ref.
function act.set(target: Ref<any>, value: any): Action
	return { ["do"] = "set", ref = refPath(target), value = value }
end

-- Flip a boolean ref.
function act.toggle(target: Ref<any>): Action
	return { ["do"] = "toggle", ref = refPath(target) }
end

-- Push a route (`{ name = "note", id = 7 }`) onto a navigation stack.
function act.push(route: { name: string, [string]: any }, stack: string?): Action
	return { ["do"] = "nav.push", stack = stack, route = route }
end

-- Pop the top route.
function act.pop(): Action
	return { ["do"] = "nav.pop" }
end

-- Pop to the root screen.
function act.popToRoot(): Action
	return { ["do"] = "nav.popToRoot" }
end

-- Move focus to the node with this key.
function act.focus(key: string): Action
	return { ["do"] = "focus", key = key }
end

-- Scroll to the node with this key.
function act.scrollTo(key: string): Action
	return { ["do"] = "scrollTo", key = key }
end

-- Copy text to the clipboard.
function act.copy(text: Expr<string>): Action
	return { ["do"] = "copy", text = text }
end

-- Report an event to the app (the handler of the node still runs on the host).
function act.emit(event: string?, payload: { [string]: any }?): Action
	return { ["do"] = "emit", event = event, payload = payload }
end

-- Run actions in order.
function act.seq(actions: { Action }): Action
	return { ["do"] = "seq", actions = actions }
end
"#;
