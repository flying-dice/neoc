//! `types/generated/ui.lua`.

use std::fmt::Write as _;

use agentos_domain::ui::{
    components::{CATALOGUE, STACK_SUGAR},
    expr::{Arity, Func},
    spec::{ComponentSpec, SlotScope},
};

use super::{classify, describe, group_name, helper_name, key};
use crate::walk::{contains_source, effective_events, effective_props, split_group};

const RUNTIME: &str = include_str!("runtime.lua.tpl");

/// The whole module.
pub fn module() -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str(RUNTIME);
    out.push('\n');
    out.push_str(&definitions());
    out.push_str(&constructors());
    out.push_str(&helpers());
    out.push_str("\nreturn ui\n");
    out
}

const HEADER: &str = "-- GENERATED by agentos-codegen from the Rust domain (crates/agentos-domain, `ui` module). Do not edit.\n\
-- Regenerate with `bun run codegen`; `bun run codegen:check` fails when this file is stale.\n\
--\n\
-- The `ui.*` constructors: `local ui = require(\"@agentos/ui\")`. Table-call syntax, positional entries are\n\
-- children (or the text/title), named keys are props, slots and handlers:\n\
--\n\
--   ui.VStack { spacing = 2, ui.Text { \"Hello\", style = \"title1\" }, ui.Button { key = \"go\", title = \"Go\", onTap = fn } }\n\
--\n\
-- Constructors return plain node tables. There are no style modifiers: apps pick semantic tokens only.\n\
-- The props, slots and events of every component are in docs/reference/components.md.\n\n";

/// The data the runtime builder reads: what each component accepts.
fn definitions() -> String {
    let mut out = String::from("local COMPONENTS = {\n");
    for c in CATALOGUE {
        out.push_str(&definition(c, c.name));
    }
    out.push_str("}\n");
    for (sugar, axis) in STACK_SUGAR {
        let _ = writeln!(out, "COMPONENTS.{sugar} = sugar(COMPONENTS.Stack, \"{sugar}\", \"{axis}\")");
    }
    out.push('\n');
    out
}

fn set(names: impl Iterator<Item = String>) -> String {
    let body: Vec<String> = names.map(|n| format!("{} = true", key(&n))).collect();
    if body.is_empty() {
        "{}".to_owned()
    } else {
        format!("{{ {} }}", body.join(", "))
    }
}

fn definition(c: &ComponentSpec, name: &str) -> String {
    let props = effective_props(c);
    let events: Vec<String> =
        effective_events(c).iter().map(|e| format!("{} = \"{}\"", e.prop_name(), e.name)).collect();
    let slots = classify(c.effective_slots());
    let plain_names = slots.plain.iter().map(|s| s.name.to_owned());
    let rows = slots.plain.iter().filter(|s| s.scope == Some(SlotScope::Row)).map(|s| s.name.to_owned());
    let groups: Vec<String> = slots
        .groups
        .iter()
        .map(|(group, members)| {
            let inner: Vec<String> = members
                .iter()
                .map(|m| {
                    let (_, sub) = split_group(m.name).unwrap_or(("", m.name));
                    format!("{} = \"{}\"", key(sub), m.name)
                })
                .collect();
            format!("{} = {{ {} }}", key(group), inner.join(", "))
        })
        .collect();
    let prefixes: Vec<String> =
        slots.prefixes.iter().map(|p| format!("{} = \"{}\"", key(group_name(p.name)), p.name)).collect();
    let bindings = props.iter().filter(|p| p.binding.is_some()).map(|p| p.name.to_owned());
    let sources = props.iter().filter(|p| contains_source(&p.ty)).map(|p| p.name.to_owned());
    let braces = |items: &[String]| {
        if items.is_empty() {
            "{}".to_owned()
        } else {
            format!("{{ {} }}", items.join(", "))
        }
    };
    format!(
        "\t{name} = {{\n\t\tname = \"{name}\",\n\t\tlabel = \"{name}\",\n\t\tpositional = {},\n\t\tprops = {},\n\t\tbindings = {},\n\t\tsources = {},\n\t\tevents = {},\n\t\tslots = {},\n\t\trows = {},\n\t\tgroups = {},\n\t\tprefixes = {},\n\t}},\n",
        c.positional.map_or_else(|| "nil".to_owned(), |p| format!("\"{p}\"")),
        set(props.iter().map(|p| p.name.to_owned())),
        set(bindings),
        set(sources),
        braces(&events),
        set(plain_names),
        set(rows),
        braces(&groups),
        braces(&prefixes),
    )
}

fn constructors() -> String {
    let mut out = String::from("local ui = {}\n\n");
    for c in CATALOGUE {
        let _ = writeln!(out, "{}", describe(c));
        let _ = writeln!(out, "function ui.{0}(props)\n\treturn build(COMPONENTS.{0}, props)\nend\n", c.name);
    }
    for (sugar, axis) in STACK_SUGAR {
        let which = if *axis == "v" { "vertical" } else { "horizontal" };
        let _ = writeln!(
            out,
            "-- A {which} `Stack`.\nfunction ui.{sugar}(props)\n\treturn build(COMPONENTS.{sugar}, props)\nend\n"
        );
    }
    out
}

/// Parameters for a function of `arity`: `a, b` / `first, ...`, and the same names to pass on. An optional
/// argument that was not given is `nil`, which ends the argument list.
fn params(arity: Arity) -> (String, String) {
    let names = ["a", "b", "c"];
    match arity.max {
        None => ("first, ...".to_owned(), "first, ...".to_owned()),
        Some(max) => {
            let declared: Vec<&str> = names.iter().take(max).copied().collect();
            (declared.join(", "), declared.join(", "))
        }
    }
}

fn helpers() -> String {
    let mut out = String::new();
    out.push_str(
        "-- Maps a Lua list to children. `nil` results are skipped.\n\
function ui.each(list, body)\n\
\tlocal out = {}\n\
\tfor index, item in ipairs(list) do\n\
\t\tlocal node = body(item, index)\n\
\t\tif node ~= nil then\n\
\t\t\ttable.insert(out, node)\n\
\t\tend\n\
\tend\n\
\treturn out\n\
end\n\n",
    );
    out.push_str("-- Expressions: the closed function set, evaluated on the client. `and`, `or` and `not` are Lua keywords.\n");
    for f in Func::ALL.iter().filter(|f| !f.name().starts_with("fmt.")) {
        let (declared, passed) = params(f.arity());
        let _ = writeln!(
            out,
            "-- {}\nfunction ui.{}({declared})\n\treturn call(\"{}\", {passed})\nend\n",
            f.doc(),
            helper_name(*f),
            f.name()
        );
    }
    out.push_str("-- Formatting in the viewer's locale and time zone.\nlocal fmt = {}\nui.fmt = fmt\n\n");
    for f in Func::ALL.iter().filter(|f| f.name().starts_with("fmt.")) {
        let (declared, passed) = params(f.arity());
        let _ = writeln!(
            out,
            "-- {}\nfunction fmt.{}({declared})\n\treturn call(\"{}\", {passed})\nend\n",
            f.doc(),
            helper_name(*f),
            f.name()
        );
    }
    out.push_str(ACTIONS);
    out
}

/// `ui.act`: the client actions (one per `Action` variant; a contract test keeps them in step).
pub const ACTION_BUILDERS: &[(&str, &str)] = &[
    ("set", "set"),
    ("toggle", "toggle"),
    ("push", "nav.push"),
    ("pop", "nav.pop"),
    ("popToRoot", "nav.popToRoot"),
    ("focus", "focus"),
    ("scrollTo", "scrollTo"),
    ("copy", "copy"),
    ("emit", "emit"),
    ("seq", "seq"),
];

const ACTIONS: &str = r#"-- Client actions: run on the client with no round trip. Handlers take one, or a list mixing actions and functions.
local act = {}
ui.act = act

-- Write a client-managed or app-state ref.
function act.set(target, value)
	return { ["do"] = "set", ref = refPath(target), value = value }
end

-- Flip a boolean ref.
function act.toggle(target)
	return { ["do"] = "toggle", ref = refPath(target) }
end

-- Push a route (`{ name = "note", id = 7 }`) onto a navigation stack (the optional `stack` names it).
function act.push(route, stack)
	return { ["do"] = "nav.push", stack = stack, route = route }
end

-- Pop the top route.
function act.pop()
	return { ["do"] = "nav.pop" }
end

-- Pop to the root screen.
function act.popToRoot()
	return { ["do"] = "nav.popToRoot" }
end

-- Move focus to the node with this key.
function act.focus(key)
	return { ["do"] = "focus", key = key }
end

-- Scroll to the node with this key.
function act.scrollTo(key)
	return { ["do"] = "scrollTo", key = key }
end

-- Copy text to the clipboard.
function act.copy(text)
	return { ["do"] = "copy", text = text }
end

-- Report an event to the app (the handler of the node still runs on the host).
function act.emit(event, payload)
	return { ["do"] = "emit", event = event, payload = payload }
end

-- Run actions in order.
function act.seq(actions)
	return { ["do"] = "seq", actions = actions }
end
"#;
