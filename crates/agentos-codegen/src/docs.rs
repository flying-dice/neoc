//! `docs/reference/components.md`: the component reference, emitted from the catalogue.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use agentos_domain::ui::{
    components::{CATALOGUE, COMMON_EVENTS, COMMON_PROPS, COMMON_SLOTS, STACK_SUGAR},
    expr::{Func, ENV_NAMES},
    protocol::{Direction, MethodKind, METHODS},
    spec::{Children, ComponentSpec, EventSpec, Group, NameRule, PropSpec, PropType, SlotSpec, Tier},
    KIT_VERSION, PROTO_VERSION,
};

use crate::walk::{named_enums, named_objects};

/// The whole document.
pub fn generate() -> String {
    let mut out = String::new();
    out.push_str(
        "<!-- GENERATED by agentos-codegen from the Rust domain (crates/agentos-domain, `ui` module). Do not edit. -->\n\
<!-- Regenerate with `bun run codegen`; `bun run codegen:check` fails when this file is stale. -->\n\n",
    );
    let _ = writeln!(out, "# Component reference\n");
    let _ = writeln!(
        out,
        "Kit **{KIT_VERSION}**, protocol **{PROTO_VERSION}**. Every app describes its views with these components; the client \
renders them with the kit. Apps never style: they pick semantic tokens only (spacing, text styles, palette roles, \
radii). The design is in `docs/architecture/ui-system.md`.\n"
    );
    out.push_str(&conventions());
    out.push_str(&index());
    for group in groups() {
        let _ = writeln!(out, "## {}\n", group.title());
        for c in CATALOGUE.iter().filter(|c| c.group == group) {
            out.push_str(&component(c));
        }
    }
    out.push_str(&common());
    out.push_str(&tokens());
    out.push_str(&expressions());
    out.push_str(&protocol());
    out
}

fn groups() -> Vec<Group> {
    let mut groups: Vec<Group> = CATALOGUE.iter().map(|c| c.group).collect();
    groups.sort();
    groups.dedup();
    groups
}

fn conventions() -> String {
    "## Conventions\n\n\
- **Lua**: `ui.X { positional, prop = value, slotName = node, onEvent = handler }`. Positional entries are children, \
or the component's *positional prop* (shown below). Constructors return plain node tables.\n\
- **Values**: a prop is a literal, a **ref** (`w.client.search`, a source field, `r.title` in a row template) or a call \
of the closed expression set (`ui.concat`, `ui.when`, `ui.fmt.*`, see [Expressions](#expressions)).\n\
- **Bindings** (`Binding`): two-way props. Pass a ref the control also writes (`w.client.x`, `source:bind(\"field\")`), \
never a plain value.\n\
- **Keys**: interactive nodes need an explicit `key`; test ids derive from keys (`app-key-key-...`), skipping auto keys \
(`_0`), slot names and the window root. A row template contributes `row-<rowKey>`.\n\
- **Handlers**: a Lua function, a `ui.act.*` action (runs on the client), or a list mixing both. Nothing executable \
crosses the wire.\n\
- **Tiers**: Tier 1 is final. Tier 2 and 3 are **placeholders**: the name exists, any prop is accepted, the schema is \
written when the first app that needs it is designed.\n\n"
        .to_owned()
}

fn index() -> String {
    let mut out =
        String::from("## Index\n\n| Component | Group | Tier | Since | Notes |\n|---|---|---|---|---|\n");
    for c in CATALOGUE {
        let notes = [c.interactive.then_some("interactive"), c.open_props.then_some("placeholder")]
            .into_iter()
            .flatten()
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            out,
            "| [`{}`](#{}) | {} | {} | {} | {} |",
            c.name,
            c.name.to_lowercase(),
            c.group.title(),
            c.tier as u8,
            c.since,
            notes
        );
    }
    out.push('\n');
    out
}

fn type_label(ty: &PropType) -> String {
    match ty {
        PropType::Str => "string".to_owned(),
        PropType::Number => "number".to_owned(),
        PropType::Int => "integer".to_owned(),
        PropType::Bool => "boolean".to_owned(),
        PropType::Json => "any".to_owned(),
        PropType::Source => "source".to_owned(),
        PropType::Enum(def) if def.name.is_empty() => {
            def.values.iter().map(|v| format!("`{v}`")).collect::<Vec<_>>().join(" \\| ")
        }
        PropType::Enum(def) => format!("[`{}`](#{})", def.name, def.name.to_lowercase()),
        PropType::Spacing => "spacing 0..8".to_owned(),
        PropType::Insets => "spacing \\| [`Insets`](#insets)".to_owned(),
        PropType::Frame => "`fill` \\| [`Frame`](#frame)".to_owned(),
        PropType::List(inner) => format!("list of {}", type_label(inner)),
        PropType::Object(def) if def.name.is_empty() => "object".to_owned(),
        PropType::Object(def) => format!("[`{}`](#{})", def.name, def.name.to_lowercase()),
        PropType::Union(options) => options.iter().map(type_label).collect::<Vec<_>>().join(" \\| "),
    }
}

fn prop_row(p: &PropSpec) -> String {
    let ty = match p.binding {
        Some(kind) => format!("Binding ({}) of {}", kind.as_str(), type_label(&p.ty)),
        None => type_label(&p.ty),
    };
    format!(
        "| `{}` | {} | {} | {} | {} |\n",
        p.name,
        ty,
        if p.required { "yes" } else { "" },
        p.default.map_or_else(String::new, |d| format!("`{d}`")),
        p.doc.replace('|', "\\|")
    )
}

fn component(c: &ComponentSpec) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "### {}\n", c.name);
    let _ = writeln!(out, "{}\n", c.doc);
    let mut facts = vec![format!("Tier {}", c.tier as u8), format!("since {}", c.since)];
    if c.interactive {
        facts.push("interactive (needs an explicit `key`)".to_owned());
    }
    if let Some(p) = c.positional {
        facts.push(format!("positional: `{p}`"));
    }
    if let Some(reason) = c.deprecated {
        facts.push(format!("deprecated: {reason}"));
    }
    let _ = writeln!(out, "{}\n", facts.join(" · "));
    if c.name == "Stack" {
        let sugar: Vec<String> =
            STACK_SUGAR.iter().map(|(name, axis)| format!("`ui.{name}` is `axis = \"{axis}\"`")).collect();
        let _ = writeln!(out, "{}.\n", sugar.join(", "));
    }
    out.push_str(&accessibility(c));
    if c.open_props {
        out.push_str("*Placeholder: props, events and slots are not final; any prop is accepted.*\n\n");
    }
    if !c.props.is_empty() {
        out.push_str("| Prop | Type | Required | Default | Notes |\n|---|---|---|---|---|\n");
        for p in c.props {
            out.push_str(&prop_row(p));
        }
        out.push('\n');
    }
    if !c.events.is_empty() {
        out.push_str(&events_table(c.events));
    }
    if !c.slots.is_empty() || !matches!(c.children, Children::None) {
        out.push_str(&slots_table(c));
    }
    out
}

fn accessibility(c: &ComponentSpec) -> String {
    let role = if c.a11y.role.is_empty() { String::new() } else { format!("role `{}`. ", c.a11y.role) };
    let name = match c.a11y.name {
        NameRule::None => String::new(),
        NameRule::OneOf { props, children } => {
            let props: Vec<String> = props.iter().map(|p| format!("`{p}`")).collect();
            format!(
                "**Accessible name required**: set {}{}.",
                props.join(" or "),
                if children { ", or give it content" } else { "" }
            )
        }
        NameRule::AltOrDecorative => {
            "**Accessible name required**: set `alt`, or `decorative = true`.".to_owned()
        }
    };
    if role.is_empty() && name.is_empty() {
        String::new()
    } else {
        format!("Accessibility: {role}{name}\n\n")
    }
}

fn payload_label(fields: &[PropSpec]) -> String {
    if fields.is_empty() {
        "none".to_owned()
    } else {
        fields
            .iter()
            .map(|f| {
                format!(
                    "`{}{}: {}`",
                    f.name,
                    if f.required { "" } else { "?" },
                    type_label(&f.ty).replace(" \\| ", " | ")
                )
            })
            .collect::<Vec<_>>()
            .join(", ")
    }
}

fn events_table(events: &[EventSpec]) -> String {
    let mut out = String::from("| Event | Lua prop | Payload | Notes |\n|---|---|---|---|\n");
    for e in events {
        let _ = writeln!(
            out,
            "| `{}` | `{}` | {} | {} |",
            e.name,
            e.prop_name(),
            payload_label(e.payload),
            e.doc
        );
    }
    out.push('\n');
    out
}

fn slots_table(c: &ComponentSpec) -> String {
    let mut out = String::from("| Slot | Lua key | Notes |\n|---|---|---|\n");
    let children = match c.children {
        Children::None => None,
        Children::Any => Some("positional entries: any number of nodes".to_owned()),
        Children::Max(n) => Some(format!("positional entries: at most {n}")),
    };
    if let Some(note) = children {
        let _ = writeln!(out, "| *(default)* | positional | {note} |");
    }
    for s in c.slots {
        out.push_str(&slot_row(s));
    }
    out.push('\n');
    out
}

fn slot_row(s: &SlotSpec) -> String {
    let lua = if s.prefix {
        format!("`{}.<name>`", s.name.trim_end_matches(':'))
    } else if let Some((group, sub)) = s.name.split_once('.') {
        format!("`{group} = {{ {sub} = ... }}`")
    } else {
        format!("`{}`", s.name)
    };
    let mut notes = Vec::new();
    if s.required {
        notes.push("required".to_owned());
    }
    if let Some(max) = s.max {
        notes.push(format!("at most {max}"));
    }
    if !s.doc.is_empty() {
        notes.push(s.doc.to_owned());
    }
    format!("| `{}` | {} | {} |\n", s.name, lua, notes.join("; "))
}

fn common() -> String {
    let mut out = String::from("## Common props, events and slots\n\nEvery node accepts these. A component's own prop of the same name overrides the common one.\n\n");
    out.push_str("| Prop | Type | Required | Default | Notes |\n|---|---|---|---|---|\n");
    for p in COMMON_PROPS {
        out.push_str(&prop_row(p));
    }
    out.push('\n');
    out.push_str(&events_table(COMMON_EVENTS));
    out.push_str("| Slot | Lua key | Notes |\n|---|---|---|\n");
    for s in COMMON_SLOTS {
        out.push_str(&slot_row(s));
    }
    out.push('\n');
    out
}

fn tokens() -> String {
    let mut out = String::from("## Tokens and shared types\n\n");
    let enums = named_enums();
    for (name, def) in &enums {
        let values: Vec<String> = def.values.iter().map(|v| format!("`{v}`")).collect();
        let _ = writeln!(out, "### {name}\n\n{}\n", values.join(", "));
    }
    let objects = named_objects();
    for (name, def) in &objects {
        let _ = writeln!(out, "### {name}\n");
        out.push_str("| Field | Type | Required | Default | Notes |\n|---|---|---|---|---|\n");
        for f in def.fields {
            out.push_str(&prop_row(f));
        }
        if def.open {
            out.push_str("| *(any other)* | any | | | extra fields are allowed |\n");
        }
        out.push('\n');
    }
    out
}

fn expressions() -> String {
    let mut out = String::from(
        "## Expressions\n\nA prop value is a literal, a ref, or a call of this closed set. Pure, presentation-only, no loops, no \
recursion, no I/O: it cannot hang or exfiltrate and costs at most its node count. Anything else is computed on the host.\n\n",
    );
    out.push_str("| Wire name | Lua | Arguments | Notes |\n|---|---|---|---|\n");
    for f in Func::ALL {
        let lua = match f {
            Func::And => "ui.all".to_owned(),
            Func::Or => "ui.any".to_owned(),
            Func::Not => "ui.negate".to_owned(),
            Func::If => "ui.when".to_owned(),
            other if other.name().starts_with("fmt.") => format!("ui.{}", other.name()),
            other => format!("ui.{}", other.name()),
        };
        let a = f.arity();
        let args = match a.max {
            Some(max) if max == a.min => max.to_string(),
            Some(max) => format!("{}..{max}", a.min),
            None => format!("{}+", a.min),
        };
        let _ = writeln!(out, "| `{}` | `{lua}` | {args} | {} |", f.name(), f.doc());
    }
    out.push('\n');
    let env: Vec<String> = ENV_NAMES.iter().map(|n| format!("`env.{n}`")).collect();
    let _ = writeln!(
        out,
        "**Refs** point into: `client.*` (client-managed state), `state.*` (app and window state), `src.<id>.<field>` (a source), \
`row.*` (the current row, inside a row template), `route.*` (inside a navigation destination) and {}. A `Binding` prop \
only accepts the writable namespaces: `client`, `state`, `src` and `row`.\n",
        env.join(", ")
    );
    out.push_str(
        "**Client actions** (`ui.act.*`): `set(ref, value)`, `toggle(ref)`, `push(route, stack?)`, `pop()`, `popToRoot()`, \
`focus(key)`, `scrollTo(key)`, `copy(text)`, `emit(event?, payload?)`, `seq{...}`.\n\n",
    );
    out
}

fn protocol() -> String {
    let mut out =
        String::from("## Protocol methods\n\nJSON-RPC 2.0 over `/rpc`, by-name params objects.\n\n");
    out.push_str("| Method | Direction | Kind | Params | Result | Notes |\n|---|---|---|---|---|---|\n");
    let mut by_direction: BTreeMap<u8, Vec<_>> = BTreeMap::new();
    for m in METHODS {
        by_direction.entry(u8::from(m.direction == Direction::HostToClient)).or_default().push(m);
    }
    for m in by_direction.values().flatten() {
        let direction =
            if m.direction == Direction::ClientToHost { "client to host" } else { "host to client" };
        let kind = if m.kind == MethodKind::Request { "request" } else { "notification" };
        let _ = writeln!(
            out,
            "| `{}` | {direction} | {kind} | `{}` | {} | {} |",
            m.name,
            m.params,
            m.result.map_or_else(String::new, |r| format!("`{r}`")),
            m.doc
        );
    }
    out.push('\n');
    let tiers: Vec<String> = [Tier::One, Tier::Two, Tier::Three]
        .iter()
        .map(|t| format!("Tier {}: {}", *t as u8, CATALOGUE.iter().filter(|c| c.tier == *t).count()))
        .collect();
    let _ = writeln!(out, "Catalogue size: {}.", tiers.join(", "));
    out
}
