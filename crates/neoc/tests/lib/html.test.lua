local _t       = require("lib:test")
local describe = _t.describe
local test     = _t.test
local expect   = _t.expect

local html = require("lib:html")

describe("html", function()

    -- escape -----------------------------------------------------------------

    describe("escape", function()
        test("XSS payload escapes all five entities", function()
            expect(html.escape([[<script>alert("xss")</script>]]))
                .toBe([[&lt;script&gt;alert(&quot;xss&quot;)&lt;/script&gt;]])
        end)
        test("apostrophe escapes to &apos;", function()
            expect(html.escape("it's")).toBe("it&apos;s")
        end)
        test("empty string is empty", function()
            expect(html.escape("")).toBe("")
        end)
        test("plain text passes through", function()
            expect(html.escape("hello")).toBe("hello")
        end)
        test("non-ASCII passes through unchanged", function()
            expect(html.escape("café")).toBe("café")
        end)
        test("multi-byte emoji passes through unchanged", function()
            expect(html.escape("🦀")).toBe("🦀")
        end)
        test("double-escape produces &amp;amp;", function()
            expect(html.escape("&amp;")).toBe("&amp;amp;")
        end)
    end)

    describe("escape opts are forward-compatible", function()
        test("empty table accepted", function()
            expect(html.escape("<b>", {})).toBe("&lt;b&gt;")
        end)
        test("context key ignored in v1", function()
            expect(html.escape("<b>", { context = "attribute" })).toBe("&lt;b&gt;")
        end)
        test("unknown keys ignored", function()
            expect(html.escape("<b>", { unknown = true })).toBe("&lt;b&gt;")
        end)
    end)

    -- unescape ---------------------------------------------------------------

    describe("unescape named entities", function()
        test("amp/lt/gt/quot/apos all reverse", function()
            expect(html.unescape("&amp;&lt;&gt;&quot;&apos;")).toBe([[&<>"']])
        end)
        test("HTML fragment round-trips through both calls", function()
            expect(html.unescape("&lt;b&gt;bold&lt;/b&gt;")).toBe("<b>bold</b>")
        end)
        test("unknown named entity passes through unchanged", function()
            expect(html.unescape("&notareal;")).toBe("&notareal;")
        end)
        test("named entity outside v1 set passes through unchanged", function()
            -- `&copy;` is real HTML5 but intentionally not supported in v1.
            -- Behaviour is documented as passthrough — flag if you "fix" this.
            expect(html.unescape("&copy;")).toBe("&copy;")
        end)
        test("missing semicolon — no partial match", function()
            expect(html.unescape("&amp")).toBe("&amp")
        end)
        test("space after ampersand — no partial match", function()
            expect(html.unescape("& amp;")).toBe("& amp;")
        end)
        test("bare trailing ampersand passes through", function()
            expect(html.unescape("foo&")).toBe("foo&")
        end)
    end)

    describe("unescape numeric references", function()
        test("decimal reference", function()
            expect(html.unescape("&#65;")).toBe("A")
        end)
        test("hex reference lowercase x", function()
            expect(html.unescape("&#x41;")).toBe("A")
        end)
        test("hex reference uppercase X", function()
            expect(html.unescape("&#X41;")).toBe("A")
        end)
        test("multiple references in one string", function()
            expect(html.unescape("&#x41;&#65;")).toBe("AA")
        end)
        test("NUL passes through (prevents NUL injection)", function()
            expect(html.unescape("&#0;")).toBe("&#0;")
        end)
        test("surrogate passes through", function()
            expect(html.unescape("&#xD800;")).toBe("&#xD800;")
        end)
        test("out-of-range decimal passes through (1114112 = 0x110000)", function()
            -- Issue spec cites `&#999999;` as out-of-range but 999999 =
            -- U+F423F is a valid scalar (PUA-A) — standard runtimes decode
            -- it. 1114112 is the actual first invalid codepoint. Flagged
            -- on the PR for the author to amend the spec table.
            expect(html.unescape("&#1114112;")).toBe("&#1114112;")
        end)
        test("decimal in private-use area decodes (counter to spec)", function()
            -- Counter-test for the spec correction: 999999 must decode.
            expect(html.unescape("&#999999;")).toBe("\u{F423F}")
        end)
        test("beyond Unicode max passes through", function()
            expect(html.unescape("&#x110000;")).toBe("&#x110000;")
        end)
        test("malformed empty numeric passes through", function()
            expect(html.unescape("&#;")).toBe("&#;")
        end)
        test("malformed empty hex passes through", function()
            expect(html.unescape("&#x;")).toBe("&#x;")
        end)
        test("invalid hex digits pass through", function()
            expect(html.unescape("&#xGG;")).toBe("&#xGG;")
        end)
        test("leading + in decimal passes through (matches Python/Go/Deno)", function()
            expect(html.unescape("&#+5;")).toBe("&#+5;")
        end)
        test("leading + in hex passes through", function()
            expect(html.unescape("&#x+5;")).toBe("&#x+5;")
        end)
    end)

    -- round-trip + invariants ------------------------------------------------

    describe("round-trip invariant", function()
        test("ASCII plain string", function()
            expect(html.unescape(html.escape("hello"))).toBe("hello")
        end)
        test("all five entities at once", function()
            expect(html.unescape(html.escape([[<>&"']]))).toBe([[<>&"']])
        end)
        test("empty string", function()
            expect(html.unescape(html.escape(""))).toBe("")
        end)
        test("double-escape does not corrupt", function()
            expect(html.unescape(html.escape("&amp;"))).toBe("&amp;")
        end)
        test("non-ASCII content", function()
            expect(html.unescape(html.escape("café"))).toBe("café")
        end)
        test("multi-byte emoji", function()
            expect(html.unescape(html.escape("🦀"))).toBe("🦀")
        end)
    end)

    describe("idempotence note", function()
        -- Documented non-idempotence: each `unescape` call performs one pass.
        -- Implementors must not "fix" this — it is correct behaviour.
        test("one pass: &amp;lt; -> &lt;", function()
            expect(html.unescape("&amp;lt;")).toBe("&lt;")
        end)
        test("two passes: &amp;lt; -> <", function()
            expect(html.unescape(html.unescape("&amp;lt;"))).toBe("<")
        end)
    end)
end)
