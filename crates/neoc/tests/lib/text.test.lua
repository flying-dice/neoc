local _t       = require("lib:test")
local describe = _t.describe
local test     = _t.test
local expect   = _t.expect

local text = require("lib:text")

describe("text", function()

    -- case conversion --------------------------------------------------------

    describe("to_camel_case", function()
        test("snake to camel", function()
            expect(text.to_camel_case("hello_world")).toBe("helloWorld")
        end)
        test("acronym HTTPSConnection", function()
            expect(text.to_camel_case("HTTPSConnection")).toBe("httpsConnection")
        end)
        test("trailing acronym getHTTPSURL", function()
            expect(text.to_camel_case("getHTTPSURL")).toBe("getHttpsurl")
        end)
        test("kebab to camel", function()
            expect(text.to_camel_case("kebab-case")).toBe("kebabCase")
        end)
        test("empty string", function()
            expect(text.to_camel_case("")).toBe("")
        end)
    end)

    describe("to_snake_case", function()
        test("camel to snake", function()
            expect(text.to_snake_case("helloWorld")).toBe("hello_world")
        end)
        test("acronym XMLParser", function()
            expect(text.to_snake_case("XMLParser")).toBe("xml_parser")
        end)
        test("already snake unchanged", function()
            expect(text.to_snake_case("already_snake")).toBe("already_snake")
        end)
        test("dots become word boundaries", function()
            expect(text.to_snake_case("with.dots.in")).toBe("with_dots_in")
        end)
        test("whitespace stripped", function()
            expect(text.to_snake_case("  spaces  ")).toBe("spaces")
        end)
    end)

    describe("to_kebab_case", function()
        test("camel to kebab", function()
            expect(text.to_kebab_case("helloWorld")).toBe("hello-world")
        end)
        test("acronym HTTPSConnection", function()
            expect(text.to_kebab_case("HTTPSConnection")).toBe("https-connection")
        end)
    end)

    describe("to_pascal_case", function()
        test("snake to pascal", function()
            expect(text.to_pascal_case("hello_world")).toBe("HelloWorld")
        end)
        test("acronym XMLParser pinned", function()
            expect(text.to_pascal_case("XMLParser")).toBe("XmlParser")
        end)
    end)

    describe("to_title_case", function()
        test("snake to title", function()
            expect(text.to_title_case("hello_world")).toBe("Hello World")
        end)
        test("camel to title", function()
            expect(text.to_title_case("helloWorld")).toBe("Hello World")
        end)
        test("acronym HTTPSConnection pinned", function()
            expect(text.to_title_case("HTTPSConnection")).toBe("Https Connection")
        end)
    end)

    describe("to_constant_case", function()
        test("camel to constant", function()
            expect(text.to_constant_case("helloWorld")).toBe("HELLO_WORLD")
        end)
        test("kebab to constant", function()
            expect(text.to_constant_case("kebab-case")).toBe("KEBAB_CASE")
        end)
    end)

    -- word_wrap --------------------------------------------------------------

    describe("word_wrap", function()
        test("fits within width", function()
            local s, err = text.word_wrap("hello world", 80)
            expect(err).toBeNil()
            expect(s).toBe("hello world")
        end)

        test("wraps at word boundary", function()
            local s = text.word_wrap("hello world", 5)
            expect(s).toBe("hello\nworld")
        end)

        test("break_words splits oversize words", function()
            local s = text.word_wrap("abcdefghij", 5, { break_words = true })
            expect(s).toBe("abcde\nfghij")
        end)

        test("without break_words oversize words overflow", function()
            local s = text.word_wrap("abcdefghij", 5)
            expect(s).toBe("abcdefghij")
        end)

        test("preserve_newlines=true keeps line breaks", function()
            local s = text.word_wrap("line1\nline2", 80, { preserve_newlines = true })
            expect(s).toBe("line1\nline2")
        end)

        test("preserve_newlines=false flattens to spaces", function()
            local s = text.word_wrap("line1\nline2", 80, { preserve_newlines = false })
            expect(s).toBe("line1 line2")
        end)

        test("width=0 errors", function()
            local v, e = text.word_wrap("hi", 0)
            expect(v).toBeNil()
            expect(string.find(e, "width must be > 0") ~= nil).toBeTruthy()
        end)

        test("empty string returns empty", function()
            expect(text.word_wrap("", 80)).toBe("")
        end)
    end)

    -- levenshtein ------------------------------------------------------------

    describe("levenshtein", function()
        test("kitten vs sitting", function()
            expect(text.levenshtein("kitten", "sitting")).toBe(3)
        end)
        test("empty vs abc", function()
            expect(text.levenshtein("", "abc")).toBe(3)
        end)
        test("equal strings distance 0", function()
            expect(text.levenshtein("abc", "abc")).toBe(0)
        end)
        test("symmetry", function()
            expect(text.levenshtein("foo", "bar")).toBe(text.levenshtein("bar", "foo"))
        end)
    end)

    -- closest ----------------------------------------------------------------

    describe("closest", function()
        test("ranks by ascending distance", function()
            local r = text.closest("teh", { "the", "tea", "ten" })
            -- "tea" and "ten" at distance 1, "the" at distance 2.
            expect(r[1].match).toBe("tea")
            expect(r[1].distance).toBe(1)
            expect(r[2].match).toBe("ten")
            expect(r[2].distance).toBe(1)
            expect(r[3].match).toBe("the")
            expect(r[3].distance).toBe(2)
        end)

        test("limit caps results", function()
            local r = text.closest("teh", { "the", "tea", "ten" }, { limit = 2 })
            expect(#r).toBe(2)
        end)

        test("empty candidates returns nil", function()
            local r = text.closest("x", {})
            expect(r).toBeNil()
        end)

        test("limit=0 returns empty table", function()
            local r = text.closest("x", { "a", "b" }, { limit = 0 })
            expect(#r).toBe(0)
        end)

        test("exact match at distance 0", function()
            local r = text.closest("the", { "the", "tea" })
            expect(r[1].match).toBe("the")
            expect(r[1].distance).toBe(0)
        end)
    end)

    -- truncate ---------------------------------------------------------------

    describe("truncate", function()
        test("char boundary with ellipsis", function()
            expect(text.truncate("hello world", 8)).toBe("hello...")
        end)
        test("word boundary with ellipsis", function()
            expect(text.truncate("hello world", 8, { boundary = "word" })).toBe("hello...")
        end)
        test("returns unchanged when short enough", function()
            expect(text.truncate("hi", 8)).toBe("hi")
        end)
        test("max_len=3 returns ellipsis only", function()
            expect(text.truncate("hello", 3)).toBe("...")
        end)
        test("max_len<3 drops ellipsis, takes prefix", function()
            expect(text.truncate("hello", 2)).toBe("he")
        end)
        test("empty input passes through", function()
            expect(text.truncate("", 5)).toBe("")
        end)
        test("invalid boundary errors", function()
            local v, e = text.truncate("abc def", 5, { boundary = "byte" })
            expect(v).toBeNil()
            expect(string.find(e, "\"char\" or \"word\"") ~= nil).toBeTruthy()
        end)
    end)

    -- pad / center -----------------------------------------------------------

    describe("pad_left", function()
        test("default space fill", function()
            expect(text.pad_left("42", 5)).toBe("   42")
        end)
        test("custom fill char", function()
            expect(text.pad_left("42", 5, "0")).toBe("00042")
        end)
        test("already wide enough", function()
            expect(text.pad_left("abcdef", 3)).toBe("abcdef")
        end)
        test("empty fill rejected", function()
            local v, e = text.pad_left("x", 5, "")
            expect(v).toBeNil()
            expect(string.find(e, "exactly one character") ~= nil).toBeTruthy()
        end)
        test("multi-char fill rejected", function()
            local v, e = text.pad_left("x", 5, "ab")
            expect(v).toBeNil()
            expect(string.find(e, "exactly one character") ~= nil).toBeTruthy()
        end)
    end)

    describe("pad_right", function()
        test("default space fill", function()
            expect(text.pad_right("name", 10)).toBe("name      ")
        end)
        test("dot fill", function()
            expect(text.pad_right("name", 7, ".")).toBe("name...")
        end)
    end)

    describe("center", function()
        test("even padding", function()
            expect(text.center("title", 11)).toBe("   title   ")
        end)
        test("uneven padding extra on right", function()
            expect(text.center("ab", 5)).toBe(" ab  ")
        end)
        test("already wide", function()
            expect(text.center("abcdef", 3)).toBe("abcdef")
        end)
    end)

    -- slugify ----------------------------------------------------------------

    describe("slugify", function()
        test("punctuation collapsed to hyphens", function()
            expect(text.slugify("Hello, World!")).toBe("hello-world")
        end)
        test("leading and trailing whitespace stripped", function()
            expect(text.slugify("  leading trailing  ")).toBe("leading-trailing")
        end)
        test("hyphen runs collapse", function()
            expect(text.slugify("---multiple---hyphens---")).toBe("multiple-hyphens")
        end)
        test("diacritics stripped to ASCII", function()
            expect(text.slugify("Café résumé")).toBe("cafe-resume")
        end)
        test("empty stays empty", function()
            expect(text.slugify("")).toBe("")
        end)
        -- Pin the full deunicode transliteration policy — locks the
        -- contract beyond bare diacritic strip so the docstring claims hold.
        test("CJK transliterates to pinyin-style ASCII", function()
            expect(text.slugify("日本語")).toBe("ri-ben-yu")
        end)
        test("Cyrillic transliterates to Latin", function()
            expect(text.slugify("Привет мир")).toBe("privet-mir")
        end)
        test("emoji become English names", function()
            expect(text.slugify("hello 😀")).toBe("hello-grinning")
        end)
    end)


    -- trim -------------------------------------------------------------------

    describe("trim", function()
        test("both ends", function()
            expect(text.trim("  \t hello world \r\n")).toBe("hello world")
        end)
        test("one end", function()
            expect(text.trim_start("  hi  ")).toBe("hi  ")
            expect(text.trim_end("  hi  ")).toBe("  hi")
        end)
        test("Unicode white space, which %s does not match", function()
            expect(text.trim("\u{00A0}\u{3000}hi\u{2003}\u{2028}")).toBe("hi")
        end)
        test("inner white space stays", function()
            expect(text.trim(" a  b ")).toBe("a  b")
        end)
        test("empty and all white space are empty", function()
            expect(text.trim("")).toBe("")
            expect(text.trim(" \n\t ")).toBe("")
            expect(text.trim_start(" \n\t ")).toBe("")
            expect(text.trim_end(" \n\t ")).toBe("")
        end)
        test("bytes that are not text are an error, not a crash", function()
            for _, f in ipairs({ text.trim, text.trim_start, text.trim_end }) do
                expect((pcall(f, " \xff "))).toBe(false)
            end
        end)
    end)

    -- clip -------------------------------------------------------------------

    describe("clip", function()
        test("short text is returned whole", function()
            expect(text.clip("hello", 5)).toBe("hello")
            expect(text.clip("hello", 10, "…")).toBe("hello")
            expect(text.clip("", 0, "…")).toBe("")
        end)
        test("cuts to max characters", function()
            expect(text.clip("hello world", 5)).toBe("hello")
            expect(text.clip("hello", 0)).toBe("")
        end)
        test("the ellipsis counts toward max", function()
            expect(text.clip("hello world", 5, "…")).toBe("hell…")
            expect(text.clip("hello world", 5, "...")).toBe("he...")
            expect(text.clip("hello world", 3, "...")).toBe("...")
        end)
        test("an ellipsis longer than max is left out", function()
            expect(text.clip("hello world", 2, "...")).toBe("he")
            expect(text.clip("hello", 0, "…")).toBe("")
        end)
        test("counts characters, not bytes", function()
            expect(text.clip("héllo wörld", 4)).toBe("héll")
            expect(text.clip("日本語のテキスト", 3)).toBe("日本語")
        end)
        test("never cuts inside a character", function()
            -- a flag is two code points, a family is seven, an accented letter may be two
            expect(text.clip("🇬🇧🇫🇷🇩🇪", 2)).toBe("🇬🇧🇫🇷")
            expect(text.clip("👨‍👩‍👧‍👦!", 1)).toBe("👨‍👩‍👧‍👦")
            expect(text.clip("e\u{0301}e\u{0301}e\u{0301}", 2)).toBe("e\u{0301}e\u{0301}")
            expect(text.clip("🇬🇧🇫🇷🇩🇪", 2, "…")).toBe("🇬🇧…")
        end)
        test("a max beyond any text is the whole text", function()
            expect(text.clip("hello", 2 ^ 53)).toBe("hello")
            expect(text.clip("hello", 2 ^ 63, "…")).toBe("hello")
            expect(text.clip("hello", 1e300)).toBe("hello")
            expect(text.clip("hello", math.huge)).toBe("hello")
        end)
        test("an ellipsis far longer than max is left out", function()
            expect(text.clip("hello world", 3, string.rep("…", 1000))).toBe("hel")
        end)
        test("bounds characters, not bytes", function()
            local marked = "a" .. string.rep("\u{0301}", 100)
            expect(text.clip(marked .. "b", 1)).toBe(marked)
        end)
        test("a negative or fractional max, or bytes that are not text, raise", function()
            expect((pcall(text.clip, "hello", -1))).toBe(false)
            expect((pcall(text.clip, "hello", 1.5))).toBe(false)
            expect((pcall(text.clip, "hello", 0 / 0))).toBe(false)
            expect((pcall(text.clip, "hello", -math.huge))).toBe(false)
            expect((pcall(text.clip, "hello", -0.5))).toBe(false)
            expect((pcall(text.clip, "hello", "two"))).toBe(false)
            expect((pcall(text.clip, "hello"))).toBe(false)
            expect((pcall(text.clip, "\xff\xff", 1))).toBe(false)
            expect((pcall(text.clip, "hello", 1, "\xff"))).toBe(false)
            local _, err = pcall(text.clip, "hello", -1)
            expect(tostring(err)).toContain("text.clip: max must be a whole number >= 0")
        end)
    end)

    -- to_valid_utf8 ----------------------------------------------------------

    describe("to_valid_utf8", function()
        test("valid text is unchanged", function()
            expect(text.to_valid_utf8("")).toBe("")
            expect(text.to_valid_utf8("héllo 日本 🇬🇧")).toBe("héllo 日本 🇬🇧")
            expect(text.to_valid_utf8("a\0b")).toBe("a\0b")
        end)
        test("a byte that is not a character becomes U+FFFD", function()
            expect(text.to_valid_utf8("a\xffb")).toBe("a\u{FFFD}b")
            expect(text.to_valid_utf8("\x80")).toBe("\u{FFFD}")
        end)
        test("a character cut short becomes U+FFFD", function()
            -- the first two bytes of the three of U+20AC
            expect(text.to_valid_utf8("ab\xe2\x82")).toBe("ab\u{FFFD}")
            expect(text.to_valid_utf8("\x82\xacab")).toBe("\u{FFFD}\u{FFFD}ab")
        end)
        test("a surrogate and an overlong form are not characters", function()
            expect(text.to_valid_utf8("\xed\xa0\x80")).toBe("\u{FFFD}\u{FFFD}\u{FFFD}")
            expect(text.to_valid_utf8("\xc0\xaf")).toBe("\u{FFFD}\u{FFFD}")
        end)
        test("the result is text every other function takes", function()
            expect(text.trim(text.to_valid_utf8(" \xff "))).toBe("\u{FFFD}")
        end)
    end)

    -- strip_ansi -------------------------------------------------------------

    describe("strip_ansi", function()
        test("plain text is unchanged", function()
            expect(text.strip_ansi("")).toBe("")
            expect(text.strip_ansi("héllo 日本\n\tindented")).toBe("héllo 日本\n\tindented")
        end)
        test("colours go", function()
            expect(text.strip_ansi("\27[32mok\27[0m \27[1;31mfailed\27[m")).toBe("ok failed")
            expect(text.strip_ansi("\27[38;2;255;0;0mred\27[39m")).toBe("red")
        end)
        test("cursor movement and line erasing go", function()
            expect(text.strip_ansi("\27[2K\27[1Gdone\27[?25h")).toBe("done")
        end)
        test("a window title and a hyperlink go, the link's words stay", function()
            expect(text.strip_ansi("\27]0;title\7text")).toBe("text")
            expect(text.strip_ansi("\27]8;;https://example.com\27\\link\27]8;;\27\\")).toBe("link")
        end)
        test("control characters go, line feeds and tabs stay", function()
            expect(text.strip_ansi("a\0b\7c\8d\127e")).toBe("abcde")
            expect(text.strip_ansi("one\r\ntwo\n\tthree\r")).toBe("one\ntwo\n\tthree")
        end)
        test("a sequence cut short at the end takes nothing with it", function()
            expect(text.strip_ansi("ok\27[")).toBe("ok")
            expect(text.strip_ansi("ok\27")).toBe("ok")
        end)
        test("a sequence that is never ended takes the rest of its line and no more", function()
            -- a window title (OSC), a device control string (DCS) and an application command (APC)
            expect(text.strip_ansi("a\27]0;title\nline2\nline3")).toBe("a\nline2\nline3")
            expect(text.strip_ansi("a\27Pxx\nline2")).toBe("a\nline2")
            expect(text.strip_ansi("a\27_xx\nline2\n")).toBe("a\nline2\n")
            expect(text.strip_ansi("a\27[38;5\n\27[1mline2")).toBe("a\nline2")
        end)
        test("a C1 control written as a character goes, and starts no sequence", function()
            expect(text.strip_ansi("a\u{9b}31mb")).toBe("a31mb")
        end)
        test("bytes that are not text are an error, not a crash", function()
            expect((pcall(text.strip_ansi, "\27[31m\xff"))).toBe(false)
            expect(text.strip_ansi(text.to_valid_utf8("\27[31m\xff"))).toBe("\u{FFFD}")
        end)
    end)

    describe("pad sizes", function()
        test("a negative width is an error", function()
            for _, f in ipairs({ text.pad_left, text.pad_right, text.center }) do
                local v, err = f("x", -1)
                expect(v).toBeNil()
                expect(err).toContain("width must be non-negative")
            end
        end)

        test("a width no call may allocate is an error", function()
            for _, f in ipairs({ text.pad_left, text.pad_right, text.center }) do
                local v, err = f("x", 2 ^ 40)
                expect(v).toBeNil()
                expect(err).toContain("too large")
            end
        end)
    end)
end)
