local _t       = require("lib:test")
local describe = _t.describe
local test     = _t.test
local expect   = _t.expect

local keyring = require("vnd:keyring")

-- A mock store: the suite never reaches the credential store of whoever runs it. (`keyring.store()` is the
-- operating system's; the Rust tests of the module have one ignored test against it.)
local store = keyring.mock()

describe("keyring", function()

    describe("a password", function()
        test("is kept, read back and replaced", function()
            local entry = assert(store:entry("example.com", "ada"))
            expect(entry:set_password("first")).toBe(true)
            expect(entry:get_password()).toBe("first")
            expect(entry:set_password("second")).toBe(true)
            expect(entry:get_password()).toBe("second")
        end)

        test("is the same credential through another entry of the same name", function()
            assert(assert(store:entry("example.com", "shared")):set_password("one"))
            expect(assert(store:entry("example.com", "shared")):get_password()).toBe("one")
        end)

        test("that is not there is nil, and not an error", function()
            local entry = assert(store:entry("example.com", "nobody"))
            local password, err = entry:get_password()
            expect(password).toBeNil()
            expect(err).toBeNil()
        end)

        test("is deleted once: true, then false", function()
            local entry = assert(store:entry("example.com", "going"))
            assert(entry:set_password("gone soon"))
            expect(entry:delete_credential()).toBe(true)
            expect(entry:get_password()).toBeNil()
            local again, err = entry:delete_credential()
            expect(again).toBe(false)
            expect(err).toBeNil()
        end)

        test("does not reach another store", function()
            assert(assert(store:entry("example.com", "here")):set_password("only here"))
            expect(assert(keyring.mock():entry("example.com", "here")):get_password()).toBeNil()
        end)
    end)

    describe("a secret", function()
        test("is the bytes that were stored", function()
            local entry = assert(store:entry("example.com", "key"))
            expect(entry:set_secret("\0\255bytes\0")).toBe(true)
            expect(entry:get_secret()).toBe("\0\255bytes\0")
        end)

        test("that is not text is bad_encoding as a password, and is not in the error", function()
            local entry = assert(store:entry("example.com", "binary"))
            assert(entry:set_secret("\255hunter2"))
            local password, err = entry:get_password()
            expect(password).toBeNil()
            expect(keyring.error_kind(err)).toBe("bad_encoding")
            expect(string.find(err, "hunter2", 1, true)).toBeNil()
        end)
    end)

    describe("an entry", function()
        test("says what it was made from", function()
            local service, user = assert(store:entry("example.com", "ada")):get_specifiers()
            expect(service).toBe("example.com")
            expect(user).toBe("ada")
        end)

        test("of a service that is not text is refused", function()
            local entry, err = store:entry("\255", "ada")
            expect(entry).toBeNil()
            expect(err).toBe("keyring.entry: invalid_input: the service is not UTF-8 text")
        end)
    end)

    describe("search", function()
        test("returns the entries that match", function()
            local own = keyring.mock()
            assert(assert(own:entry("example.com", "ada")):set_password("a"))
            assert(assert(own:entry("example.com", "grace")):set_password("g"))
            assert(assert(own:entry("other.org", "ada")):set_password("o"))
            expect(#assert(own:search())).toBe(3)
            local found = assert(own:search({ service = "example", user = "grace" }))
            expect(#found).toBe(1)
            expect(found[1]:get_password()).toBe("g")
        end)

        test("refuses a spec that is not text under text", function()
            local found, err = store:search({ service = 1 })
            expect(found).toBeNil()
            expect(keyring.error_kind(err)).toBe("invalid_input")
        end)
    end)

    describe("error_kind", function()
        test("is nil for a string that is not this module's, and for nil", function()
            expect(keyring.error_kind("bollard.ping: connect: refused")).toBeNil()
            expect(keyring.error_kind(nil)).toBeNil()
        end)
    end)

    describe("error_message", function()
        test("is what follows the kind", function()
            local entry, err = keyring.mock():entry("\255", "ada")
            expect(entry).toBeNil()
            local message = keyring.error_message(err)
            expect(message ~= "").toBe(true)
            expect(err).toBe("keyring.entry: invalid_input: " .. message)
        end)

        test("is nil for a string that is not this module's, and for nil", function()
            expect(keyring.error_message("bollard.ping: connect: refused")).toBeNil()
            expect(keyring.error_message("keyring.store: not_a_kind: x")).toBeNil()
            expect(keyring.error_message(nil)).toBeNil()
        end)
    end)
end)
