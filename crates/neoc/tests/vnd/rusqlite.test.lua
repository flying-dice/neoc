local _t       = require("lib:test")
local describe = _t.describe
local test     = _t.test
local expect   = _t.expect

local fs = require("std:fs")
local rusqlite = require("vnd:rusqlite")

fs.create_dir_all(".tmp")

describe("rusqlite", function()

    -- open ---------------------------------------------------------------------

    describe("open", function()
        test(":memory: returns a database handle", function()
            local db, err = rusqlite.open(":memory:")
            expect(err).toBeNil()
            expect(db).toBeTruthy()
            db:close()
        end)

        test("file path opens (creating if missing)", function()
            local db, err = rusqlite.open(".tmp/sqlite_create.db")
            expect(err).toBeNil()
            expect(db).toBeTruthy()
            db:execute("CREATE TABLE IF NOT EXISTS t (id INTEGER)")
            db:close()
        end)
    end)

    -- execute ------------------------------------------------------------------

    describe("execute", function()
        test("CREATE TABLE returns rows_affected = 0", function()
            local db = rusqlite.open(":memory:")
            local n, err = db:execute("CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)")
            expect(err).toBeNil()
            expect(n).toBe(0)
            db:close()
        end)

        test("INSERT returns rows_affected", function()
            local db = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)")
            local n, err = db:execute("INSERT INTO t (v) VALUES (?)", "hello")
            expect(err).toBeNil()
            expect(n).toBe(1)
            db:close()
        end)

        test("UPDATE returns rows_affected", function()
            local db = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)")
            db:execute("INSERT INTO t (v) VALUES (?)", "a")
            db:execute("INSERT INTO t (v) VALUES (?)", "b")
            local n = db:execute("UPDATE t SET v = ? WHERE v = ?", "x", "a")
            expect(n).toBe(1)
            db:close()
        end)

        test("invalid SQL returns error", function()
            local db = rusqlite.open(":memory:")
            local n, err = db:execute("NOT VALID SQL")
            expect(n).toBeNil()
            expect(err).toContain("rusqlite.execute:")
            db:close()
        end)

        test("a second statement is rejected, not silently dropped", function()
            -- rusqlite 0.43: one statement per call. Older versions ran only
            -- the first statement and ignored the rest.
            local db = rusqlite.open(":memory:")
            local n, err = db:execute("CREATE TABLE a (x INTEGER); CREATE TABLE b (x INTEGER)")
            expect(n).toBeNil()
            expect(err).toContain("rusqlite.execute:")
            expect(err).toContain("Multiple statements")
            expect(#db:query("SELECT name FROM sqlite_master WHERE type = 'table'")).toBe(0)
            db:close()
        end)

        test("empty or comment-only SQL is an error", function()
            local db = rusqlite.open(":memory:")
            local n, err = db:execute("")
            expect(n).toBeNil()
            expect(err).toBe("rusqlite.execute: SQL is empty or comment only")
            local n2, err2 = db:execute("-- just a comment")
            expect(n2).toBeNil()
            expect(err2).toBe("rusqlite.execute: SQL is empty or comment only")
            db:close()
        end)

        test("binds nil as NULL", function()
            local db = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (v TEXT)")
            db:execute("INSERT INTO t (v) VALUES (?)", nil)
            local row = db:query_one("SELECT v FROM t")
            expect(row.v).toBeNil()
            db:close()
        end)
    end)

    -- query --------------------------------------------------------------------

    describe("query", function()
        test("returns array of row tables", function()
            local db = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)")
            db:execute("INSERT INTO t (v) VALUES (?)", "a")
            db:execute("INSERT INTO t (v) VALUES (?)", "b")
            local rows, err = db:query("SELECT id, v FROM t ORDER BY id")
            expect(err).toBeNil()
            expect(#rows).toBe(2)
            expect(rows[1].id).toBe(1)
            expect(rows[1].v).toBe("a")
            expect(rows[2].id).toBe(2)
            expect(rows[2].v).toBe("b")
            db:close()
        end)

        test("empty result returns empty array", function()
            local db = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (id INTEGER)")
            local rows, err = db:query("SELECT * FROM t")
            expect(err).toBeNil()
            expect(#rows).toBe(0)
            db:close()
        end)

        test("WHERE with parameters", function()
            local db = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)")
            db:execute("INSERT INTO t (v) VALUES (?)", "a")
            db:execute("INSERT INTO t (v) VALUES (?)", "b")
            local rows = db:query("SELECT v FROM t WHERE v = ?", "b")
            expect(#rows).toBe(1)
            expect(rows[1].v).toBe("b")
            db:close()
        end)

        test("REAL columns become numbers", function()
            local db = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (x REAL)")
            db:execute("INSERT INTO t (x) VALUES (?)", 3.14)
            local row = db:query_one("SELECT x FROM t")
            expect(row.x).toBe(3.14)
            db:close()
        end)

        test("BLOB round-trips through bytes", function()
            local db = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (b BLOB)")
            db:execute("INSERT INTO t (b) VALUES (?)", "\0\1\2\254\255")
            local row = db:query_one("SELECT b FROM t")
            expect(row.b).toBe("\0\1\2\254\255")
            db:close()
        end)
    end)

    -- query_one ----------------------------------------------------------------

    describe("multiple statements", function()
        test("query and query_one reject them too", function()
            local db = rusqlite.open(":memory:")
            local rows, err = db:query("SELECT 1 AS a; SELECT 2 AS a")
            expect(rows).toBeNil()
            expect(err).toContain("rusqlite.query:")
            expect(err).toContain("Multiple statements")
            local row, err2 = db:query_one("SELECT 1 AS a; SELECT 2 AS a")
            expect(row).toBeNil()
            expect(err2).toContain("rusqlite.query_one:")
            expect(err2).toContain("Multiple statements")
            db:close()
        end)

        test("separate calls run each statement", function()
            local db = rusqlite.open(":memory:")
            expect(db:execute("CREATE TABLE a (x INTEGER)")).toBe(0)
            expect(db:execute("CREATE TABLE b (x INTEGER)")).toBe(0)
            expect(#db:query("SELECT name FROM sqlite_master WHERE type = 'table'")).toBe(2)
            db:close()
        end)
    end)

    describe("query_one", function()
        test("returns single row table", function()
            local db = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)")
            db:execute("INSERT INTO t (v) VALUES (?)", "alice")
            local row, err = db:query_one("SELECT id, v FROM t WHERE id = ?", 1)
            expect(err).toBeNil()
            expect(row.id).toBe(1)
            expect(row.v).toBe("alice")
            db:close()
        end)

        test("returns nil on no match", function()
            local db = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (id INTEGER)")
            local row, err = db:query_one("SELECT * FROM t WHERE id = ?", 999)
            expect(err).toBeNil()
            expect(row).toBeNil()
            db:close()
        end)
    end)

    -- prepare ------------------------------------------------------------------

    describe("prepare", function()
        test("execute reuses sql", function()
            local db   = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)")
            local ins  = db:prepare("INSERT INTO t (v) VALUES (?)")
            expect(ins:execute("a")).toBe(1)
            expect(ins:execute("b")).toBe(1)
            local rows = db:query("SELECT v FROM t ORDER BY id")
            expect(rows[1].v).toBe("a")
            expect(rows[2].v).toBe("b")
            db:close()
        end)

        test("query_one returns row", function()
            local db  = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)")
            db:execute("INSERT INTO t (v) VALUES (?)", "alice")
            local sel = db:prepare("SELECT id, v FROM t WHERE id = ?")
            local row = sel:query_one(1)
            expect(row.id).toBe(1)
            expect(row.v).toBe("alice")
            db:close()
        end)

        test("query returns array", function()
            local db  = rusqlite.open(":memory:")
            db:execute("CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)")
            db:execute("INSERT INTO t (v) VALUES (?)", "a")
            db:execute("INSERT INTO t (v) VALUES (?)", "b")
            local sel = db:prepare("SELECT v FROM t WHERE v = ?")
            local rows = sel:query("a")
            expect(#rows).toBe(1)
            expect(rows[1].v).toBe("a")
            db:close()
        end)
    end)

    -- close --------------------------------------------------------------------

    describe("close", function()
        test("subsequent calls return error", function()
            local db = rusqlite.open(":memory:")
            db:close()
            local n, err = db:execute("SELECT 1")
            expect(n).toBeNil()
            expect(err).toContain("database is closed")
        end)

        test("idempotent", function()
            local db = rusqlite.open(":memory:")
            db:close()
            db:close()
        end)
    end)

end)
