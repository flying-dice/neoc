local _t       = require("lib:test")
local describe = _t.describe
local test     = _t.test
local expect   = _t.expect

local fs = require("std:fs")
local path = require("std:path")
local random = require("lib:random")
local tempfile = require("lib:tempfile")

-- A fresh directory for one test: keep the handle (it deletes the directory when collected).
local function scratch()
    local handle = assert(tempfile.tempdir())
    return handle, handle:path()
end

-- The kind of a failed call: `kind_of(fs.read(p))`.
local function kind_of(value, err)
    expect(value).toBeNil()
    return fs.error_kind(err)
end

-- The value of a call that must have succeeded (`assert` would also reject a `false` result).
local function ok(value, err)
    expect(err).toBeNil()
    return value
end

local function names(entries)
    local out = {}
    for i, entry in ipairs(entries) do out[i] = entry:file_name() end
    return table.concat(out, ",")
end

fs.create_dir_all(".tmp")

describe("fs", function()

    -- create_dir ---------------------------------------------------------------

    describe("create_dir", function()
        test("creates a directory that does not exist", function()
            local name = ".tmp/fs_create_dir_" .. random.uuid_v4()
            local ok, err = fs.create_dir(name)
            expect(err).toBeNil()
            expect(ok).toBe(true)
        end)

        test("errors when directory already exists", function()
            local ok, err = fs.create_dir(".tmp")
            expect(ok).toBeNil()
            expect(err).toContain("fs.create_dir:")
        end)

        test("errors when parent does not exist", function()
            local ok, err = fs.create_dir(".tmp/fs_create_dir_no_parent/sub/deep")
            expect(ok).toBeNil()
            expect(err).toContain("fs.create_dir:")
        end)
    end)

    -- create_dir_all -----------------------------------------------------------

    describe("create_dir_all", function()
        test("creates nested directories", function()
            local ok, err = fs.create_dir_all(".tmp/fs_create_dir_all/sub/deep")
            expect(err).toBeNil()
            expect(ok).toBe(true)
        end)

        test("succeeds when directory already exists", function()
            fs.create_dir_all(".tmp/fs_create_dir_all_idem")
            local ok, err = fs.create_dir_all(".tmp/fs_create_dir_all_idem")
            expect(err).toBeNil()
            expect(ok).toBe(true)
        end)

        test("succeeds when partial path exists", function()
            fs.create_dir_all(".tmp/fs_create_dir_all_partial")
            local ok, err = fs.create_dir_all(".tmp/fs_create_dir_all_partial/child/grandchild")
            expect(err).toBeNil()
            expect(ok).toBe(true)
        end)
    end)

    -- open ---------------------------------------------------------------------

    describe("open", function()
        test("mode r returns a reader", function()
            fs.write(".tmp/fs_open_r.txt", "hello")
            local reader, err = fs.open({ path = ".tmp/fs_open_r.txt", mode = "r" })
            expect(err).toBeNil()
            local data, rerr = reader:read_all()
            expect(rerr).toBeNil()
            expect(data).toBe("hello")
        end)

        test("mode w returns a writer and truncates existing content", function()
            fs.write(".tmp/fs_open_w.txt", "old content")
            local writer, err = fs.open({ path = ".tmp/fs_open_w.txt", mode = "w" })
            expect(err).toBeNil()
            writer:write("new")
            writer:flush()
            local data, _ = fs.read(".tmp/fs_open_w.txt")
            expect(data).toBe("new")
        end)

        test("mode a appends to existing content", function()
            fs.write(".tmp/fs_open_a.txt", "hello")
            local writer, err = fs.open({ path = ".tmp/fs_open_a.txt", mode = "a" })
            expect(err).toBeNil()
            writer:write(" world")
            writer:flush()
            local data, _ = fs.read(".tmp/fs_open_a.txt")
            expect(data).toBe("hello world")
        end)

        test("mode a creates file if it does not exist", function()
            -- reset state from prior runs so the file starts empty
            fs.write(".tmp/fs_open_a_new.txt", "")
            local writer, err = fs.open({ path = ".tmp/fs_open_a_new.txt", mode = "a" })
            expect(err).toBeNil()
            writer:write("created")
            writer:flush()
            local data, _ = fs.read(".tmp/fs_open_a_new.txt")
            expect(data).toBe("created")
        end)

        test("unknown mode returns error", function()
            local handle, err = fs.open({ path = ".tmp/fs_unused.txt", mode = "x" })
            expect(handle).toBeNil()
            expect(err).toContain("fs.open:")
        end)

        test("missing file with mode r returns error", function()
            local handle, err = fs.open({ path = ".tmp/does_not_exist_ever.txt", mode = "r" })
            expect(handle).toBeNil()
            expect(err).toContain("fs.open:")
        end)
    end)

    -- read ---------------------------------------------------------------------

    describe("read", function()
        test("reads entire file as string", function()
            fs.write(".tmp/fs_read_test.txt", "hello world")
            local data, err = fs.read(".tmp/fs_read_test.txt")
            expect(err).toBeNil()
            expect(data).toBe("hello world")
        end)

        test("reads binary content", function()
            local writer, _ = fs.open({ path = ".tmp/fs_read_bin.bin", mode = "w" })
            writer:write("\0\1\2\254\255")
            writer:flush()
            local data, err = fs.read(".tmp/fs_read_bin.bin")
            expect(err).toBeNil()
            expect(data).toBe("\0\1\2\254\255")
        end)

        test("reads empty file as empty string", function()
            fs.write(".tmp/fs_read_empty.txt", "")
            local data, err = fs.read(".tmp/fs_read_empty.txt")
            expect(err).toBeNil()
            expect(data).toBe("")
        end)

        test("missing file returns error", function()
            local data, err = fs.read(".tmp/does_not_exist_ever.txt")
            expect(data).toBeNil()
            expect(err).toContain("fs.read:")
        end)
    end)

    -- write --------------------------------------------------------------------

    describe("write", function()
        test("writes string to file", function()
            local ok, err = fs.write(".tmp/fs_write_test.txt", "written")
            expect(err).toBeNil()
            expect(ok).toBe(true)
            local data, _ = fs.read(".tmp/fs_write_test.txt")
            expect(data).toBe("written")
        end)

        test("overwrites existing content", function()
            fs.write(".tmp/fs_write_overwrite.txt", "first")
            fs.write(".tmp/fs_write_overwrite.txt", "second")
            local data, _ = fs.read(".tmp/fs_write_overwrite.txt")
            expect(data).toBe("second")
        end)

        test("writes empty string", function()
            local ok, err = fs.write(".tmp/fs_write_empty.txt", "")
            expect(err).toBeNil()
            expect(ok).toBe(true)
            local data, _ = fs.read(".tmp/fs_write_empty.txt")
            expect(data).toBe("")
        end)
    end)

    -- error kinds ---------------------------------------------------------------

    describe("errors", function()
        test("a failure names the function, the kind and the path", function()
            local _, dir = scratch()
            local value, err = fs.read(dir .. "/missing")
            expect(value).toBeNil()
            expect(err).toContain("fs.read: not_found: ")
            expect(err).toContain(dir .. "/missing")
        end)

        test("error_kind reads the kind and nothing else", function()
            expect(fs.error_kind("fs.copy: already_exists: /x: exists")).toBe("already_exists")
            expect(fs.error_kind("fs.copy: bogus: /x")).toBeNil()
            expect(fs.error_kind("not an fs error")).toBeNil()
            expect(fs.error_kind("")).toBeNil()
        end)

        test("a path with a NUL byte is invalid_input", function()
            local value, err = fs.read("a\0b")
            expect(kind_of(value, err)).toBe("invalid_input")
            expect(err).toContain("NUL")
        end)

        test("an empty path is an error, not the current directory", function()
            local value, err = fs.read_dir("")
            expect(kind_of(value, err)).toBe("not_found")
        end)
    end)

    -- exists / metadata ---------------------------------------------------------

    describe("exists", function()
        test("true for a file and a directory, false for a missing path", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            expect(fs.exists(dir .. "/f")).toBe(true)
            expect(fs.exists(dir)).toBe(true)
            expect(fs.exists(dir .. "/missing")).toBe(false)
        end)
    end)

    describe("metadata", function()
        test("describes a file", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "12345")
            local m = assert(fs.metadata(dir .. "/f"))
            expect(m:kind()).toBe("file")
            expect(m:is_file()).toBe(true)
            expect(m:is_dir()).toBe(false)
            expect(m:is_symlink()).toBe(false)
            expect(m:len()).toBe(5)
            expect(m:modified() > 1e9).toBe(true)
            expect(m:readonly()).toBe(false)
        end)

        test("describes a directory", function()
            local _, dir = scratch()
            local m = assert(fs.metadata(dir))
            expect(m:kind()).toBe("dir")
            expect(m:is_dir()).toBe(true)
        end)

        test("a missing path is not_found", function()
            local _, dir = scratch()
            expect(kind_of(fs.metadata(dir .. "/missing"))).toBe("not_found")
            expect(kind_of(fs.symlink_metadata(dir .. "/missing"))).toBe("not_found")
        end)

        test("symlink_metadata reports a link, metadata follows it", function()
            local _, dir = scratch()
            fs.write(dir .. "/target", "abc")
            local linked, lerr = fs.symlink("target", dir .. "/link")
            if linked == nil then
                -- no privilege to make links here (Windows without developer mode)
                expect(fs.error_kind(lerr) ~= nil).toBe(true)
                return
            end
            expect(assert(fs.symlink_metadata(dir .. "/link")):kind()).toBe("symlink")
            expect(assert(fs.symlink_metadata(dir .. "/link")):is_symlink()).toBe(true)
            expect(assert(fs.metadata(dir .. "/link")):kind()).toBe("file")
            expect(assert(fs.metadata(dir .. "/link")):len()).toBe(3)
            expect(assert(fs.read_link(dir .. "/link"))).toBe("target")
        end)

        test("a dangling link is not_found to metadata but visible to symlink_metadata", function()
            local _, dir = scratch()
            if fs.symlink("nowhere", dir .. "/dangling") == nil then return end
            expect(kind_of(fs.metadata(dir .. "/dangling"))).toBe("not_found")
            expect(assert(fs.symlink_metadata(dir .. "/dangling")):is_symlink()).toBe(true)
            expect(fs.exists(dir .. "/dangling")).toBe(false)
        end)
    end)

    describe("set_permissions", function()
        test("readonly round-trips through metadata", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            assert(fs.set_permissions(dir .. "/f", { readonly = true }))
            expect(assert(fs.metadata(dir .. "/f")):readonly()).toBe(true)
            assert(fs.set_permissions(dir .. "/f", { readonly = false }))
            expect(assert(fs.metadata(dir .. "/f")):readonly()).toBe(false)
        end)

        test("mode sets the Unix permission bits", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            local value, err = fs.set_permissions(dir .. "/f", { mode = 420 })
            if value == nil then
                expect(fs.error_kind(err)).toBe("unsupported")
                return
            end
            expect(assert(fs.metadata(dir .. "/f")):mode()).toBe(420)
        end)

        test("exactly one of mode and readonly, and a mode in range", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            expect(kind_of(fs.set_permissions(dir .. "/f", {}))).toBe("invalid_input")
            expect(kind_of(fs.set_permissions(dir .. "/f", { mode = 420, readonly = true }))).toBe("invalid_input")
            expect(kind_of(fs.set_permissions(dir .. "/f", { mode = 4096 }))).toBe("invalid_input")
            expect(kind_of(fs.set_permissions(dir .. "/f", { mode = -1 }))).toBe("invalid_input")
            expect(kind_of(fs.set_permissions(dir .. "/f", { mode = 1e300 }))).toBe("invalid_input")
        end)

        test("a missing path is not_found", function()
            local _, dir = scratch()
            expect(kind_of(fs.set_permissions(dir .. "/missing", { readonly = true }))).toBe("not_found")
        end)
    end)

    -- read_dir / walk -----------------------------------------------------------

    describe("read_dir", function()
        test("lists the entries sorted by name with their kinds", function()
            local _, dir = scratch()
            fs.write(dir .. "/b.txt", "b")
            fs.write(dir .. "/a.txt", "a")
            fs.create_dir(dir .. "/sub")
            local entries = assert(fs.read_dir(dir))
            expect(names(entries)).toBe("a.txt,b.txt,sub")
            expect(entries[1]:kind()).toBe("file")
            expect(entries[3]:kind()).toBe("dir")
            expect(entries[3]:is_dir()).toBe(true)
            expect(entries[3]:path()).toBe(dir .. "/sub")
            expect(entries[1]:depth()).toBe(1)
        end)

        test("an empty directory is an empty array", function()
            local _, dir = scratch()
            expect(#assert(fs.read_dir(dir))).toBe(0)
        end)

        test("a file is not_a_directory and a missing path is not_found", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            expect(kind_of(fs.read_dir(dir .. "/f"))).toBe("not_a_directory")
            expect(kind_of(fs.read_dir(dir .. "/missing"))).toBe("not_found")
        end)
    end)

    describe("walk", function()
        local function tree(dir)
            fs.create_dir_all(dir .. "/sub/deeper")
            fs.write(dir .. "/b", "b")
            fs.write(dir .. "/a", "a")
            fs.write(dir .. "/sub/c", "c")
            fs.write(dir .. "/sub/deeper/d", "d")
        end

        test("lists the whole tree depth first, each directory sorted", function()
            local _, dir = scratch()
            tree(dir)
            local all = assert(fs.walk(dir))
            expect(names(all)).toBe("a,b,sub,c,deeper,d")
            expect(all[1]:depth()).toBe(1)
            expect(all[4]:depth()).toBe(2)
            expect(all[6]:depth()).toBe(3)
            expect(all[6]:path()).toBe(dir .. "/sub/deeper/d")
        end)

        test("max_depth limits the depth", function()
            local _, dir = scratch()
            tree(dir)
            expect(#assert(fs.walk(dir, { max_depth = 1 }))).toBe(3)
            expect(#assert(fs.walk(dir, { max_depth = 2 }))).toBe(5)
            expect(#assert(fs.walk(dir, { max_depth = 0 }))).toBe(0)
            expect(#assert(fs.walk(dir, { max_depth = 1e300 }))).toBe(6)
        end)

        test("a bad max_depth or option is invalid_input", function()
            local _, dir = scratch()
            expect(kind_of(fs.walk(dir, { max_depth = -1 }))).toBe("invalid_input")
            expect(kind_of(fs.walk(dir, { max_depth = 1.5 }))).toBe("invalid_input")
            expect(kind_of(fs.walk(dir, { max_depth = 0 / 0 }))).toBe("invalid_input")
            expect(kind_of(fs.walk(dir, { max_depth = "2" }))).toBe("invalid_input")
            expect(kind_of(fs.walk(dir, { depth = 2 }))).toBe("invalid_input")
        end)

        test("a file is not_a_directory and a missing path is not_found", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            expect(kind_of(fs.walk(dir .. "/f"))).toBe("not_a_directory")
            expect(kind_of(fs.walk(dir .. "/missing"))).toBe("not_found")
        end)

        test("a symlink loop is listed, not followed", function()
            local _, dir = scratch()
            fs.create_dir(dir .. "/t")
            fs.write(dir .. "/t/f", "f")
            if fs.symlink(dir, dir .. "/t/loop") == nil then return end
            local all = assert(fs.walk(dir .. "/t"))
            expect(names(all)).toBe("f,loop")
            expect(all[2]:kind()).toBe("symlink")
        end)
    end)

    -- copy / copy_dir ------------------------------------------------------------

    describe("copy", function()
        test("copies a file and returns the bytes written", function()
            local _, dir = scratch()
            fs.write(dir .. "/a", "hello")
            expect(assert(fs.copy(dir .. "/a", dir .. "/b"))).toBe(5)
            expect(assert(fs.read(dir .. "/b"))).toBe("hello")
            expect(assert(fs.read(dir .. "/a"))).toBe("hello")
        end)

        test("copies an empty file", function()
            local _, dir = scratch()
            fs.write(dir .. "/a", "")
            expect(assert(fs.copy(dir .. "/a", dir .. "/b"))).toBe(0)
            expect(fs.exists(dir .. "/b")).toBe(true)
        end)

        test("replaces an existing file", function()
            local _, dir = scratch()
            fs.write(dir .. "/a", "new")
            fs.write(dir .. "/b", "old content")
            expect(assert(fs.copy(dir .. "/a", dir .. "/b"))).toBe(3)
            expect(assert(fs.read(dir .. "/b"))).toBe("new")
        end)

        test("a directory source is is_directory", function()
            local _, dir = scratch()
            fs.create_dir(dir .. "/d")
            expect(kind_of(fs.copy(dir .. "/d", dir .. "/e"))).toBe("is_directory")
        end)

        test("a directory destination is is_directory", function()
            local _, dir = scratch()
            fs.write(dir .. "/a", "x")
            fs.create_dir(dir .. "/d")
            expect(kind_of(fs.copy(dir .. "/a", dir .. "/d"))).toBe("is_directory")
        end)

        test("a file onto itself is invalid_input and keeps its content", function()
            local _, dir = scratch()
            fs.write(dir .. "/a", "keep")
            expect(kind_of(fs.copy(dir .. "/a", dir .. "/a"))).toBe("invalid_input")
            expect(assert(fs.read(dir .. "/a"))).toBe("keep")
        end)

        test("a missing source or parent is not_found", function()
            local _, dir = scratch()
            fs.write(dir .. "/a", "x")
            expect(kind_of(fs.copy(dir .. "/missing", dir .. "/b"))).toBe("not_found")
            expect(kind_of(fs.copy(dir .. "/a", dir .. "/no/such/b"))).toBe("not_found")
        end)
    end)

    describe("copy_dir", function()
        test("copies a tree and returns the bytes of data", function()
            local _, dir = scratch()
            fs.create_dir_all(dir .. "/src/sub/deeper")
            fs.create_dir_all(dir .. "/src/empty")
            fs.write(dir .. "/src/a", "a")
            fs.write(dir .. "/src/sub/b", "bb")
            fs.write(dir .. "/src/sub/deeper/c", "ccc")
            expect(assert(fs.copy_dir(dir .. "/src", dir .. "/dst"))).toBe(6)
            expect(assert(fs.read(dir .. "/dst/sub/deeper/c"))).toBe("ccc")
            expect(fs.exists(dir .. "/dst/empty")).toBe(true)
            expect(assert(fs.read(dir .. "/src/a"))).toBe("a")
        end)

        test("an existing destination is already_exists and is left alone", function()
            local _, dir = scratch()
            fs.create_dir(dir .. "/src")
            fs.create_dir(dir .. "/dst")
            fs.write(dir .. "/dst/keep", "k")
            expect(kind_of(fs.copy_dir(dir .. "/src", dir .. "/dst"))).toBe("already_exists")
            expect(assert(fs.read(dir .. "/dst/keep"))).toBe("k")
        end)

        test("a destination inside the source is invalid_input", function()
            local _, dir = scratch()
            fs.create_dir_all(dir .. "/src/sub")
            expect(kind_of(fs.copy_dir(dir .. "/src", dir .. "/src/sub/copy"))).toBe("invalid_input")
            expect(fs.exists(dir .. "/src/sub/copy")).toBe(false)
        end)

        test("a file source is not_a_directory, a missing source or parent is not_found", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            fs.create_dir(dir .. "/src")
            expect(kind_of(fs.copy_dir(dir .. "/f", dir .. "/x"))).toBe("not_a_directory")
            expect(kind_of(fs.copy_dir(dir .. "/missing", dir .. "/x"))).toBe("not_found")
            expect(kind_of(fs.copy_dir(dir .. "/src", dir .. "/no/such/x"))).toBe("not_found")
        end)

        test("symlinks are recreated, not followed", function()
            local _, dir = scratch()
            fs.create_dir(dir .. "/src")
            fs.write(dir .. "/src/f", "f")
            if fs.symlink(dir, dir .. "/src/loop") == nil then return end
            expect(assert(fs.copy_dir(dir .. "/src", dir .. "/dst"))).toBe(1)
            expect(assert(fs.symlink_metadata(dir .. "/dst/loop")):is_symlink()).toBe(true)
            expect(assert(fs.read_link(dir .. "/dst/loop"))).toBe(dir)
        end)
    end)

    -- rename / move ---------------------------------------------------------------

    describe("rename and move", function()
        for _, op in ipairs { "rename", "move" } do
            test(op .. " moves a file and replaces an existing one", function()
                local _, dir = scratch()
                fs.write(dir .. "/a", "a")
                assert(fs[op](dir .. "/a", dir .. "/b"))
                expect(fs.exists(dir .. "/a")).toBe(false)
                expect(assert(fs.read(dir .. "/b"))).toBe("a")
                fs.write(dir .. "/a", "new")
                assert(fs[op](dir .. "/a", dir .. "/b"))
                expect(assert(fs.read(dir .. "/b"))).toBe("new")
            end)

            test(op .. " moves a directory with its contents", function()
                local _, dir = scratch()
                fs.create_dir_all(dir .. "/tree/sub")
                fs.write(dir .. "/tree/sub/f", "f")
                assert(fs[op](dir .. "/tree", dir .. "/moved"))
                expect(fs.exists(dir .. "/tree")).toBe(false)
                expect(assert(fs.read(dir .. "/moved/sub/f"))).toBe("f")
            end)

            test(op .. " of a missing source is not_found", function()
                local _, dir = scratch()
                expect(kind_of(fs[op](dir .. "/missing", dir .. "/b"))).toBe("not_found")
            end)

            test(op .. " of a file onto a directory is is_directory and changes nothing", function()
                local _, dir = scratch()
                fs.write(dir .. "/a", "a")
                fs.create_dir(dir .. "/d")
                expect(kind_of(fs[op](dir .. "/a", dir .. "/d"))).toBe("is_directory")
                expect(assert(fs.read(dir .. "/a"))).toBe("a")
            end)
        end
    end)

    -- remove ---------------------------------------------------------------------

    describe("remove_file", function()
        test("removes a file and reports true", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            expect(assert(fs.remove_file(dir .. "/f"))).toBe(true)
            expect(fs.exists(dir .. "/f")).toBe(false)
        end)

        test("a missing file is not_found, or false with missing_ok", function()
            local _, dir = scratch()
            expect(kind_of(fs.remove_file(dir .. "/f"))).toBe("not_found")
            expect(ok(fs.remove_file(dir .. "/f", { missing_ok = true }))).toBe(false)
        end)

        test("a directory is is_directory", function()
            local _, dir = scratch()
            fs.create_dir(dir .. "/d")
            expect(kind_of(fs.remove_file(dir .. "/d"))).toBe("is_directory")
        end)

        test("removes a symlink and not its target", function()
            local _, dir = scratch()
            fs.write(dir .. "/target", "t")
            if fs.symlink("target", dir .. "/link") == nil then return end
            expect(assert(fs.remove_file(dir .. "/link"))).toBe(true)
            expect(assert(fs.read(dir .. "/target"))).toBe("t")
        end)

        test("an unknown option or a non-boolean value is invalid_input", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            expect(kind_of(fs.remove_file(dir .. "/f", { missing = true }))).toBe("invalid_input")
            expect(kind_of(fs.remove_file(dir .. "/f", { missing_ok = "yes" }))).toBe("invalid_input")
            expect(fs.exists(dir .. "/f")).toBe(true)
        end)
    end)

    describe("remove_dir", function()
        test("removes an empty directory", function()
            local _, dir = scratch()
            fs.create_dir(dir .. "/d")
            expect(assert(fs.remove_dir(dir .. "/d"))).toBe(true)
            expect(fs.exists(dir .. "/d")).toBe(false)
        end)

        test("a directory with content is not_empty", function()
            local _, dir = scratch()
            fs.create_dir(dir .. "/d")
            fs.write(dir .. "/d/f", "x")
            expect(kind_of(fs.remove_dir(dir .. "/d"))).toBe("not_empty")
            expect(fs.exists(dir .. "/d/f")).toBe(true)
        end)

        test("a file is not_a_directory, a missing path not_found or false with missing_ok", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            expect(kind_of(fs.remove_dir(dir .. "/f"))).toBe("not_a_directory")
            expect(kind_of(fs.remove_dir(dir .. "/missing"))).toBe("not_found")
            expect(ok(fs.remove_dir(dir .. "/missing", { missing_ok = true }))).toBe(false)
        end)
    end)

    describe("remove_dir_all", function()
        test("removes a tree", function()
            local _, dir = scratch()
            fs.create_dir_all(dir .. "/t/sub/deeper")
            fs.write(dir .. "/t/sub/deeper/f", "x")
            expect(assert(fs.remove_dir_all(dir .. "/t"))).toBe(true)
            expect(fs.exists(dir .. "/t")).toBe(false)
        end)

        test("a missing path is not_found, or false with missing_ok", function()
            local _, dir = scratch()
            expect(kind_of(fs.remove_dir_all(dir .. "/t"))).toBe("not_found")
            expect(ok(fs.remove_dir_all(dir .. "/t", { missing_ok = true }))).toBe(false)
        end)

        test("a file is not_a_directory", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            expect(kind_of(fs.remove_dir_all(dir .. "/f"))).toBe("not_a_directory")
            expect(fs.exists(dir .. "/f")).toBe(true)
        end)

        test("refuses a path that names no directory", function()
            for _, bad in ipairs { "", "/", ".", ".." } do
                expect(kind_of(fs.remove_dir_all(bad))).toBe("invalid_input")
            end
        end)

        test("deletes links inside without touching what they point at", function()
            local _, dir = scratch()
            fs.create_dir(dir .. "/victim")
            fs.write(dir .. "/victim/precious", "p")
            fs.create_dir(dir .. "/t")
            if fs.symlink(dir .. "/victim", dir .. "/t/link") == nil then return end
            expect(assert(fs.remove_dir_all(dir .. "/t"))).toBe(true)
            expect(assert(fs.read(dir .. "/victim/precious"))).toBe("p")
        end)

        test("refuses a symlink to a directory, however it is written", function()
            local _, dir = scratch()
            fs.create_dir(dir .. "/real")
            fs.write(dir .. "/real/keep", "k")
            if fs.symlink("real", dir .. "/link") == nil then return end
            expect(kind_of(fs.remove_dir_all(dir .. "/link"))).toBe("not_a_directory")
            expect(kind_of(fs.remove_dir_all(dir .. "/link/"))).toBe("not_a_directory")
            expect(assert(fs.read(dir .. "/real/keep"))).toBe("k")
        end)
    end)

    -- links ----------------------------------------------------------------------

    describe("symlink, read_link and canonicalize", function()
        test("read_link returns the target as stored", function()
            local _, dir = scratch()
            fs.write(dir .. "/target", "t")
            if fs.symlink("target", dir .. "/link") == nil then return end
            expect(assert(fs.read_link(dir .. "/link"))).toBe("target")
            expect(path.file_name(assert(fs.canonicalize(dir .. "/link")))).toBe("target")
        end)

        test("symlink onto an existing path is already_exists", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            local value, err = fs.symlink("elsewhere", dir .. "/f")
            -- Windows without the privilege to make links says so; everywhere else the path exists
            local expected = (path.separator == "/") and "already_exists" or fs.error_kind(err)
            expect(kind_of(value, err)).toBe(expected)
        end)

        test("read_link of a file is invalid_input and of a missing path not_found", function()
            local _, dir = scratch()
            fs.write(dir .. "/f", "x")
            expect(kind_of(fs.read_link(dir .. "/f"))).toBe("invalid_input")
            expect(kind_of(fs.read_link(dir .. "/missing"))).toBe("not_found")
        end)

        test("canonicalize of a missing path is not_found", function()
            local _, dir = scratch()
            expect(kind_of(fs.canonicalize(dir .. "/missing"))).toBe("not_found")
        end)
    end)

    -- a task keeps running while a long call waits --------------------------------

    describe("long calls wait", function()
        test("copy_dir, walk and remove_dir_all work from inside a task", function()
            local task = require("std:task")
            local _, dir = scratch()
            fs.create_dir_all(dir .. "/t/sub")
            fs.write(dir .. "/t/sub/f", "f")
            local job = task.spawn(function()
                local copied = assert(fs.copy_dir(dir .. "/t", dir .. "/u"))
                local count = #assert(fs.walk(dir .. "/u"))
                assert(fs.remove_dir_all(dir .. "/u"))
                return copied + count
            end)
            expect(job:await()).toBe(3)
        end)
    end)
