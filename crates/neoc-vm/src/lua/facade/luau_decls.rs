//! The declarations of a module's recorded surface: as a tree, and as Luau.
//!
//! [`Module::ast`] is the module's declarations as a tree (`neoc_decl`): the recording, with every recorded type
//! turned into Luau's by the rules below and read into the tree. [`Module::luau_decls`] is that tree written as
//! Luau by `neoc_decl::luau`, and `types/neoc.ast.json` is the same tree for a generator for another language
//! (vos-codegen writes TypeScript's from it), so neither is a translation of the other.
//!
//! As Luau, a module is one section of a luau-lsp definitions file: an `export type` alias per resource type
//! (a table type of its methods, `self` first, and its fields), a `<Type>Statics` alias for the sub-table of a
//! type on its module (`Duration.from_secs`), and one alias for the module table itself, named after the
//! registry key (`lib:json` is `lib_json`, its `Object` type `lib_json_Object`). [`require_declaration`]
//! closes the file with the overloaded `require` that maps each `"ns:name"` to its module alias.
//!
//! Aliases of table types, not `declare class`: luau-lsp 1.70.1 replaced `declare class` with
//! `declare extern type` (a definitions file with `declare class` fails to load there), and an alias parses
//! in 1.70.1, the only release tried. Each alias is an `export type`, which is what makes it visible to the
//! scripts (`local o: lib_json_Object`): a plain `type` in a definitions file stays private to it. All of
//! them share one global namespace, hence the module prefix on every name.
//!
//! The recorded vocabulary (see `CLAUDE.md`) is `string`, `number`, `bool`, `LuaValue` (opaque, `any`), a
//! trailing `?` for optional, `Result<T, string>` for `(value, err)`, `(A, B)` for several returns (a `...`
//! in it, or alone, for any number), `()` for nothing, a type's own name for a type its module declares,
//! `std_net.TcpListener` for one of another module, and Luau's own syntax for a function
//! (`(req: vnd_hyper.Request) -> ...(string | { status: number? } | nil)`), a table (`{ [string]: any }`, `{ status: number? }`) and a
//! string literal (`"GET" | "POST"`, copied as it is).
//!
//! The emitter refuses what it can see it cannot express: a control character in a doc or a type, a tuple
//! or `...` inside `Result<>`, a top-level `...` that is not last, a character a type does not use, unbalanced
//! brackets, a name that is not an identifier. That is an error of [`Module::luau_decls`], not invalid Luau in
//! the file. A type that uses only permitted characters and is still malformed is an error too: every type is
//! read into the tree (`neoc_decl::parse`) before anything is written. The test-only `grammar` module parses
//! the whole generated file besides, with no luau-lsp needed.

use std::fmt::Write as _;

use neoc_decl::{Decl, Func, Param, Prop, Section, Ty};

use super::{Entry, FieldEntry, Module, TypeEntry, VARIADIC, recorded_any};

#[cfg(test)]
pub(crate) mod grammar;

/// What the emitter cannot write is a message, not a panic and not invalid text.
type Emit<T> = Result<T, String>;

/// Reserved words of Luau: not usable as a parameter name or a bare property name. (`goto` is not one: Luau
/// does not reserve it.)
const LUAU_KEYWORDS: &[&str] = &[
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local",
    "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
];

/// The types Luau has that the recorded vocabulary uses as they are (`buffer` is Luau's byte block).
const PRIMITIVES: &[&str] = &["string", "number", "boolean", "any", "nil", "buffer"];

/// The prefix of every type name a registry key's module declares: `lib:json` becomes `lib_json`.
#[must_use]
pub fn scope(key: &str) -> String {
    key.replace(':', "_")
}

/// The comment that opens the definitions file.
#[must_use]
pub fn file_header() -> String {
    "\
-- GENERATED by neoc-vm (`cargo run -p neoc-vm --example luau_decls`) from each module's
-- recorded surface. Do not edit. Regenerate with the same command; `-- --check` fails
-- when this file is stale.
--
-- Luau declarations for luau-lsp: a definitions file (`--definitions:@neoc=<this file>` of `luau-lsp`,
-- `luau-lsp.types.definitionFiles` in an editor). Never loaded by neoc. One section per module, then
-- the `require` overloads that give `require(\"lib:json\")` the type of that module.

"
    .to_string()
}

/// The closing declaration: `require` takes only a module key and returns that module's table type, as
/// neoc's own `require` does (an unknown name is a type error in the editor, as it is a run-time error).
#[must_use]
pub fn require_declaration(keys: &[&str]) -> String {
    let mut out = String::from("-- ===== require =====\n\ndeclare require: ");
    for (i, key) in keys.iter().enumerate() {
        let sep = if i == 0 { "\n\t" } else { "\n\t& " };
        let _ = write!(out, "{sep}((path: \"{key}\") -> {})", scope(key));
    }
    out.push('\n');
    out
}

impl Module<'_> {
    /// Emits this module's section of the Luau declarations: an alias per resource type, a `Statics` alias
    /// per type with constructors or constants on the module, and the module's own table type. It is
    /// [`Module::ast`] as Luau writes it.
    ///
    /// # Errors
    /// As [`Module::ast`].
    pub fn luau_decls(&self) -> mlua::Result<String> {
        Ok(neoc_decl::luau::section(&self.ast()?))
    }

    /// This module's declarations as a tree: what [`Module::luau_decls`] writes as Luau and what a generator
    /// for another language reads (`types/neoc.ast.json`).
    ///
    /// # Errors
    /// Fails when the live module table cannot be read, when a type's sub-table on it disagrees with the
    /// recording (a member that was not recorded would be a false alarm for every script that uses it, and a
    /// recorded one that does not exist a call the editor accepts and the VM refuses), or when a record
    /// cannot be declared (see the module doc).
    pub fn ast(&self) -> mlua::Result<Section> {
        for ud in &self.userdata {
            self.check_statics_recorded(ud)?;
        }
        self.declarations()
            .map_err(|e| mlua::Error::external(format!("{}: {e}", self.name)))
    }

    fn declarations(&self) -> Emit<Section> {
        let scope = scope(&self.name);
        check_key(&self.name)?;
        let mut aliases = Vec::new();
        let mut statics = Vec::new();
        check_unique(
            &self.name,
            self.userdata
                .iter()
                .map(|u| u.type_name.as_str())
                .chain(self.types.iter().map(|t| t.type_name.as_str())),
        )?;
        for ud in &self.userdata {
            aliases.push(alias(
                &scope,
                &ud.type_name,
                &ud.fields,
                &[(&ud.methods, true), (&ud.functions, false)],
            )?);
            if recorded_any(ud) {
                aliases.push(alias(
                    &scope,
                    &statics_name(&ud.type_name),
                    &ud.static_consts,
                    &[(&ud.statics, false)],
                )?);
                statics.push(&ud.type_name);
            }
        }
        for ty in &self.types {
            aliases.extend(type_entry(&scope, ty)?);
            statics.push(&ty.type_name);
        }

        check_unique(
            &scope,
            statics
                .iter()
                .map(|n| n.as_str())
                .chain(self.consts.iter().map(|c| c.name.as_str()))
                .chain(self.entries.iter().map(|e| e.name.as_str())),
        )?;
        let mut props = Vec::new();
        for name in statics {
            let ty = Ty::Name(alias_name(&scope, &statics_name(name)));
            props.push(prop("", name, ty)?);
        }
        for c in &self.consts {
            props.push(field(&scope, c)?);
        }
        for e in &self.entries {
            props.push(e.fn_prop(&scope, None)?);
        }
        aliases.push(Decl {
            doc: String::new(),
            name: scope,
            ty: Ty::Table { props, index: None },
        });
        Ok(Section {
            name: self.name.clone(),
            aliases,
            globals: Vec::new(),
        })
    }
}

/// The name of the alias of a type of a module: `lib_json_Object`.
fn alias_name(scope: &str, type_name: &str) -> String {
    format!("{scope}_{type_name}")
}

/// The type name of the sub-table of a type on its module (`Duration.from_secs`): `DurationStatics`.
fn statics_name(type_name: &str) -> String {
    format!("{type_name}Statics")
}

/// Names written into one table type must differ: Luau keeps the last of two equal keys, so the other
/// record would silently be lost.
fn check_unique<'a>(table: &str, names: impl Iterator<Item = &'a str>) -> Emit<()> {
    let mut seen = std::collections::HashSet::new();
    for name in names {
        if !seen.insert(name) {
            return Err(format!("`{name}` is recorded twice in `{table}`"));
        }
    }
    Ok(())
}

/// A registry key is `ns:name` with both parts identifiers: it is written in a header comment and in a
/// string literal.
fn check_key(key: &str) -> Emit<()> {
    match key.split_once(':') {
        Some((ns, name)) if is_ident(ns) && is_ident(name) => Ok(()),
        _ => Err(format!("`{key}` is not an `ns:name` registry key")),
    }
}

fn is_ident(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn check_ident(what: &str, name: &str) -> Emit<()> {
    if is_ident(name) {
        Ok(())
    } else {
        Err(format!("{what} `{name}` is not an identifier"))
    }
}

/// A doc is comment lines: Luau ends a comment at a bare `\r` too, which `str::lines` does not split on,
/// and any other control character is not text. A tab is.
fn check_doc(doc: &str) -> Emit<()> {
    match doc
        .chars()
        .find(|c| c.is_control() && !matches!(c, '\n' | '\t'))
    {
        Some(c) => Err(format!(
            "a doc contains the control character {c:?}: {doc:?}"
        )),
        None => Ok(()),
    }
}

/// The aliases of a type with constructors recorded through `Module::type_`: its methods, and the statics.
fn type_entry(scope: &str, ty: &TypeEntry) -> Emit<[Decl; 2]> {
    Ok([
        alias(
            scope,
            &ty.type_name,
            &ty.fields,
            &[(&ty.methods, true), (&ty.functions, false)],
        )?,
        alias(
            scope,
            &statics_name(&ty.type_name),
            &[],
            &[(&ty.constructors, false)],
        )?,
    ])
}

/// One `<scope>_<name>`, a table type: the fields, then the functions of each group. A method (`true`)
/// takes the type itself as `self`, so `value:name(...)` checks and `value.name(...)` does not.
fn alias(
    scope: &str,
    name: &str,
    fields: &[FieldEntry],
    groups: &[(&[Entry], bool)],
) -> Emit<Decl> {
    check_ident("type name", name)?;
    let alias = alias_name(scope, name);
    check_unique(
        &alias,
        fields.iter().map(|f| f.name.as_str()).chain(
            groups
                .iter()
                .flat_map(|(entries, _)| entries.iter().map(|e| e.name.as_str())),
        ),
    )?;
    let mut props = Vec::new();
    for f in fields {
        props.push(field(scope, f)?);
    }
    for (entries, is_method) in groups {
        for entry in *entries {
            props.push(entry.fn_prop(scope, is_method.then_some(alias.as_str()))?);
        }
    }
    Ok(Decl {
        doc: String::new(),
        name: alias,
        ty: Ty::Table { props, index: None },
    })
}

impl Entry {
    /// This function as a property of a table type, with its doc. `receiver` is the alias of the type a
    /// method belongs to.
    fn fn_prop(&self, scope: &str, receiver: Option<&str>) -> Emit<Prop> {
        let mut params: Vec<Param> = receiver
            .map(|alias| Param {
                name: Some(neoc_decl::SELF.to_owned()),
                ty: Ty::Name(alias.to_owned()),
            })
            .into_iter()
            .collect();
        let mut rest = None;
        for (i, (name, ty)) in self.params.iter().enumerate() {
            if name == VARIADIC {
                if i + 1 != self.params.len() {
                    return Err(format!("`{}`: `...` is not its last parameter", self.name));
                }
                rest = Some(tree(&luau_type(ty, scope)?)?);
            } else {
                check_ident("parameter", name)?;
                params.push(Param {
                    name: Some(name.clone()),
                    ty: tree(&luau_type(ty, scope)?)?,
                });
            }
        }
        let returns = luau_returns(&self.ret, scope)?;
        let ret = neoc_decl::parse::ret(&returns)
            .map_err(|e| format!("the return `{returns}` is not read: {e}"))?;
        let func = Func {
            generics: Vec::new(),
            params,
            rest,
            ret,
        };
        prop(&self.doc, &self.name, Ty::Func(Box::new(func)))
    }
}

/// The tree of a type the rules below wrote as Luau.
fn tree(luau: &str) -> Emit<Ty> {
    neoc_decl::parse::ty(luau).map_err(|e| format!("the type `{luau}` is not read: {e}"))
}

/// One property of a value (a field, a constant) with its doc.
fn field(scope: &str, field: &FieldEntry) -> Emit<Prop> {
    prop(
        &field.doc,
        &field.name,
        tree(&luau_type(&field.ty, scope)?)?,
    )
}

/// A property, once its name and its doc are known to be writable.
fn prop(doc: &str, name: &str, ty: Ty) -> Emit<Prop> {
    check_ident("name", name)?;
    check_doc(doc)?;
    Ok(Prop {
        doc: doc.to_owned(),
        name: name.to_owned(),
        ty,
    })
}

/// A name made safe to write as a parameter name: a reserved word gets a trailing underscore.
fn param_ident(name: &str) -> String {
    if LUAU_KEYWORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// A property name as a table type writes it: a reserved word is a quoted key (`["end"]`), still read as
/// `value["end"]`.
fn prop_name(name: &str) -> String {
    if LUAU_KEYWORDS.contains(&name) {
        format!("[\"{name}\"]")
    } else {
        name.to_string()
    }
}

/// The Luau type of one recorded type string.
///
/// Identifiers are mapped one by one and everything else (parentheses, `->`, `|`, `?`, braces) is Luau
/// already: `bool` is `boolean`, `LuaValue` is `any`, a name with a dot is the type of another module
/// (`std_net.TcpListener` is `std_net_TcpListener`), any other name not Luau's own is a type of `scope`'s
/// module. A word followed by a colon is a label, not a type: a property name inside a table type
/// (a reserved word becomes the quoted key `["end"]`) and a parameter name inside a function type (a
/// reserved word gets a trailing underscore). A string literal is copied as it is. A bare `()` is `nil`, as
/// a value; a bare `...` and unbalanced brackets are errors.
fn luau_type(ty: &str, scope: &str) -> Emit<String> {
    let ty = ty.trim();
    if ty.is_empty() {
        return Err("a type is empty".to_string());
    }
    if ty == "()" {
        return Ok("nil".to_string());
    }
    if ty == VARIADIC {
        return Err("`...` is a trailing parameter or a return, not a type".to_string());
    }
    let chars: Vec<char> = ty.chars().collect();
    let mut out = String::new();
    let mut open: Vec<char> = Vec::new();
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        match c {
            _ if c.is_control() => return Err(format!("control character {c:?} in type `{ty}`")),
            '"' => {
                let end = string_end(&chars, i).map_err(|e| format!("{e} in type `{ty}`"))?;
                if let Some(c) = chars[i..=end].iter().find(|c| c.is_control()) {
                    return Err(format!(
                        "control character {c:?} in a string in type `{ty}`"
                    ));
                }
                out.extend(&chars[i..=end]);
                i = end + 1;
            }
            '(' | '{' | '[' => {
                open.push(c);
                out.push(c);
                i += 1;
            }
            ')' | '}' | ']' => {
                let want = match c {
                    ')' => '(',
                    '}' => '{',
                    _ => '[',
                };
                if open.pop() != Some(want) {
                    return Err(format!("unbalanced `{c}` in type `{ty}`"));
                }
                out.push(c);
                i += 1;
            }
            _ if c.is_ascii_alphabetic() || c == '_' => {
                let start = i;
                while i < chars.len()
                    && (chars[i].is_ascii_alphanumeric() || matches!(chars[i], '_' | '.'))
                {
                    i += 1;
                }
                let word: String = chars[start..i].iter().collect();
                if word.split('.').any(str::is_empty) {
                    return Err(format!("`{word}` is not part of a type: `{ty}`"));
                }
                let is_label = chars[i..]
                    .iter()
                    .find(|c| !c.is_whitespace())
                    .is_some_and(|c| *c == ':');
                out.push_str(&match (is_label, open.last()) {
                    (true, Some('{')) => prop_name(&word),
                    (true, _) => param_ident(&word),
                    (false, _) => named_type(&word, scope),
                });
            }
            '-' if chars.get(i + 1) == Some(&'>') => {
                out.push_str("->");
                i += 2;
            }
            '.' if chars[i..].starts_with(&['.', '.', '.']) => {
                out.push_str("...");
                i += 3;
            }
            ',' | ':' | '|' | '&' | '?' | ' ' => {
                out.push(c);
                i += 1;
            }
            _ => return Err(format!("`{c}` is not part of a type: `{ty}`")),
        }
    }
    if open.is_empty() {
        Ok(out)
    } else {
        Err(format!("unbalanced brackets in type `{ty}`"))
    }
}

/// The index of the quote that closes the string literal opened at `start`; every escape in it is one the
/// emitter takes (`escape_len`).
fn string_end(chars: &[char], start: usize) -> Result<usize, String> {
    let mut i = start + 1;
    while i < chars.len() {
        match chars[i] {
            '\\' => {
                i += escape_len(chars, i).ok_or_else(|| {
                    format!(
                        "an escape the emitter does not take, in a string at `{}`",
                        chars[i..].iter().take(6).collect::<String>()
                    )
                })?;
            }
            '"' => return Ok(i),
            _ => i += 1,
        }
    }
    Err("unterminated string".to_string())
}

/// The length of the escape that starts with the backslash at `at`, or `None` for an escape the emitter does
/// not take. It takes only these, which Luau reads: one
/// of `\a \b \f \n \r \t \v \\ \" \' \z`, `\xHH`, `\u{H...}` (a code point) or `\ddd` (one to three digits,
/// at most 255).
fn escape_len(chars: &[char], at: usize) -> Option<usize> {
    let hex = |i: usize| chars.get(i).is_some_and(char::is_ascii_hexdigit);
    match *chars.get(at + 1)? {
        'a' | 'b' | 'f' | 'n' | 'r' | 't' | 'v' | '\\' | '"' | '\'' | 'z' => Some(2),
        'x' => (hex(at + 2) && hex(at + 3)).then_some(4),
        'u' => {
            if chars.get(at + 2) != Some(&'{') {
                return None;
            }
            let digits = chars[at + 3..]
                .iter()
                .take_while(|c| c.is_ascii_hexdigit())
                .count();
            let value = u32::from_str_radix(
                &chars[at + 3..at + 3 + digits].iter().collect::<String>(),
                16,
            )
            .ok()?;
            (digits > 0 && chars.get(at + 3 + digits) == Some(&'}') && value <= 0x0010_FFFF)
                .then_some(3 + digits + 1)
        }
        '0'..='9' => {
            let digits = chars[at + 1..]
                .iter()
                .take(3)
                .take_while(|c| c.is_ascii_digit())
                .count();
            let value: u32 = chars[at + 1..at + 1 + digits]
                .iter()
                .collect::<String>()
                .parse()
                .ok()?;
            (value <= 255).then_some(1 + digits)
        }
        _ => None,
    }
}

fn named_type(word: &str, scope: &str) -> String {
    match word {
        "bool" => "boolean".to_string(),
        "LuaValue" => "any".to_string(),
        _ if PRIMITIVES.contains(&word) => word.to_string(),
        _ if word.contains('.') => word.replace('.', "_"),
        _ => alias_name(scope, word),
    }
}

/// The Luau return type of a recorded return type, as written after `->`.
///
/// `()` returns nothing. `Result<T, string>` is the runtime's `(value, error)` idiom: `(T?, string?)`
/// (a `()` value is `nil`; a tuple or a `...` as `T` is an error, a value is not both). `(A, B)` is a function
/// that returns several values of its own, and a `...` in it (or alone) is any number of further values
/// (`...any`), for a function that hands back whatever a Lua function returned; it must be last. Anything
/// else is one value.
fn luau_returns(ret: &str, scope: &str) -> Emit<String> {
    let ret = ret.trim();
    if ret == "()" {
        return Ok("()".to_string());
    }
    if let Some(values) = unwrap_parens(ret) {
        let parts = split_top_level(values);
        let mut items = Vec::new();
        for (i, part) in parts.iter().enumerate() {
            if part.trim() == VARIADIC && i + 1 != parts.len() {
                return Err(format!("`...` is not last in the return `{ret}`"));
            }
            items.push(return_item(part, scope)?);
        }
        return Ok(format!("({})", items.join(", ")));
    }
    if let Some(value) = ret
        .strip_prefix("Result<")
        .and_then(|r| r.strip_suffix(", string>"))
    {
        let value = value.trim();
        if value == VARIADIC || (value != "()" && unwrap_parens(value).is_some()) {
            return Err(format!(
                "`Result<{value}, string>`: a result holds one value, not a tuple or `...`"
            ));
        }
        return Ok(format!(
            "({}, string?)",
            optional(&return_item(value, scope)?)
        ));
    }
    return_item(ret, scope)
}

/// One value of a return: `()` is `nil` there, `...` is any number of values, and a function type is
/// parenthesised, so it reads as one value in a tuple and after `->`.
fn return_item(value: &str, scope: &str) -> Emit<String> {
    Ok(match value.trim() {
        "()" => "nil".to_string(),
        VARIADIC => "...any".to_string(),
        other => {
            let ty = luau_type(other, scope)?;
            if is_function(&ty) {
                format!("({ty})")
            } else {
                ty
            }
        }
    })
}

/// `ty` made optional. `nil` and `any` already are, an already optional type stays as it is, and a function
/// or a union is parenthesised first: a trailing `?` on `(a) -> b` belongs to the return type.
fn optional(ty: &str) -> String {
    if ty == "nil" || ty == "any" {
        return ty.to_string();
    }
    if is_function(ty) || top_level(ty).any(|(_, c)| c == '|') {
        return format!("({ty})?");
    }
    if ty.ends_with('?') {
        ty.to_string()
    } else {
        format!("{ty}?")
    }
}

/// The characters of `s` outside every bracket and every string literal, with their byte index: the bracket
/// that opens a group and the one that closes it are outside it, what is between them is not.
fn top_level(s: &str) -> impl Iterator<Item = (usize, char)> + '_ {
    let mut depth = 0_usize;
    let mut in_string = false;
    let mut escaped = false;
    s.char_indices().filter(move |&(_, c)| {
        if in_string {
            match (escaped, c) {
                (true, _) => escaped = false,
                (false, '\\') => escaped = true,
                (false, '"') => in_string = false,
                _ => {}
            }
            return false;
        }
        match c {
            '"' => {
                in_string = true;
                depth == 0
            }
            '(' | '[' | '{' => {
                depth += 1;
                depth == 1
            }
            ')' | ']' | '}' => {
                depth = depth.saturating_sub(1);
                depth == 0
            }
            _ => depth == 0,
        }
    })
}

/// Whether `ty` is a function type: a `->` outside every bracket.
pub(crate) fn is_function(ty: &str) -> bool {
    top_level(ty).any(|(i, c)| c == '>' && ty[..i].ends_with('-'))
}

/// The inside of `s` when one pair of parentheses wraps all of it (`(A, B)`), not for a function type that
/// merely starts with one (`(a: A) -> B`).
fn unwrap_parens(s: &str) -> Option<&str> {
    let mut tops = top_level(s);
    let (_, open) = tops.next()?;
    let (close_at, close) = tops.next()?;
    (open == '(' && close == ')' && close_at + 1 == s.len()).then(|| &s[1..close_at])
}

/// Splits `s` on the commas that are not inside brackets, so a `(a: A) -> B` or `{ [string]: any }` type
/// stays in one piece.
fn split_top_level(s: &str) -> Vec<&str> {
    let mut parts = Vec::new();
    let mut start = 0;
    for (i, _) in top_level(s).filter(|&(_, c)| c == ',') {
        parts.push(&s[start..i]);
        start = i + 1;
    }
    parts.push(&s[start..]);
    parts
}

