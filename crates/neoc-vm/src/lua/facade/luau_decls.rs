    /// Each of `needles` is found after the one before it.
    fn contains_in_order(haystack: &str, needles: &[&str]) -> bool {
        let mut rest = haystack;
        needles.iter().all(|n| match rest.find(n) {
            Some(at) => {
                rest = &rest[at + n.len()..];
                true
            }
            None => false,
        })
    }

    /// `func` / `try_func` accept any arity through `FromLuaMulti`: a two-argument function takes a tuple
    /// and records both params, and a fallible one returns the value and the error, both optional.
    #[test]
    fn multi_arg_function() {
        let lua = Lua::new();
        let mut m = Module::new(&lua, "vnd:demo").expect("module");
        m.try_func(
            "join",
            &[("a", "string"), ("b", "string")],
            "Concatenate two strings.",
            |_, (a, b): (String, String)| Ok::<_, String>(format!("{a}{b}")),
        )
        .expect("try_func");

        let decls = m.luau_decls().expect("decls");
        assert!(
            contains_in_order(
                &decls,
                &[
                    "\t--- Concatenate two strings.\n",
                    "\tjoin: (a: string, b: string) -> (string?, string?),\n",
                ]
            ),
            "{decls}"
        );

        let f: mlua::Function = m.into_table().get("join").expect("get fn");
        let (v, err): (String, Option<String>) = f.call(("foo", "bar")).expect("call");
        assert_eq!(v, "foobar");
        assert!(err.is_none());
    }

