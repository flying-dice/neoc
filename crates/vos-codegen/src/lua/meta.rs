//! The `LuaLS` (lua-language-server) definition files under `types/generated/luals/`: `---@meta` `LuaCATS` for editors
//! and `bun run lint:lua`. They are never loaded by the host.
//!
//! A module name has a colon, which is not portable in a file name (Windows) and which `---@meta <name>` cannot
//! carry either, so the files are laid out by the part of the name after the prefix. `.luarc.json` sets
//! `completion.requireSeparator` to `:`, which makes `LuaLS` read `require("vos:ui")` as the path `vos/ui` and find
//! it through the workspace library (the library root is `types/generated/luals/`). Without that setting (checked
//! on `LuaLS` 3.19.2) the `require` finds nothing and returns `any`, so `ui` and `app` lose their types and the
//! negative fixtures of `bun run lint:lua` stop being flagged.
//! The files live at `vos/ui.lua` and `vos/app.lua`, and `vos.lua` holds the shared types and the global `app`.
//! Classes and aliases are global to the workspace, so
//! the module files use the shared types without importing them.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use schemars::schema_for;
use vos_domain::ui::{
    components::{CATALOGUE, STACK_SUGAR},
    expr::{Arity, Func},
    source::ClientDecl,
    spec::{ComponentSpec, SlotScope},
};

use super::{
    classify, describe, field_type, group_name, helper_name, key, literals, object_type, optional,
    payload_type, value_type,
};
use crate::schema_lua::schema_to_lua;
use crate::walk::{effective_events, effective_props, named_enums, named_objects, split_group};

const APP_API: &str = include_str!("app_api.lua.tpl");

const HEADER: &str = "-- GENERATED by vos-codegen from the Rust domain (crates/vos-domain, `ui` module). Do not edit.\n\
-- Regenerate with `bun run codegen`; `bun run codegen:check` fails when this file is stale.\n\
--\n\
-- LuaCATS definitions for lua-language-server (`bun run lint:lua`, and editors through .luarc.json). Never loaded\n\
-- by the host: the runtime module is types/generated/ui.lua.\n";

/// The types the host and the constructors share.
const CORE: &str = r#"--- A reference to client or app state or to a source field. `__phantom` is never set: it only ties the type to `T`.
--- (An alias, not a class: LuaLS does not check a value against a generic class.)
---@alias Ref<T> { ["$ref"]: string, __phantom: T? }

---@class Fn
---@field ["$fn"] string
---@field args any[]

---@alias Expr<T> T|Ref<T>|Fn

---@class Source
---@field ["$source"] string

---@alias RowRefs table<string, Ref<any>>

---@class Actor
---@field name string
---@field kind "user"|"agent"

---@class EventArg<P>
---@field key any
---@field row any
---@field value any
---@field payload P
---@field actor Actor

---@class Action
---@field ["do"] string
---@field [string] any

---@alias Handler<P> fun(e: EventArg<P>)|Action|(Action|fun(e: EventArg<P>))[]

---@class Node
---@field type string
---@field key string?
---@field props table<string, any>?
---@field children Node[]?
---@field slots table<string, Node[]>?
---@field on table<string, any>?

---@alias Child Node|Node[]

"#;

/// `types/generated/luals/vos.lua`: the shared types, the component enums and objects, `ClientDecl` and the `app`
/// API with its global.
pub fn vos_definitions() -> String {
    let mut out = String::from("---@meta\n\n");
    out.push_str(HEADER);
    out.push('\n');
    out.push_str(CORE);
    for (name, def) in named_enums() {
        let _ = writeln!(out, "---@alias {name} {}\n", literals(def.values));
    }
    for (name, def) in named_objects() {
        let _ = writeln!(out, "---@alias {name} {}\n", object_type(def));
    }
    out.push_str(&client_decl());
    out.push_str(APP_API);
    out
}

/// `ClientDecl` and its enums, from the JSON Schema of the Rust types.
fn client_decl() -> String {
    let mut seen = std::collections::BTreeSet::new();
    let schema = serde_json::to_value(schema_for!(ClientDecl)).unwrap_or(serde_json::Value::Null);
    schema_to_lua("ClientDecl", &schema, &mut seen)
}

/// `types/generated/luals/vos/app.lua`: `require("vos:app")` is the global `app`.
pub fn app_module_definitions() -> String {
    format!("---@meta\n\n{HEADER}\nreturn app\n")
}

/// `types/generated/luals/vos/ui.lua`: the `ui` module and every component's props.
pub fn ui_module_definitions() -> String {
    let mut out = String::from("---@meta\n\n");
    out.push_str(HEADER);
    out.push('\n');
    for c in CATALOGUE {
        out.push_str(&props_class(c));
    }
    out.push_str("---@class UI\n---@field act UiActions\n---@field fmt UiFormat\nlocal ui = {}\n\n");
    out.push_str("---@class UiFormat\nlocal fmt = {}\n\n");
    out.push_str(&constructors());
    out.push_str(&helpers());
    out.push_str("return ui\n");
    out
}

/// One field of a props class: its type and whether the author must give it.
struct Field {
    ty: String,
    required: bool,
    doc: &'static str,
}

/// The fields of a props class, in the order they were first put.
#[derive(Default)]
struct Fields {
    by_name: BTreeMap<String, Field>,
    order: Vec<String>,
}

impl Fields {
    fn put(&mut self, name: String, field: Field) {
        if self.by_name.insert(name.clone(), field).is_none() {
            self.order.push(name);
        }
    }
}

fn props_class(c: &ComponentSpec) -> String {
    let mut fields = Fields::default();

    fields.put("key".to_owned(), Field { ty: "string".to_owned(), required: c.interactive, doc: "" });
    for p in effective_props(c) {
        // a positional prop is given as the first entry, so it is never required by name
        let required = p.required && c.positional != Some(p.name);
        fields.put(key(p.name), Field { ty: field_type(p), required, doc: p.doc });
    }
    for e in effective_events(c) {
        fields.put(
            e.prop_name(),
            Field { ty: format!("Handler<{}>", payload_type(e.payload)), required: false, doc: "" },
        );
    }
    // slots: a slot that shares a name with a prop widens that prop's type (a string, or a node)
    let slots = classify(c.effective_slots());
    for slot in &slots.plain {
        let row = slot.scope == Some(SlotScope::Row);
        let slot_ty = if row { "Child|fun(r: RowRefs): Node" } else { "Child" };
        let name = key(slot.name);
        match fields.by_name.get_mut(&name) {
            Some(existing) => {
                existing.ty = format!("{}|{slot_ty}", existing.ty);
                existing.required = false;
            }
            None => fields.put(name, Field { ty: slot_ty.to_owned(), required: slot.required, doc: "" }),
        }
    }
    for (group, members) in &slots.groups {
        let inner: Vec<String> = members
            .iter()
            .map(|m| {
                let (_, sub) = split_group(m.name).unwrap_or(("", m.name));
                format!("{}?: Child", key(sub))
            })
            .collect();
        fields.put(key(group), Field { ty: format!("{{ {} }}", inner.join(", ")), required: false, doc: "" });
    }
    for prefix in &slots.prefixes {
        fields.put(
            key(group_name(prefix.name)),
            Field { ty: "table<string, Child>".to_owned(), required: false, doc: "" },
        );
    }

    let mut out = String::new();
    let _ = writeln!(out, "--- {}", c.doc);
    let _ = writeln!(out, "---@class {}Props", c.name);
    for name in &fields.order {
        let field = &fields.by_name[name];
        let ty = if field.required { field.ty.clone() } else { optional(&field.ty) };
        let doc = field.doc.replace('\n', " ");
        let _ = writeln!(
            out,
            "---@field {name} {ty}{}",
            if doc.is_empty() { String::new() } else { format!(" {doc}") }
        );
    }
    // positional entries
    let positional = c.positional.and_then(|p| c.prop(p));
    let entry = match (positional, c.children) {
        (Some(p), vos_domain::ui::spec::Children::None) => Some(format!("Expr<{}>", value_type(&p.ty))),
        (Some(p), _) => Some(format!("Expr<{}>|Child", value_type(&p.ty))),
        (None, vos_domain::ui::spec::Children::None) => None,
        (None, _) => Some("Child".to_owned()),
    };
    if let Some(entry) = entry {
        let _ = writeln!(out, "---@field [integer] {entry}");
    }
    out.push('\n');
    out
}

fn constructors() -> String {
    let mut out = String::new();
    for c in CATALOGUE {
        let _ = writeln!(out, "{}", describe(c).replacen("-- ", "--- ", 1));
        let _ =
            writeln!(out, "---@param props {0}Props\n---@return Node\nfunction ui.{0}(props) end\n", c.name);
    }
    for (sugar, axis) in STACK_SUGAR {
        let which = if *axis == "v" { "vertical" } else { "horizontal" };
        let _ = writeln!(
            out,
            "--- A {which} `Stack`.\n---@param props StackProps\n---@return Node\nfunction ui.{sugar}(props) end\n"
        );
    }
    out
}

/// Parameters of a function of `arity`: the `---@param` lines and the names for the `function` line.
fn params(arity: Arity) -> (String, String) {
    let names = ["a", "b", "c"];
    match arity.max {
        None => ("---@param first any\n---@param ... any\n".to_owned(), "first, ...".to_owned()),
        Some(max) => {
            let mut lines = String::new();
            for (i, name) in names.iter().enumerate().take(max) {
                let _ = writeln!(lines, "---@param {name}{} any", if i < arity.min { "" } else { "?" });
            }
            (lines, names.iter().take(max).copied().collect::<Vec<_>>().join(", "))
        }
    }
}

fn helpers() -> String {
    let mut out = String::new();
    out.push_str(
        "--- Maps a Lua list to children. `nil` results are skipped.\n\
---@generic T\n\
---@param list T[]\n\
---@param body fun(item: T, index: number): Node?\n\
---@return Node[]\n\
function ui.each(list, body) end\n\n",
    );
    for f in Func::ALL.iter().filter(|f| !f.name().starts_with("fmt.")) {
        let (lines, passed) = params(f.arity());
        let _ = writeln!(
            out,
            "--- {}\n{lines}---@return Fn\nfunction ui.{}({passed}) end\n",
            f.doc(),
            helper_name(*f),
        );
    }
    for f in Func::ALL.iter().filter(|f| f.name().starts_with("fmt.")) {
        let (lines, passed) = params(f.arity());
        let _ = writeln!(
            out,
            "--- {}\n{lines}---@return Fn\nfunction fmt.{}({passed}) end\n",
            f.doc(),
            helper_name(*f),
        );
    }
    out.push_str("ui.fmt = fmt\n\n");
    out.push_str(ACTIONS);
    out
}

const ACTIONS: &str = r#"--- Client actions: run on the client with no round trip. Handlers take one, or a list mixing actions and functions.
---@class UiActions
local act = {}
ui.act = act

--- Write a client-managed or app-state ref.
---@param target Ref<any>|string
---@param value any
---@return Action
function act.set(target, value) end

--- Flip a boolean ref.
---@param target Ref<any>|string
---@return Action
function act.toggle(target) end

--- Push a route (`{ name = "note", id = 7 }`) onto a navigation stack (the optional `stack` names it).
---@param route { name: string, [string]: any }
---@param stack string?
---@return Action
function act.push(route, stack) end

--- Pop the top route.
---@return Action
function act.pop() end

--- Pop to the root screen.
---@return Action
function act.popToRoot() end

--- Move focus to the node with this key.
---@param key string
---@return Action
function act.focus(key) end

--- Scroll to the node with this key.
---@param key string
---@return Action
function act.scrollTo(key) end

--- Copy text to the clipboard.
---@param text Expr<string>
---@return Action
function act.copy(text) end

--- Report an event to the app (the handler of the node still runs on the host).
---@param event string?
---@param payload table<string, any>?
---@return Action
function act.emit(event, payload) end

--- Run actions in order.
---@param actions Action[]
---@return Action
function act.seq(actions) end

"#;

