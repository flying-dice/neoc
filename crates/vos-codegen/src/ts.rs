//! `types/generated/vos.ts`: the wire types of the `/rpc` socket (derived by `ts-rs` from the Rust types, so they
//! cannot drift from the serde shapes), the two version constants and the method table.

use std::fmt::Write as _;

use ts_rs::TS;
use vos_domain::api::{
    AgentGrantsRow, AgentList, AgentRow, AppEvent, AppList, AppPreview, AppState, AppSummary, AppWindow,
    Catalog, DeviceList, DeviceRow, FileEntry, FileEntryKind, FileList, FileLocations, InstalledInfo,
};
use vos_domain::protocol::{
    AppNotification, Direction, Empty, MethodKind, ResumeView, SessionHello, SessionResume, SessionWelcome,
    WindowOpen, METHODS,
};
use vos_domain::{KIT_VERSION, PROTO_VERSION};

fn export(decl: &str) -> String {
    format!("export {decl}\n")
}

/// The whole file.
pub fn generate() -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    let _ = writeln!(out, "export const PROTO_VERSION = {PROTO_VERSION}");
    let _ = writeln!(out, "export const KIT_VERSION = '{KIT_VERSION}'\n");
    out.push_str(&export(&serde_json::Value::decl(&ts_rs::Config::default())));
    out.push_str("\n// ---------------------------------------------------------------------------------------------\n");
    out.push_str("// Protocol (ts-rs)\n");
    out.push_str("// ---------------------------------------------------------------------------------------------\n\n");
    out.push_str(&protocol());
    out.push('\n');
    out.push_str(&methods());
    out
}

const HEADER: &str =
    "// GENERATED by vos-codegen from the Rust domain (crates/vos-domain, `protocol` and `api`). Do not edit.\n\
// Regenerate with `bun run codegen`; `bun run codegen:check` fails when this file is stale.\n\
/* eslint-disable */\n\n";

fn protocol() -> String {
    let cfg = ts_rs::Config::default();
    let mut out = String::new();
    let mut add = |decl: String| out.push_str(&export(&decl));
    add(SessionHello::decl(&cfg));
    add(SessionResume::decl(&cfg));
    add(ResumeView::decl(&cfg));
    add(SessionWelcome::decl(&cfg));
    add(WindowOpen::decl(&cfg));
    add(AppNotification::decl(&cfg));
    add(Empty::decl(&cfg));
    add(AppState::decl(&cfg));
    add(AppWindow::decl(&cfg));
    add(AppSummary::decl(&cfg));
    add(AppList::decl(&cfg));
    add(AppEvent::decl(&cfg));
    add(InstalledInfo::decl(&cfg));
    add(AppPreview::decl(&cfg));
    add(Catalog::decl(&cfg));
    add(DeviceRow::decl(&cfg));
    add(DeviceList::decl(&cfg));
    add(FileEntryKind::decl(&cfg));
    add(FileEntry::decl(&cfg));
    add(FileList::decl(&cfg));
    add(FileLocations::decl(&cfg));
    add(AgentGrantsRow::decl(&cfg));
    add(AgentRow::decl(&cfg));
    add(AgentList::decl(&cfg));
    add(rpc_error());
    out
}

/// The JSON-RPC error object (the envelope itself is hand-written protocol, not derived).
fn rpc_error() -> String {
    "type RpcError = { code: number, message: string, data?: JsonValue }".to_owned()
}

fn methods() -> String {
    let mut out = String::from("/** The JSON-RPC method table: who sends it, and the params and result types. */\nexport interface Methods {\n");
    for m in METHODS {
        let kind = match m.kind {
            MethodKind::Request => "request",
            MethodKind::Notification => "notification",
        };
        let direction = match m.direction {
            Direction::ClientToHost => "clientToHost",
            Direction::HostToClient => "hostToClient",
        };
        let result = m.result.unwrap_or("never");
        let _ = writeln!(
            out,
            "  '{}': {{ kind: '{kind}'; direction: '{direction}'; params: {}; result: {result} }}",
            m.name, m.params
        );
    }
    out.push_str("}\n\nexport type MethodName = keyof Methods\n\n");
    out.push_str("/** Method names by direction, for dispatch tables. */\n");
    let list = |direction| {
        METHODS
            .iter()
            .filter(|m| m.direction == direction)
            .map(|m| format!("'{}'", m.name))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let _ = writeln!(
        out,
        "export const CLIENT_METHODS = [{}] as const\nexport const HOST_METHODS = [{}] as const",
        list(Direction::ClientToHost),
        list(Direction::HostToClient)
    );
    out
}
