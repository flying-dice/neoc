//! `types/generated/vos.d.luau`: the app-facing definitions (see the [module](super) docs for what is in it).

use std::fmt::Write as _;

use schemars::schema_for;
use vos_domain::ui::source::ClientDecl;
use vos_domain::{GLOBALS_NOT_FOR_APPS, NOT_FOR_APPS};

use super::{literals, named, neoc, neoc::Offered, object_type, schema::schema_to_luau, ui};
use crate::walk::{named_enums, named_objects};

const APP_API: &str = include_str!("app_api.luau.tpl");

const HEADER: &str = "-- GENERATED by vos-codegen from the Rust domain (crates/vos-domain, `ui` module) and from\n\
-- types/neoc.d.luau (neoc's declarations of the std:, lib: and vnd: modules). Do not edit.\n\
-- Regenerate with `bun run codegen`; `bun run codegen:check` fails when this file is stale.\n\
--\n\
-- Luau declarations for luau-lsp (`bun run lint:luau`, and editors: a definitions file, `--definitions:@vos=<this\n\
-- file>` of `luau-lsp`, `luau-lsp.types.definitionFiles` in an editor). Never loaded by the host: the runtime module\n\
-- of `vos:ui` is types/generated/ui.lua. What it declares, in this order: the modules an app is offered (neoc's\n\
-- sections, less the modules in NOT_FOR_APPS), then vos's types (`vos_<Name>`), the globals, and the ONE\n\
-- `declare require` (two do not merge) with an overload for every module an app is offered, `vos:app` and\n\
-- `vos:ui`, and an unusable type for each module it is not.\n\n";

/// The types the host and the constructors share.
const CORE: &str = r#"-- ===== vos =====
-- The types the host and the constructors share.

--- A reference to client or app state or to a source field. `__phantom` is never set: it only ties the type to `T`.
export type vos_Ref<T> = { ["$ref"]: string, __phantom: T? }

export type vos_Fn = { ["$fn"]: string, args: { any } }

export type vos_Expr<T> = T | vos_Ref<T> | vos_Fn

export type vos_Source = { ["$source"]: string }

export type vos_RowRefs = { [string]: vos_Ref<any> }

export type vos_Actor = { name: string, kind: "user" | "agent" }

export type vos_EventArg<P> = { key: any, row: any, value: any, payload: P, actor: vos_Actor }

export type vos_Action = { ["do"]: string, [string]: any }

export type vos_Handler<P> = ((vos_EventArg<P>) -> ()) | vos_Action | { vos_Action | ((vos_EventArg<P>) -> ()) }

export type vos_Node = {
	type: string,
	key: string?,
	props: { [string]: any }?,
	children: { vos_Node }?,
	slots: { [string]: { vos_Node } }?,
	on: { [string]: any }?,
}

export type vos_Child = vos_Node | { vos_Node }

"#;

/// The type an unusable name has: a table with nothing in it, so the first use is a type error that names it.
fn not_for_apps_type(name: &str) -> String {
    named(&format!("NotForApps_{}", name.replace(':', "_")))
}

/// `ClientDecl` and its enums, from the JSON Schema of the Rust types.
fn client_decl() -> String {
    let mut seen = std::collections::BTreeSet::new();
    let schema = serde_json::to_value(schema_for!(ClientDecl)).unwrap_or(serde_json::Value::Null);
    schema_to_luau("ClientDecl", &schema, &mut seen)
}

/// The declarations vos adds to what neoc offers: its types, the app API and the `ui` module.
fn vos_declarations() -> String {
    let mut out = String::from(CORE);
    for (name, def) in named_enums() {
        let _ = writeln!(out, "export type {} = {}\n", named(name), literals(def.values));
    }
    for (name, def) in named_objects() {
        let _ = writeln!(out, "export type {} = {}\n", named(name), object_type(def));
    }
    out.push_str(&client_decl());
    out.push_str(APP_API);
    out.push_str(&ui::declarations());
    out
}

/// The modules and globals an app is not given, as types no value can be used through.
fn unusable(offered: &Offered) -> String {
    let mut out = String::from(
        "-- ===== not for apps =====\n\
-- A module in NOT_FOR_APPS (the Lua adapter refuses it when it runs) and a global the app's environment does not\n\
-- have are declared as a table with one `never` field: the first use of one is a type error naming it.\n\n",
    );
    for module in &offered.refused {
        let _ = writeln!(
            out,
            "--- `{module}` is not offered to apps.\nexport type {} = {{ __not_for_apps: never }}\n",
            not_for_apps_type(module)
        );
    }
    for global in GLOBALS_NOT_FOR_APPS {
        let _ = writeln!(
            out,
            "--- `{global}` does not exist in an app's environment.\nexport type {} = {{ __not_for_apps: never }}\n",
            not_for_apps_type(global)
        );
    }
    out
}

fn globals() -> String {
    let mut out = String::from("-- ===== globals =====\n\n");
    let _ = writeln!(
        out,
        "--- The `app` API, the same as `require(\"vos:app\")`.\ndeclare app: {}\n",
        named("AppApi")
    );
    for global in GLOBALS_NOT_FOR_APPS {
        let _ = writeln!(out, "declare {global}: {}", not_for_apps_type(global));
    }
    out.push('\n');
    out
}

/// The one `declare require`: the offered modules, the two `vos:` ones, the refused modules (typed unusable), and
/// last `(path: string) -> any` for an app's own bundled modules (`require("./calc")`).
///
/// Why that last overload: luau-lsp resolves a relative `require` to the file's type only while `require` is the
/// built-in one, and a `declare require` replaces it (an intersection with `typeof(require)` brings the resolution
/// back for every call, and then fails every `vos:` and `std:` name as an unknown file). So a bundled module's
/// type is `any` here, and `bun run lint:luau` checks the module names a `require` uses (see scripts/lint-luau.ts)
/// where the types cannot.
fn require(offered: &Offered) -> String {
    let mut lines: Vec<String> =
        offered.overloads.iter().map(|(module, ty)| format!("((path: \"{module}\") -> {ty})")).collect();
    lines.push(format!("((path: \"vos:app\") -> {})", named("AppApi")));
    lines.push(format!("((path: \"vos:ui\") -> {})", named("ui")));
    lines.extend(
        offered
            .refused
            .iter()
            .map(|module| format!("((path: \"{module}\") -> {})", not_for_apps_type(module))),
    );
    lines.push("((path: string) -> any)".to_owned());
    format!("-- ===== require =====\n\ndeclare require: \n\t{}\n", lines.join("\n\t& "))
}

/// The whole file, from neoc's declarations.
///
/// # Errors
/// neoc's file does not have the shape [`neoc::offered`] reads.
pub fn definitions(neoc_declarations: &str) -> Result<String, String> {
    let offered = neoc::offered(neoc_declarations, NOT_FOR_APPS)?;
    let mut out = String::from(HEADER);
    out.push_str(&offered.sections);
    out.push_str(&vos_declarations());
    out.push_str(&unusable(&offered));
    out.push_str(&globals());
    out.push_str(&require(&offered));
    Ok(out)
}

/// The `(module, type)` of every `require` overload of a generated file, in order: what the Lua adapter's tests and
/// `bun run lint:luau` hold to the modules the host offers.
#[must_use]
pub fn require_overloads(definitions: &str) -> Vec<(String, String)> {
    let start = definitions.find("declare require:").unwrap_or(definitions.len());
    definitions[start..].lines().skip(1).filter_map(neoc::overload).collect()
}
